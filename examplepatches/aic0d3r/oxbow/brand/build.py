"""Oxbow brand assets. Single source of truth: edit geometry here, then run
`python3 brand/build.py` (needs rsvg-convert + magick) to regenerate every export.

The mark: a lake (ring) cut off by a river that has moved on. The cut is a mask, so the
mark keeps a real gap on any background.
"""
import math, os, re, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DARK, LIGHT = "#0E0E0E", "#F4F4F4"  # DESIGN.md SURFACE / ON_SURFACE

# ---- mark geometry (512 grid, optically centred) ---------------------------------------
# Centred on (256,256): the farthest point (river cap) is ~221 from centre.
RING = dict(cx=219, cy=219, r=118, w=52)
RIVER = "M135 423 C231 371 311 331 423 139"
RIVER_W, GAP = 30, 24  # river stroke; clearance between river and the cut ring ends


# Adaptive icon: the mark's 221-unit reach must sit inside the 33dp safe radius of a 108dp
# canvas: 33/108 * 512 / 221 = 0.708 of the 512 grid per 108dp.
ADAPTIVE_SCALE = 0.70


def _river_points(n=400):
    nums = [float(v) for v in re.findall(r"-?\d+\.?\d*", RIVER)]
    p0, rest = (nums[0], nums[1]), nums[2:]
    pts = [p0]
    for i in range(0, len(rest), 6):
        c1, c2, p1 = rest[i:i + 2], rest[i + 2:i + 4], rest[i + 4:i + 6]
        for k in range(1, n + 1):
            t = k / n; u = 1 - t
            pts.append(tuple(u**3 * p0[j] + 3 * u * u * t * c1[j] + 3 * u * t * t * c2[j] + t**3 * p1[j]
                             for j in (0, 1)))
        p0 = tuple(p1)
    return pts


def _dist(p, pts):
    best = 1e9
    for a, b in zip(pts, pts[1:]):
        dx, dy = b[0] - a[0], b[1] - a[1]
        t = max(0, min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy)))
        best = min(best, math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy))
    return best


def _cut(radius, pts, clear):
    """(enter, leave) angles in degrees where a circle of this radius crosses the river's
    clearance band."""
    cx, cy = RING["cx"], RING["cy"]
    inside = lambda a: _dist((cx + radius * math.cos(math.radians(a)),
                              cy + radius * math.sin(math.radians(a))), pts) < clear

    def edge(lo, hi):
        flo = inside(lo)
        for _ in range(40):
            mid = (lo + hi) / 2
            if inside(mid) == flo: lo = mid
            else: hi = mid
        return (lo + hi) / 2

    steps = [i * 0.5 for i in range(721)]
    flags = [inside(a) for a in steps]
    enter = [edge(steps[i], steps[i + 1]) for i in range(720) if not flags[i] and flags[i + 1]]
    leave = [edge(steps[i], steps[i + 1]) for i in range(720) if flags[i] and not flags[i + 1]]
    assert len(enter) == 1 and len(leave) == 1, "river must cut the ring exactly once"
    return enter[0], leave[0]


def ring_path():
    """The lake: the ring with the river's band cut out, as one filled outline (works in SVG
    and Android VectorDrawable, which has no masks)."""
    cx, cy, r, w = RING["cx"], RING["cy"], RING["r"], RING["w"]
    pts, clear = _river_points(), RIVER_W / 2 + GAP
    ro, ri = r + w / 2, r - w / 2
    o_enter, o_leave = _cut(ro, pts, clear)
    i_enter, i_leave = _cut(ri, pts, clear)
    # walk clockwise from where the band ends to where it begins: outer forward, inner back
    a0, a1 = o_leave, o_enter + (360 if o_enter < o_leave else 0)
    b1, b0 = i_enter + (360 if i_enter < i_leave else 0), i_leave
    P = lambda R, a: f"{cx + R * math.cos(math.radians(a)):.2f} {cy + R * math.sin(math.radians(a)):.2f}"
    return (f"M{P(ro, a0)} A{ro} {ro} 0 {int(a1 - a0 > 180)} 1 {P(ro, a1)} "
            f"L{P(ri, b1)} A{ri} {ri} 0 {int(b1 - b0 > 180)} 0 {P(ri, b0)} Z")


RING_D = ring_path()


def mark(fg):
    """The mark's shapes in fg on a 512 grid, no background."""
    return (f'<path d="{RING_D}" fill="{fg}"/>'
            f'<path d="{RIVER}" fill="none" stroke="{fg}" stroke-width="{RIVER_W}" stroke-linecap="round"/>')


def vector_drawable(color="#FFFFFFFF"):
    """Android adaptive-icon foreground: 108dp, mark scaled into the 66dp safe zone."""
    s = ADAPTIVE_SCALE
    off = (512 / s - 512) / 2  # viewport 512/s wide, mark centred
    vp = 512 / s
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by brand/build.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="{vp:.2f}" android:viewportHeight="{vp:.2f}">
    <group android:translateX="{off:.2f}" android:translateY="{off:.2f}">
        <path android:fillColor="{color}" android:pathData="{RING_D}"/>
        <path android:strokeColor="{color}" android:strokeWidth="{RIVER_W}"
            android:strokeLineCap="round" android:pathData="{RIVER}"/>
    </group>
</vector>
'''


def svg(w, h, body, vb=None):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
            f'viewBox="{vb or f"0 0 {w} {h}"}">{body}</svg>\n')


def icon(rx=112):
    """App tile: mark on the dark surface. rx=0 for platforms that round it themselves."""
    return svg(512, 512, f'<rect width="512" height="512" rx="{rx}" fill="{DARK}"/>' + mark(LIGHT))


def adaptive_fg(fg=LIGHT):
    """Android adaptive-icon foreground, 108dp canvas: mark scaled into the 66dp safe zone."""
    s = ADAPTIVE_SCALE * 432 / 512  # same proportions as the VectorDrawable
    off = (432 - 512 * s) / 2
    return svg(432, 432, f'<g transform="translate({off:.2f} {off:.2f}) scale({s})">{mark(fg)}</g>')


# ---- wordmark: lowercase geometric monoline, drawn (no font dependency) ----------------
XH, SW, TRACK = 120, 28, 24  # x-height, stroke, gap between letters


def wordmark_paths(fg):
    r = (XH - SW) / 2  # bowl radius on stroke centre
    cy = -XH / 2
    parts, x = [], 0.0
    st = f'fill="none" stroke="{fg}" stroke-width="{SW}" stroke-linecap="round" stroke-linejoin="round"'

    def o():
        nonlocal x
        parts.append(f'<circle cx="{x + XH / 2:.1f}" cy="{cy}" r="{r}" {st}/>')
        x += XH + TRACK

    def xx():
        nonlocal x
        a, b, w = x + SW / 2, -XH + SW / 2, 96
        parts.append(f'<path d="M{a} {b} L{a + w - SW} {-SW / 2} M{a + w - SW} {b} L{a} {-SW / 2}" {st}/>')
        x += w + TRACK

    def b():
        nonlocal x
        stem = x + SW / 2
        parts.append(f'<path d="M{stem} {-XH * 1.62 + SW / 2} L{stem} {cy}" {st}/>')
        parts.append(f'<circle cx="{stem + r:.1f}" cy="{cy}" r="{r}" {st}/>')
        x += XH + TRACK

    def w():
        nonlocal x
        t, bt, step = -XH + SW / 2, -SW / 2, 36
        a = x + SW / 2
        parts.append(f'<path d="M{a} {t} L{a + step} {bt} L{a + 2 * step} {t + 30} '
                     f'L{a + 3 * step} {bt} L{a + 4 * step} {t}" {st}/>')
        x += 4 * step + SW

    for f in (o, xx, b, o, w):
        f()
    return "".join(parts), x


def wordmark(fg):
    body, width = wordmark_paths(fg)
    top = XH * 1.62
    return svg(round(width), round(top), f'<g transform="translate(0 {top})">{body}</g>')


def lockup(fg, tile=False):
    """Mark + wordmark side by side; height 512 grid."""
    body, width = wordmark_paths(fg)
    scale = 1.55
    gap = 40
    mark_svg = (f'<rect width="512" height="512" rx="112" fill="{DARK}"/>' + mark(LIGHT)) if tile else mark(fg)
    total = 512 + gap + width * scale
    # x-height centred on the mark's optical centre (ring + river span ~86..453)
    ty = 270 + XH * scale / 2
    return svg(round(total), 512,
               mark_svg + f'<g transform="translate({512 + gap} {ty:.1f}) scale({scale})">{body}</g>')


def social_preview():
    """GitHub social preview, 1280x640. Tagline uses the system sans (rendered to PNG here)."""
    body, width = wordmark_paths(LIGHT)
    ws = 0.82  # wordmark ~ 590 wide, ascender 160 tall
    mx, my, ms = 140, 196, 248 / 512
    tx = mx + 248 + 64
    sans = "Roboto, 'Noto Sans', sans-serif"
    return svg(1280, 640,
               f'<rect width="1280" height="640" fill="{DARK}"/>'
               f'<g transform="translate({mx} {my}) scale({ms})">'
               f'<rect width="512" height="512" rx="112" fill="#1B1B1B"/>{mark(LIGHT)}</g>'
               f'<g transform="translate({tx} {my + 132}) scale({ws})">{body}</g>'
               f'<text x="{tx}" y="{my + 196}" font-family="{sans}" font-size="38" fill="#ABABAB">'
               f'Instagram, cut off from the current.</text>'
               f'<text x="{tx}" y="{my + 242}" font-family="{sans}" font-size="26" fill="#757575">'
               f'No feed, Reels or ads. Free and open source, for Android.</text>')


def write(rel, text):
    p = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w").write(text)
    return p


def png(src, dst, w, h=None):
    dst = os.path.join(ROOT, dst)
    args = ["rsvg-convert", "-w", str(w)] + (["-h", str(h)] if h else []) + [src, "-o", dst]
    subprocess.run(args, check=True)
    return dst


