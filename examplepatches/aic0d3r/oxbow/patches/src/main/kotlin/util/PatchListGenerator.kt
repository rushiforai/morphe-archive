/*
 * Adapted from the Morphe patches template (https://github.com/MorpheApp/morphe-patches-template)
 * for morphe-patcher 1.5 (no category / form factor). Writes ../patches-list.json, which Morphe
 * Manager and the patch registries read to list a source's patches.
 */

package util

import app.morphe.patcher.patch.Patch
import app.morphe.patcher.patch.loadPatchesFromJar
import com.google.gson.GsonBuilder
import com.google.gson.JsonObject
import java.io.File

fun main(args: Array<String>) {
    val version = args.firstOrNull() ?: error("usage: PatchListGenerator <version>")
    val bundle = File("build/libs/").listFiles { file ->
        file.name.endsWith(".mpp") && !file.name.contains("javadoc") && !file.name.contains("sources")
    }!!.maxBy { it.lastModified() }
    @Suppress("UNCHECKED_CAST")
    val patches = loadPatchesFromJar(setOf(bundle)) as Set<Patch<*>>

    val list = patches.filter { it.name != null }.sortedBy { it.name }.map { patch ->
        mapOf(
            "name" to patch.name,
            "description" to patch.description,
            "default" to patch.default,
            "compatiblePackages" to patch.compatibility?.map { compat ->
                mapOf(
                    "packageName" to compat.packageName,
                    "name" to compat.name,
                    "description" to compat.description,
                    "apkFileType" to compat.apkFileType?.name,
                    "appIconColor" to compat.appIconColor?.let { "#%06X".format(it) },
                    "signatures" to compat.signatures,
                    "targets" to compat.targets.map { target ->
                        mapOf(
                            "version" to target.version,
                            "versionCodes" to target.versionCodes?.mapKeys { it.key.name },
                            "isExperimental" to target.isExperimental,
                            "minSdk" to target.minSdk,
                            "description" to target.description,
                        )
                    },
                )
            },
            "options" to patch.options.values.map { option ->
                mapOf(
                    "key" to option.key,
                    "title" to option.title,
                    "description" to option.description,
                    "required" to option.required,
                    "type" to option.type.toString(),
                    "default" to option.default,
                    "values" to option.values,
                )
            },
        )
    }

    val gson = GsonBuilder().serializeNulls().disableHtmlEscaping().setPrettyPrinting().create()
    val json = JsonObject()
    json.addProperty("NOTE", "Generated by release.sh. Do not edit by hand.")
    json.addProperty("version", version)
    json.add("patches", gson.toJsonTree(list))
    File("../patches-list.json").writeText(gson.toJson(json) + "\n")
    println("patches-list.json: ${list.size} patches, version $version")
}
