package app.danielthemaniel.patches.campfire.extension;

/**
 * Keeps Campfire's real-time chat alive.
 *
 * Live chat messages arrive over Niantic's push gateway WebSocket
 * (wss://pushgateway-*.nianticlabs.com/mf/ws?pg-token=...). The app's own client retries a dropped
 * connection at most twice and then gives up, and Android routinely kills sockets of
 * backgrounded/sleeping apps — leaving an open chat on a dead socket until it's re-entered.
 *
 * This replaces window.WebSocket (before any app script runs, via Capacitor's injected script)
 * with a wrapper that, for push gateway sockets only:
 *   - hides unexpected drops from the app and reconnects with backoff (0.5 s .. 30 s, 10 tries),
 *   - replays every topic subscription the app sent (Upstream frames with field 3) on reconnect,
 *   - reconnects immediately when the app returns from background (>15 s) or the network returns.
 * App-initiated close() and a failing first connection behave exactly like a native WebSocket.
 * Look for "[MorphePushGateway]" in the WebView console to see it work.
 */
@SuppressWarnings("unused")
public final class LiveChat {
    private LiveChat() {}

    private static final String SCRIPT =
            "(function () {\n"
            + "  if (window.__morphePushGateway) return;\n"
            + "  var Native = window.WebSocket;\n"
            + "  if (!Native) return;\n"
            + "  var TAG = '[MorphePushGateway]';\n"
            + "  var live = new Set();\n"
            + "  window.__morphePushGateway = live;\n"
            + "\n"
            + "  function bytes(data) {\n"
            + "    if (data instanceof ArrayBuffer) return new Uint8Array(data);\n"
            + "    if (ArrayBuffer.isView(data)) return new Uint8Array(data.buffer, data.byteOffset, data.byteLength);\n"
            + "    return null;\n"
            + "  }\n"
            + "  // nia.pushgateway.Upstream: 1 requestId (varint), 3 subscribe, 4 probe.\n"
            + "  function isSubscribe(data) {\n"
            + "    var b = bytes(data);\n"
            + "    if (!b || b[0] !== 0x08) return false;\n"
            + "    var i = 1;\n"
            + "    while (i < b.length && (b[i] & 0x80)) i++;\n"
            + "    return b[i + 1] === 0x1a;\n"
            + "  }\n"
            + "  function copy(data) {\n"
            + "    var b = bytes(data);\n"
            + "    return b ? b.slice().buffer : data;\n"
            + "  }\n"
            + "\n"
            + "  function Resilient(url, protocols) {\n"
            + "    this.url = url;\n"
            + "    this._protocols = protocols;\n"
            + "    this._listeners = { open: [], message: [], close: [], error: [] };\n"
            + "    this._subs = [];\n"
            + "    this._queue = [];\n"
            + "    this._closedByApp = false;\n"
            + "    this._everOpen = false;\n"
            + "    this._attempt = 0;\n"
            + "    this._timer = null;\n"
            + "    this._ws = null;\n"
            + "    this._binaryType = 'blob';\n"
            + "    this.onopen = this.onmessage = this.onclose = this.onerror = null;\n"
            + "    this.readyState = 0;\n"
            + "    this.protocol = '';\n"
            + "    this.extensions = '';\n"
            + "    this.bufferedAmount = 0;\n"
            + "    live.add(this);\n"
            + "    this._connect();\n"
            + "  }\n"
            + "  var P = Resilient.prototype;\n"
            + "  P.CONNECTING = 0; P.OPEN = 1; P.CLOSING = 2; P.CLOSED = 3;\n"
            + "\n"
            + "  Object.defineProperty(P, 'binaryType', {\n"
            + "    get: function () { return this._binaryType; },\n"
            + "    set: function (v) { this._binaryType = v; if (this._ws) this._ws.binaryType = v; }\n"
            + "  });\n"
            + "\n"
            + "  P._emit = function (type, ev) {\n"
            + "    var self = this;\n"
            + "    var h = this['on' + type];\n"
            + "    try { if (h) h.call(this, ev); } catch (e) { console.error(e); }\n"
            + "    this._listeners[type].slice().forEach(function (l) {\n"
            + "      try { (typeof l === 'function' ? l : l.handleEvent).call(self, ev); } catch (e) { console.error(e); }\n"
            + "    });\n"
            + "  };\n"
            + "\n"
            + "  P._connect = function () {\n"
            + "    var self = this;\n"
            + "    clearTimeout(this._timer);\n"
            + "    this._timer = null;\n"
            + "    var ws;\n"
            + "    try {\n"
            + "      ws = this._protocols !== undefined ? new Native(this.url, this._protocols) : new Native(this.url);\n"
            + "    } catch (e) {\n"
            + "      return this._onDrop({ code: 1006 });\n"
            + "    }\n"
            + "    ws.binaryType = this._binaryType;\n"
            + "    this._ws = ws;\n"
            + "\n"
            + "    ws.onopen = function () {\n"
            + "      if (self._ws !== ws) return;\n"
            + "      var first = !self._everOpen;\n"
            + "      self._everOpen = true;\n"
            + "      self._attempt = 0;\n"
            + "      self.readyState = 1;\n"
            + "      if (!first) {\n"
            + "        console.log(TAG, 'reconnected, replaying', self._subs.length, 'subscription(s)');\n"
            + "        self._subs.forEach(function (f) { ws.send(f); });\n"
            + "      }\n"
            + "      var q = self._queue;\n"
            + "      self._queue = [];\n"
            + "      q.forEach(function (f) { ws.send(f); });\n"
            + "      if (first) self._emit('open', { type: 'open', target: self });\n"
            + "    };\n"
            + "    ws.onmessage = function (ev) {\n"
            + "      if (self._ws !== ws) return;\n"
            + "      self._emit('message', { type: 'message', data: ev.data, target: self });\n"
            + "    };\n"
            + "    ws.onerror = function () {};\n"
            + "    ws.onclose = function (ev) {\n"
            + "      if (self._ws !== ws) return;\n"
            + "      self._ws = null;\n"
            + "      if (self._closedByApp) {\n"
            + "        self.readyState = 3;\n"
            + "        live.delete(self);\n"
            + "        self._emit('close', { type: 'close', code: ev.code, reason: ev.reason, wasClean: ev.wasClean, target: self });\n"
            + "        return;\n"
            + "      }\n"
            + "      if (!self._everOpen) {\n"
            + "        // First connection failed: behave exactly like a native socket.\n"
            + "        self.readyState = 3;\n"
            + "        live.delete(self);\n"
            + "        self._emit('error', { type: 'error', target: self });\n"
            + "        self._emit('close', { type: 'close', code: ev.code, reason: ev.reason, wasClean: ev.wasClean, target: self });\n"
            + "        return;\n"
            + "      }\n"
            + "      self._onDrop(ev);\n"
            + "    };\n"
            + "  };\n"
            + "\n"
            + "  // Unexpected drop of an established connection: reconnect quietly, keep the app's view \"open\".\n"
            + "  P._onDrop = function (ev) {\n"
            + "    var self = this;\n"
            + "    this._attempt++;\n"
            + "    if (this._attempt > 10) {\n"
            + "      console.warn(TAG, 'giving up after', this._attempt - 1, 'attempts');\n"
            + "      this.readyState = 3;\n"
            + "      live.delete(this);\n"
            + "      this._emit('close', { type: 'close', code: (ev && ev.code) || 1006, reason: '', wasClean: false, target: this });\n"
            + "      return;\n"
            + "    }\n"
            + "    var delay = Math.min(30000, 500 * Math.pow(2, this._attempt - 1));\n"
            + "    console.log(TAG, 'connection dropped (code ' + (ev && ev.code) + '), reconnecting in', delay, 'ms');\n"
            + "    this.readyState = 1;\n"
            + "    this._timer = setTimeout(function () { self._connect(); }, delay);\n"
            + "  };\n"
            + "\n"
            + "  // Reconnect now: after returning from background (the socket may be silently dead) or when\n"
            + "  // the network comes back while a retry is pending.\n"
            + "  P._reconnectNow = function (reason) {\n"
            + "    if (this._closedByApp || !this._everOpen) return;\n"
            + "    console.log(TAG, 'reconnecting now:', reason);\n"
            + "    var old = this._ws;\n"
            + "    this._ws = null;\n"
            + "    if (old) { try { old.close(); } catch (e) {} }\n"
            + "    this._attempt = 0;\n"
            + "    this._connect();\n"
            + "  };\n"
            + "\n"
            + "  P.send = function (data) {\n"
            + "    if (this._closedByApp) return;\n"
            + "    var sub = isSubscribe(data);\n"
            + "    var frame = copy(data);\n"
            + "    if (sub) this._subs.push(frame);\n"
            + "    if (this._ws && this._ws.readyState === 1) {\n"
            + "      this._ws.send(data);\n"
            + "    } else if (!this._everOpen) {\n"
            + "      this._queue.push(frame);\n"
            + "    }\n"
            + "    // While reconnecting: subscriptions are replayed on reconnect; stale probe replies are dropped.\n"
            + "  };\n"
            + "\n"
            + "  P.close = function (code, reason) {\n"
            + "    var self = this;\n"
            + "    if (this._closedByApp) return;\n"
            + "    this._closedByApp = true;\n"
            + "    clearTimeout(this._timer);\n"
            + "    this.readyState = 2;\n"
            + "    if (this._ws) {\n"
            + "      try { this._ws.close(code, reason); } catch (e) {}\n"
            + "    } else {\n"
            + "      this.readyState = 3;\n"
            + "      live.delete(this);\n"
            + "      setTimeout(function () {\n"
            + "        self._emit('close', { type: 'close', code: code || 1000, reason: reason || '', wasClean: true, target: self });\n"
            + "      }, 0);\n"
            + "    }\n"
            + "  };\n"
            + "\n"
            + "  P.addEventListener = function (type, l) {\n"
            + "    var a = this._listeners[type];\n"
            + "    if (a && l && a.indexOf(l) === -1) a.push(l);\n"
            + "  };\n"
            + "  P.removeEventListener = function (type, l) {\n"
            + "    var a = this._listeners[type];\n"
            + "    if (!a) return;\n"
            + "    var i = a.indexOf(l);\n"
            + "    if (i !== -1) a.splice(i, 1);\n"
            + "  };\n"
            + "  P.dispatchEvent = function () { return true; };\n"
            + "\n"
            + "  function WebSocket(url, protocols) {\n"
            + "    if (typeof url === 'string' && url.indexOf('pushgateway') !== -1 && url.indexOf('pg-token=') !== -1) {\n"
            + "      return new Resilient(url, protocols);\n"
            + "    }\n"
            + "    return protocols !== undefined ? new Native(url, protocols) : new Native(url);\n"
            + "  }\n"
            + "  WebSocket.prototype = Native.prototype;\n"
            + "  WebSocket.CONNECTING = 0; WebSocket.OPEN = 1; WebSocket.CLOSING = 2; WebSocket.CLOSED = 3;\n"
            + "  window.WebSocket = WebSocket;\n"
            + "\n"
            + "  var hiddenAt = 0;\n"
            + "  document.addEventListener('visibilitychange', function () {\n"
            + "    if (document.visibilityState === 'hidden') {\n"
            + "      hiddenAt = Date.now();\n"
            + "    } else if (hiddenAt && Date.now() - hiddenAt > 15000) {\n"
            + "      hiddenAt = 0;\n"
            + "      live.forEach(function (s) { s._reconnectNow('back from background'); });\n"
            + "    }\n"
            + "  });\n"
            + "  window.addEventListener('online', function () {\n"
            + "    live.forEach(function (s) { if (s._timer) s._reconnectNow('network online'); });\n"
            + "  });\n"
            + "})();\n";

    /** Called on every return of JSInjector.getScriptString(). Never throws. */
    public static String appendScript(String script) {
        return script + "\n\n" + SCRIPT;
    }
}
