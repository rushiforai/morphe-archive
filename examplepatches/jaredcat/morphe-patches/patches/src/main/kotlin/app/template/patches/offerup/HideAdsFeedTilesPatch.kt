/**
 * OfferUp home-feed ads are GraphQL modular tiles in the Hermes v98 bundle.
 *
 * Nulling a renderer leaves an empty 2-column cell, so ads are removed from the
 * tile arrays before `processAllItems` packs them:
 * 1. `tiles.map(dropAd).filter(identity)` — drop when lowercased `tileType`
 *    starts with `"ad"` or equals `banner` / `empty_state` (wire values are
 *    `AD_3P_*` / `BANNER`, not PascalCase).
 * 2. Skip module `feedIndex` splices so compacted listings are not re-gapped.
 * 3. `keepTile` filters FeedProvider / module-grid `.filter` calls the same way.
 *
 * Also nulls listing-page / Inbox / promo renderers (`InboxAd`, `GoogleBannerAd`,
 * `OUGoogleAd`, custom-native, Premium bar, ItemDetail ads). Does not unlock
 * Premium IAP. Signatures are unique prefixes in OfferUp 2026.38.0.
 */
internal val hideAdsFeedTilesPatch = rawResourcePatch {
    compatibleWith(COMPATIBILITY_OFFERUP)

    execute {
        val bundlePath = "assets/index.android.bundle"
        val bundle = get(bundlePath)
        if (!bundle.exists()) {
            throw PatchException(
                "$bundlePath missing. Use merged/base APKs that include the Hermes bundle.",
            )
        }

        val bytes = bundle.readBytes()
        if (bytes.size < HERMES_FOOTER_SIZE) {
            throw PatchException("$bundlePath is too small to be a valid Hermes bundle.")
        }

        for ((label, signature) in FEED_TILE_SIGNATURES) {
            val at = bytes.findUnique(signature, label) ?: throw PatchException(
                "$label signature not found in $bundlePath. " +
                    "This patch only supports OfferUp 2026.38.0 (Hermes v98).",
            )
            RETURN_NULL.copyInto(bytes, destinationOffset = at)
        }

        for ((label, signature, body, size) in FEED_ARRAY_REWRITES) {
            val at = bytes.findUnique(signature, label) ?: throw PatchException(
                "$label signature not found in $bundlePath. " +
                    "This patch only supports OfferUp 2026.38.0 (Hermes v98).",
            )
            if (body.size > size) {
                throw PatchException("$label rewrite is larger than the original function.")
            }
            body.copyInto(bytes, destinationOffset = at)
            if (body.size < size) {
                java.util.Arrays.fill(bytes, at + body.size, at + size, NOP)
            }
        }

        val footerAt = bytes.size - HERMES_FOOTER_SIZE
        val digest = MessageDigest.getInstance("SHA-1").digest(bytes.copyOf(footerAt))
        digest.copyInto(bytes, destinationOffset = footerAt)

        bundle.writeBytes(bytes)
    }
}

private const val HERMES_FOOTER_SIZE = 20

/** Hermes v98: LoadConstNull r0; Ret r0. */
