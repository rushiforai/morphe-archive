/*
 * The Related posts list under a post, with its "Titles are generated by AI from Meta" line (#231).
 * Read from 584, 2026-10-24; the obfuscated names are for reviewers, the code never writes one down.
 *
 * It's a plugin of the socket under a post's buttons ([POST_SOCKET]), the one Meta AI's inline
 * comment summary goes through: the socket's name table (584 LX/228;->A0k) names it with the
 * summary, and the socket asks the same per-plugin check whether it applies. The hook goes first in
 * that check, like the summary's, and while the switch is on the Related posts plugin gets a no, so
 * the socket goes on to the next plugin. Both hooks can sit in the check, each asking only about its
 * own plugin.
 */

private const val PATCH = "Hide suggested and promoted posts"

/** The Related posts plugin under a post's buttons, a kept class name the socket's name table loads. */
internal const val RELATED_POSTS =
    "com.facebook.feed.plugins.belowufifooter.impl.inlinerelatedposts.InlineRelatedPostsPlugin"

internal const val HOLDS_RELATED_POSTS = "$EXTENSION_PACKAGE/feed/RelatedPosts;->holds(Ljava/lang/String;)Z"

/** Hooks the check of the socket under a post's buttons, so the Related posts plugin can be left out. */
internal fun BytecodePatchContext.hookRelatedPosts() {
    val socket = pluginSocket(POST_SOCKET, RELATED_POSTS, patch = PATCH)
    mutableClassDefBy(socket.check.definingClass).methods.single { it.descriptor() == socket.check.descriptor() }
        .holdSummaries(socket.table, HOLDS_RELATED_POSTS, PATCH)
}
