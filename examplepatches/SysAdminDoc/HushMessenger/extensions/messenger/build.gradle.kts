/**
 * Writes NOTICE into a Java constant, so Source and licenses shows exactly the file the repository ships. Morphe's
 * section 7b notice has to reach the person using the app, and a hand-kept copy would drift from NOTICE the first
 * time either changed.
 */
abstract class GenerateLicenseNotice : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val notice: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val text = notice.get().asFile.readText(Charsets.UTF_8).replace("\r\n", "\n")
        val literal = buildString {
            for (ch in text) {
                when (ch) {
                    '\\' -> append("\\\\")
                    '"' -> append("\\\"")
                    '\n' -> append("\\n")
                    else -> if (ch.code < 0x20 || ch.code > 0x7e) append("\\u%04x".format(ch.code)) else append(ch)
                }
            }
        }
        val directory = outputDir.get().asFile.resolve("app/hushmessenger/extension")
        directory.mkdirs()
        directory.resolve("LicenseNotice.java").writeText(
            "package app.hushmessenger.extension;\n\n" +
                "/** Generated from NOTICE by :extensions:messenger:generateLicenseNotice. Do not edit. */\n" +
                "final class LicenseNotice {\n" +
                "    static final String TEXT = \"$literal\";\n\n" +
                "    private LicenseNotice() {\n    }\n}\n",
            Charsets.UTF_8,
        )
    }
}

val generateLicenseNotice = tasks.register<GenerateLicenseNotice>("generateLicenseNotice") {
    notice.set(rootProject.layout.projectDirectory.file("NOTICE"))
    outputDir.set(layout.buildDirectory.dir("generated/source/licenseNotice"))
}

/**
 * Writes the public key the bundle is signed with into a Java constant, empty for an unsigned build, so a problem report
 * can tell the official bundle from a fork's that carries the same version number. Only the public key is an input.
 */
abstract class GenerateBundleKey : DefaultTask() {
    @get:Input
    abstract val signedKey: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val key = signedKey.get()
        if (!key.matches(Regex("[A-Za-z0-9+/=]*"))) throw GradleException("morphe-signing.pub isn't a Base64 key")
        val directory = outputDir.get().asFile.resolve("app/hushmessenger/extension")
        directory.mkdirs()
        directory.resolve("BundleKey.java").writeText(
            "package app.hushmessenger.extension;\n\n" +
                "/** Generated by :extensions:messenger:generateBundleKey. Do not edit. */\n" +
                "final class BundleKey {\n" +
                "    /** The public key :patches:buildAndroid signs this bundle with, or empty when it isn't signed. */\n" +
                "    static final String SIGNED = \"$key\";\n\n" +
                "    private BundleKey() {\n    }\n}\n",
            Charsets.UTF_8,
        )
    }
}

val bundlePublicKey = rootProject.file("morphe-signing.pub")
val generateBundleKey = tasks.register<GenerateBundleKey>("generateBundleKey") {
    // The private key only decides whether there is a signature. buildAndroid refuses one that isn't this public key's.
    signedKey.set(providers.environmentVariable("MORPHE_SIGNING_KEY").filter { it.isNotBlank() }
        .map { bundlePublicKey.readText().trim() }.orElse(""))
    outputDir.set(layout.buildDirectory.dir("generated/source/bundleKey"))
}

/**
 * Writes each settings translation table in src/main/l10n into a Java class, so a language is edited as text, one id, a
 * tab and its text per line, and the table that ships can't drift from it. es.tsv becomes SettingsTextEs.TEXT and
 * zh-TW.tsv SettingsTextZhTw.TEXT. A line starting with # is a comment (the first one names the language), and \n, \t
 * and \\ in a text are escapes. A missing id or a changed placeholder is SettingsTranslationTest's to catch.
 */
abstract class GenerateSettingsTranslations : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val tables: DirectoryProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    private fun unescape(text: String, where: String): String = buildString {
        var i = 0
        while (i < text.length) {
            val ch = text[i]
            if (ch != '\\') {
                append(ch)
                i++
                continue
            }
            when (text.getOrNull(i + 1)) {
                'n' -> append('\n')
                't' -> append('\t')
                '\\' -> append('\\')
                else -> throw GradleException("$where: a backslash has to start \\n, \\t or \\\\")
            }
            i += 2
        }
    }

    private fun javaString(text: String): String = buildString {
        append('"')
        for (ch in text) {
            when (ch) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '\n' -> append("\\n")
                '\t' -> append("\\t")
                else -> if (ch.code < 0x20) throw GradleException("A control character in $text") else append(ch)
            }
        }
        append('"')
    }

    @TaskAction
    fun generate() {
        val source = tables.get().asFile
        val directory = outputDir.get().asFile.resolve("app/hushmessenger/extension")
        directory.deleteRecursively()
        directory.mkdirs()
        val files = source.listFiles { file -> file.name.endsWith(".tsv") }.orEmpty().sortedBy { it.name }
        if (files.isEmpty()) throw GradleException("No .tsv tables in $source")
        val id = Regex("[A-Za-z0-9_.]+")
        for (file in files) {
            val tag = file.name.removeSuffix(".tsv")
            val name = "SettingsText" + tag.split('-').joinToString("") { it.lowercase().replaceFirstChar(Char::uppercaseChar) }
            var language = ""
            val seen = HashSet<String>()
            val rows = StringBuilder()
            file.readText(Charsets.UTF_8).removePrefix(Char(0xFEFF).toString()).split('\n').forEachIndexed { index, raw ->
                val line = raw.removeSuffix("\r")
                val where = "src/main/l10n/${file.name}:${index + 1}"
                if (line.isEmpty()) return@forEachIndexed
                if (line.startsWith("#")) {
                    if (language.isEmpty()) language = line.removePrefix("#").trim()
                    return@forEachIndexed
                }
                val tab = line.indexOf('\t')
                if (tab < 0) throw GradleException("$where: no tab between the id and its text")
                val key = line.substring(0, tab)
                if (!key.matches(id)) throw GradleException("$where: \"$key\" isn't an id")
                if (!seen.add(key)) throw GradleException("$where: $key is in the table twice")
                rows.append("        {\"").append(key).append("\", ").append(javaString(unescape(line.substring(tab + 1), where))).append("},\n")
            }
            if (language.isEmpty() || "*/" in language) throw GradleException("src/main/l10n/${file.name}: the first line has to be a # comment naming the language")
            directory.resolve("$name.java").writeText(
                "package app.hushmessenger.extension;\n\n" +
                    "/** $language Generated from src/main/l10n/${file.name} by :extensions:messenger:generateSettingsTranslations. Do not edit. */\n" +
                    "final class $name {\n" +
                    "    private $name() { }\n\n" +
                    "    static final String[][] TEXT = {\n" +
                    rows +
                    "    };\n}\n",
                Charsets.UTF_8,
            )
        }
    }
}

val generateSettingsTranslations = tasks.register<GenerateSettingsTranslations>("generateSettingsTranslations") {
    tables.set(layout.projectDirectory.dir("src/main/l10n"))
    outputDir.set(layout.buildDirectory.dir("generated/source/settingsTranslations"))
}

