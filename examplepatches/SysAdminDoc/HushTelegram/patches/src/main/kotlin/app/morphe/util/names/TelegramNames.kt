/**
 * Telegram 13.2 ships the top-level classes of org.telegram.messenger under R8's names: the
 * MessagesController of telegram.org's 13.2.0 is `lp`, and most of its members are one or two
 * letters. Every other package keeps its names. The patches go on naming the source classes and
 * members, and this translates at the edges: a type looked up, a smali snippet or a fingerprint
 * going in, and a name read out of the dex coming back for a comparison.
 *
 * Each supported build has a table at `hushtelegram/names/<versionCode>.txt`, generated by matching
 * the build against the last one R8 left named (13.1.1). A build without a table, and any class
 * pool still carrying the source names (the synthetic classes unit tests build), reads through
 * [IDENTITY], which changes nothing.
 */
object TelegramNames {
    const val RENAMED_PACKAGE = "Lorg/telegram/messenger/"
    private const val IDENTITY_BUILD = "identity"

    /** The version codes with a table, one per supported Telegram build. */
    private val BUILDS = listOf("72919", "72911")

    /** A member's name and descriptor in one build: a method's `(params)return`, a field's type. */
    data class Member(val owner: String, val name: String, val descriptor: String)

    /** One build's names, keyed by the source names. */
    class Table internal constructor(val build: String, val version: String) {
        internal val dex = HashSet<Int>()
        internal val classFwd = HashMap<String, String>()
        internal val classBack = HashMap<String, String>()
        internal val origSuper = HashMap<String, String>()
        internal val newSuper = HashMap<String, String>()

        /** `Lsource;->name(sourceDesc)` to the build's method. */
        internal val methodFwd = HashMap<String, Member>()

        /** `Lsource;->name` to each source descriptor and the build's method, for a call named without one. */
        internal val methodsByName = HashMap<String, MutableList<Pair<String, Member>>>()

        /** `Lbuild;->name(buildDesc)` to the source name. */
        internal val methodBack = HashMap<String, String>()

        /** `Lsource;->name` to the build's field. */
        internal val fieldFwd = HashMap<String, Member>()

        /** `Lbuild;->name:buildType` to the source name; R8 gives fields of different types one name. */
        internal val fieldBack = HashMap<String, String>()

        /** `type/name` to the resource id 13.2 inlines where the R field was read. */
        internal val resourceIds = HashMap<String, Int>()
        internal val resourceNames = HashMap<Int, String>()

        val isIdentity get() = build == IDENTITY_BUILD

        /** The id of the build's [type] resource (`string`, `drawable`, `id`, `raw`) called [name], or null. */
        fun resourceId(type: String, name: String): Int? = resourceIds["$type/$name"]

        /** The id an R field reference (`Lorg/telegram/messenger/R$string;->Name:I`) stands for in this build, or null. */
        fun resourceOf(reference: String): Int? {
            if (isIdentity) return null
            val m = R_FIELD.matchEntire(reference) ?: return null
            return resourceId(m.groupValues[1], m.groupValues[2])
        }

        /** The R field reference, as the patches name it, that a literal of this build stands for; null for any other number. */
        fun resourceField(id: Int): String? = resourceNames[id]?.let {
            "${RENAMED_PACKAGE}R\$${it.substringBefore('/')};->${it.substringAfter('/')}:I"
        }

        /**
         * A reference as a patch names it (`Lowner;->name(params)return`, `Lowner;->name:Type` or a
         * type) as this build's dex holds it. Anything else comes back as it is.
         */
        fun reference(text: String): String {
            if (isIdentity || !text.contains(RENAMED_PACKAGE)) return text
            val m = SMALI_REF.matchEntire(text) ?: return text
            val owner = m.groups[1]?.value ?: return type(text)
            val name = m.groupValues[2]
            val rest = m.groupValues[3]
            return if (rest.startsWith("(")) method(owner, name, rest).let { "${it.owner}->${it.name}${it.descriptor}" }
            else field(owner, name, rest.substring(1)).let { "${it.owner}->${it.name}:${it.descriptor}" }
        }

        /**
         * How [origRef] reads this build's member for the source reference [text]: source names, with
         * the descriptor the dex carries. R8 changes some (13.2's DispatchQueue.postRunnable(Runnable)
         * returns void), so a patch looking for a call compares with this; a stub keeps [text], which
         * [translate] turns into the build's member.
         */
        fun asRead(text: String): String {
            val built = reference(text)
            if (built == text || "->" !in text) return text
            return if ('(' in text) text.substringBefore('(') + origDescriptor(built.substring(built.indexOf('(')))
            else text.substringBefore(':') + ":" + origType(built.substringAfter("->").substringAfter(':'))
        }

        /**
         * Every name this build gives a member called [name] of [owner] or its superclasses, with
         * [name] itself, for a search that can't tell overloads or fields apart. A name read off the
         * build comes back as it is.
         */
        fun memberNames(owner: String, name: String): Set<String> {
            val out = hashSetOf(name)
            if (isIdentity) return out
            var c: String? = origType(owner)
            var depth = 0
            while (c != null && depth++ < 32) {
                methodsByName["$c->$name"]?.forEach { out += it.second.name }
                fieldFwd["$c->$name"]?.let { out += it.name }
                c = origSuper[c]
            }
            return out
        }

        /** Every name this build gives a member called [name] on any class, with [name] itself. */
        fun anyMemberNames(name: String): Set<String> = (namesBySimpleName[name] ?: emptySet()) + name

        private val namesBySimpleName: Map<String, Set<String>> by lazy {
            val out = HashMap<String, HashSet<String>>()
            for ((key, members) in methodsByName) {
                val set = out.getOrPut(key.substringAfter("->")) { HashSet() }
                members.forEach { set += it.second.name }
            }
            for ((key, member) in fieldFwd) out.getOrPut(key.substringAfter("->")) { HashSet() } += member.name
            out
        }

        /** Whether [type] is one of the build's classes the table covers, renamed or with renamed members. */
        fun knows(type: String): Boolean = newSuper.containsKey(type)

        /** The build's name for a source type, arrays included; anything else comes back as it is. */
        fun type(type: String): String = mapType(type, classFwd)

        /** The source name for one of the build's types. */
        fun origType(type: String): String = mapType(type, classBack)

        fun descriptor(descriptor: String): String = mapDescriptor(descriptor, classFwd)

        fun origDescriptor(descriptor: String): String = mapDescriptor(descriptor, classBack)

        /** The build's method for a source reference, found on the class or the nearest superclass that declares it. */
        fun method(owner: String, name: String, descriptor: String): Member {
            val source = origType(owner)
            val sourceDescriptor = origDescriptor(descriptor)
            if (methodFwd.isNotEmpty()) {
                var c: String? = source
                var depth = 0
                while (c != null && depth++ < 32) {
                    methodFwd["$c->$name$sourceDescriptor"]?.let {
                        return if (c == source) it else Member(type(source), it.name, it.descriptor)
                    }
                    c = superOf(c)
                }
            }
            return Member(type(source), name, descriptor(sourceDescriptor))
        }

        /**
         * The build's name for a source method named without its full descriptor, as a fingerprint's
         * call filter names one. [parameters] and [returnType], when given, narrow the overloads.
         */
        fun methodName(owner: String, name: String, parameters: List<String>? = null, returnType: String? = null): String {
            if (methodsByName.isEmpty()) return name
            var c: String? = origType(owner)
            var depth = 0
            while (c != null && depth++ < 32) {
                val candidates = methodsByName["$c->$name"].orEmpty().filter { (descriptor, _) ->
                    (parameters == null || descriptor.substringAfter('(').substringBefore(')') ==
                        parameters.joinToString("") { origType(it) }) &&
                        (returnType == null || descriptor.substringAfter(')') == origType(returnType))
                }
                val names = candidates.map { it.second.name }.toSet()
                if (names.size == 1) return names.single()
                if (names.size > 1) throw PatchException(
                    "Telegram $version renamed the overloads of $c->$name differently (${names.joinToString()}); " +
                        "name its parameters",
                )
                c = superOf(c)
            }
            return name
        }

        fun field(owner: String, name: String, fieldType: String): Member {
            val source = origType(owner)
            if (fieldFwd.isNotEmpty()) {
                var c: String? = source
                var depth = 0
                while (c != null && depth++ < 32) {
                    fieldFwd["$c->$name"]?.let {
                        return if (c == source) it else Member(type(source), it.name, it.descriptor)
                    }
                    c = superOf(c)
                }
            }
            return Member(type(source), name, type(origType(fieldType)))
        }

        /** The source name of the build's method, looked up on the class and then its renamed superclasses. */
        fun origMethodName(owner: String, name: String, descriptor: String): String {
            if (methodBack.isEmpty()) return name
            var c: String? = owner
            var depth = 0
            while (c != null && depth++ < 32) {
                methodBack["$c->$name$descriptor"]?.let { return it }
                c = newSuper[c]
            }
            return name
        }

        fun origFieldName(owner: String, name: String, fieldType: String): String {
            if (fieldBack.isEmpty()) return name
            var c: String? = owner
            var depth = 0
            while (c != null && depth++ < 32) {
                fieldBack["$c->$name:$fieldType"]?.let { return it }
                c = newSuper[c]
            }
            return name
        }

        /** A source class's superclass, from the table or else the class pool being patched. */
        private fun superOf(source: String): String? {
            origSuper[source]?.let { return it }
            val context = currentContext() ?: return null
            if (!source.startsWith("L")) return null
            return context.classDefByOrNull(type(source))?.superclass?.let(::origType)
        }

        /**
         * [smali] with every source type and member it names in this build's names. A member of a
         * renamed class that the class pool can't resolve fails the patch here, naming it, rather
         * than leaving a call ART rejects when the app runs.
         */
        fun translate(smali: String, context: BytecodePatchContext?): String {
            if (isIdentity || !smali.contains(RENAMED_PACKAGE)) return smali
            // 13.2 has no R classes: a resource id is loaded as the literal R8 inlined everywhere else.
            val loads = SGET_RESOURCE.replace(smali) { m ->
                val (register, type, name) = m.destructured
                val id = resourceId(type, name)
                    ?: throw PatchException("Telegram $version ($build) has no $type resource called $name")
                "const $register, 0x${Integer.toHexString(id)}"
            }
            return SMALI_REF.replace(loads) { m ->
                val owner = m.groups[1]?.value ?: return@replace type(m.value)
                val name = m.groupValues[2]
                val rest = m.groupValues[3]
                if (owner.startsWith("${RENAMED_PACKAGE}R\$")) throw PatchException(
                    "Telegram $version ($build) inlines $owner->$name; only an sget of it can be put in its place",
                )
                if (rest.startsWith("(")) {
                    val t = method(owner, name, rest)
                    if (context != null) require(context, owner, name, t, field = false)
                    "${t.owner}->${t.name}${t.descriptor}"
                } else {
                    val t = field(owner, name, rest.substring(1))
                    if (context != null) require(context, owner, name, t, field = true)
                    "${t.owner}->${t.name}:${t.descriptor}"
                }
            }
        }

        private fun require(context: BytecodePatchContext, owner: String, name: String, t: Member, field: Boolean) {
            if (!isRenamed(origType(owner))) return
            if (resolves(context, t.owner, t.name, t.descriptor, field)) return
            throw PatchException(
                "Telegram $version ($build) has no ${t.owner}->${t.name}${if (field) ":" else ""}${t.descriptor} " +
                    "for ${origType(owner)}->$name; its name table has no match for that member",
            )
        }

        override fun toString() = if (isIdentity) "source names" else "Telegram $version ($build)"
    }

    /** The table that changes nothing. */
    val IDENTITY = Table(IDENTITY_BUILD, "with source names")

    private val SMALI_TYPE = """\[*(?:[ZBSCIJFD]|L[\w/$\-]+;)"""
    private val SMALI_REF = Regex(
        """(L[\w/$\-]+;)->([\w$\-]+|<init>|<clinit>)(\((?:$SMALI_TYPE)*\)(?:V|$SMALI_TYPE)|:$SMALI_TYPE)|L[\w/$\-]+;""",
    )
    private val R_FIELD = Regex("""Lorg/telegram/messenger/R\$(\w+);->(\w+):I""")
    private val SGET_RESOURCE = Regex("""\bsget(?:-\w+)?\s+([vp]\d+),\s*Lorg/telegram/messenger/R\$(\w+);->(\w+):I""")
    private val OBJECT_METHODS = setOf(
        "equals(Ljava/lang/Object;)Z", "hashCode()I", "toString()Ljava/lang/String;", "getClass()Ljava/lang/Class;",
        "notify()V", "notifyAll()V", "wait()V", "wait(J)V", "wait(JI)V", "clone()Ljava/lang/Object;", "finalize()V",
    )

    private val tables: List<Table> by lazy { BUILDS.map(::load) }
    private val byChecksum: Map<Int, Table> by lazy { tables.flatMap { t -> t.dex.map { it to t } }.toMap() }
    private val sourceRenamed: Set<String> by lazy {
        tables.flatMapTo(HashSet()) { t -> t.classFwd.filter { (k, v) -> k != v }.keys }
    }
    private val contextTables = WeakHashMap<BytecodePatchContext, Table>()

    /**
     * Tests only: the build a fixture was last read from, for names read off copies that no longer
     * know their dex. Production never sets it.
     */
    @Volatile
    var ambient: Table? = null

    fun forVersionCode(versionCode: String?): Table? = tables.firstOrNull { it.build == versionCode }

    /** The table of the build a dex belongs to, by the checksum in its header. */
    fun forDex(dex: DexBackedDexFile): Table = byChecksum[dex.buffer.readInt(8)] ?: IDENTITY

    /** The table for what's being patched now. */
    fun current(): Table = currentContext()?.let(::of) ?: ambient ?: IDENTITY

    fun of(context: BytecodePatchContext): Table = synchronized(contextTables) {
        contextTables.getOrPut(context) { detect(context) }
    }

    /** The table that names [reference]: its own dex's when it still has one, else the build being patched. */
    fun tableOf(reference: Any): Table = when (reference) {
        is DexBackedMethod -> forDex(reference.dexFile)
        is DexBackedField -> forDex(reference.dexFile)
        is DexBackedClassDef -> forDex(reference.dexFile)
        is DexBackedMethodReference -> forDex(reference.dexFile)
        is DexBackedFieldReference -> forDex(reference.dexFile)
        is DexBackedTypeReference -> forDex(reference.dexFile)
        is DexBackedInstruction -> forDex(reference.dexFile)
        else -> ambient ?: currentContext()?.let(::of) ?: IDENTITY
    }

    /** [smali] in the names of the build being patched. */
    fun tg(smali: String): String {
        val context = currentContext()
        val table = context?.let(::of) ?: ambient ?: IDENTITY
        return table.translate(smali, context)
    }

    /** A type of org.telegram.messenger's top level, the one package R8 renames. */
    fun isRenamed(type: String): Boolean {
        var i = 0
        while (i < type.length && type[i] == '[') i++
        return type.startsWith(RENAMED_PACKAGE, i) && type.indexOf('/', i + RENAMED_PACKAGE.length) < 0
    }

    private val currentField by lazy {
        PatcherContext::class.java.getDeclaredField("current").apply { isAccessible = true }
    }
    private val bytecodeGetter by lazy {
        PatcherContext::class.java.getMethod("getBytecodeContext\$morphe_patcher")
    }

    /** The bytecode context the patcher is running now, or null outside a patch. */
    fun currentContext(): BytecodePatchContext? {
        val patcher = currentField.get(null) ?: return null
        return bytecodeGetter.invoke(patcher) as BytecodePatchContext?
    }

    @Suppress("DEPRECATION")
    private fun detect(context: BytecodePatchContext): Table {
        forVersionCode(context.packageMetadata.versionCode)?.let { return it }
        // Synthetic classes and builds before 13.2 carry the source names. Otherwise the first
        // class still backed by its dex names the build.
        var named = false
        var fromDex: Table? = null
        context.classDefForEach { c ->
            if (named || !c.type.startsWith(RENAMED_PACKAGE)) return@classDefForEach
            if (c.type in sourceRenamed) named = true
            else if (fromDex == null && c is DexBackedClassDef) fromDex = byChecksum[c.dexFile.buffer.readInt(8)]
        }
        return if (named) IDENTITY else fromDex ?: IDENTITY
    }

    private fun resolves(context: BytecodePatchContext, owner: String, name: String, descriptor: String, field: Boolean): Boolean {
        val seen = HashSet<String>()
        val queue = ArrayDeque(listOf(owner))
        while (queue.isNotEmpty()) {
            val c = queue.removeFirst()
            if (!seen.add(c)) continue
            if (c == "Ljava/lang/Object;") {
                if (!field && "$name$descriptor" in OBJECT_METHODS) return true
                continue
            }
            // A framework class isn't in the pool, so whatever it declares can't be checked here.
            val def = context.classDefByOrNull(c) ?: return true
            if (field) {
                if (def.fields.any { it.name == name && it.type == descriptor }) return true
            } else if (def.methods.any { it.name == name && it.descriptor() == descriptor }) {
                return true
            }
            def.superclass?.let(queue::add)
            queue.addAll(def.interfaces)
        }
        return false
    }

    private fun load(build: String): Table {
        val path = "/hushtelegram/names/$build.txt"
        val stream = TelegramNames::class.java.getResourceAsStream(path) ?: error("$path is missing from the patches")
        var table: Table? = null
        stream.bufferedReader().useLines { lines ->
            for (line in lines) {
                if (line.isEmpty() || line.startsWith("#")) continue
                val p = line.split(' ')
                when (p[0]) {
                    "build" -> table = Table(p[1], p[2])
                    "dex" -> table!!.dex += java.lang.Long.parseLong(p[2], 16).toInt()
                    "c" -> with(table!!) {
                        classFwd[p[1]] = p[2]
                        classBack[p[2]] = p[1]
                        origSuper[p[1]] = p[3]
                        newSuper[p[2]] = p[4]
                    }
                    "m" -> with(table!!) {
                        val member = Member(p[4], p[5], p[6])
                        methodFwd["${p[1]}->${p[2]}${p[3]}"] = member
                        methodsByName.getOrPut("${p[1]}->${p[2]}") { mutableListOf() } += p[3] to member
                        methodBack["${p[4]}->${p[5]}${p[6]}"] = p[2]
                    }
                    "f" -> with(table!!) {
                        fieldFwd["${p[1]}->${p[2]}"] = Member(p[4], p[5], p[6])
                        fieldBack["${p[4]}->${p[5]}:${p[6]}"] = p[2]
                    }
                    "r" -> with(table!!) {
                        val id = java.lang.Long.parseLong(p[3], 16).toInt()
                        resourceIds["${p[1]}/${p[2]}"] = id
                        resourceNames[id] = "${p[1]}/${p[2]}"
                    }
                }
            }
        }
        return checkNotNull(table) { "$path has no build line" }.also {
            check(it.build == build) { "$path is the table of ${it.build}" }
        }
    }

    private fun mapType(type: String, map: Map<String, String>): String {
        if (map.isEmpty()) return type
        var dims = 0
        while (dims < type.length && type[dims] == '[') dims++
        if (dims >= type.length || type[dims] != 'L') return type
        val mapped = map[if (dims == 0) type else type.substring(dims)] ?: return type
        return if (dims == 0) mapped else type.substring(0, dims) + mapped
    }

    private fun mapDescriptor(descriptor: String, map: Map<String, String>): String {
        if (map.isEmpty() || descriptor.indexOf('L') < 0) return descriptor
        val out = StringBuilder(descriptor.length)
        var i = 0
        while (i < descriptor.length) {
            val c = descriptor[i]
            if (c == 'L') {
                val end = descriptor.indexOf(';', i)
                if (end < 0) {
                    out.append(descriptor, i, descriptor.length)
                    break
                }
                val type = descriptor.substring(i, end + 1)
                out.append(map[type] ?: type)
                i = end + 1
            } else {
                out.append(c)
                i++
            }
        }
        return out.toString()
    }
}

/** A method's `(params)return` descriptor. */
fun MethodReference.descriptor(): String = buildString {
    append('(')
    parameterTypes.forEach { append(it) }
    append(')')
    append(returnType)
}

/** A class's superclass in source names. */
val ClassDef.origSuperclass: String? get() = superclass?.let { TelegramNames.tableOf(this).origType(it) }

/** A class's interfaces in source names. */
val ClassDef.origInterfaces: List<String> get() = TelegramNames.tableOf(this).let { t -> interfaces.map(t::origType) }
