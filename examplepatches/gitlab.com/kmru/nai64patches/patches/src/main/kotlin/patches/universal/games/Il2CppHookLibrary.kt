/**
 * Ships the IL2CPP hook library.
 *
 * A null name is deliberate: the patch list generator drops every unnamed
 * patch, so this ships inside the bundle without showing up as a selectable
 * entry in Morphe Manager. Game patches reach it through `dependsOn`, which
 * references the object directly and does not care about the name.
 */
@Suppress("unused")
val il2cppHookLibraryPatch = resourcePatch(
    name = null,
    description = "Internal: the native library the IL2CPP game patches hook with.",
    default = false,
) {
    execute {
        val logger = Logger.getLogger(this::class.java.name)
        val bytes = try {
            Base64.getDecoder().decode(HOOK_LIBRARY_BASE64)
        } catch (e: IllegalArgumentException) {
            logger.warning("IL2CPP Hook Library: embedded library is corrupt - " + e.message)
            return@execute
        }
        if (!isElf(bytes)) {
            logger.invalidLibrary("IL2CPP Hook Library")
            return@execute
        }
        get(LIB_ASSET_PATH, true).outputStream().use { it.write(bytes) }
        logger.info("IL2CPP Hook Library: wrote $LIB_ASSET_PATH (" + bytes.size + " bytes)")
    }
}

internal const val LIB_ASSET_PATH = "assets/morphe/libmorpheil2cpp.so"
internal const val RULES_DIR = "assets/morphe/il2cpp-hooks"

