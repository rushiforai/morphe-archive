internal fun isElf(bytes: ByteArray): Boolean =
    bytes.size >= 20 &&
        bytes[0] == 0x7F.toByte() && bytes[1] == 'E'.code.toByte() &&
        bytes[2] == 'L'.code.toByte() && bytes[3] == 'F'.code.toByte()

internal fun Logger.invalidLibrary(patch: String) {
    warning("$patch: embedded hook library is not an ELF image, skipping")
}
