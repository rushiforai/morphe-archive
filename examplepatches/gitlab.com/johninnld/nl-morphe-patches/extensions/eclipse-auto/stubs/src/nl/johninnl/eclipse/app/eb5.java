package nl.johninnl.eclipse.app;

/** Stand-in for one track of a linked list: identity, explicit flag and the linked track id (nullable). */
public final class eb5 {
    public final fm3 a;
    /** Assigned in the constructor so javac reads the field instead of folding a constant into callers. */
    public final boolean b;
    public final String c;

    public eb5() {
        a = null;
        b = Boolean.parseBoolean(null);
        c = null;
    }
}
