extension {
    name = "extensions/extension.mpe"
}

// core/BuildInfo.java is generated: PATCH_VERSION = project.version, which semantic-release writes into
// gradle.properties before the release build (spec section 10, "Copy details"). See docs/DEV.md.
val buildInfoDir = layout.buildDirectory.dir("generated/source/buildinfo")
val patchVersion = project.version.toString().takeIf { it.isNotBlank() && it != "unspecified" } ?: "dev"

val generateBuildInfo = tasks.register("generateBuildInfo") {
    val outDir = buildInfoDir
    val v = patchVersion
    inputs.property("patchVersion", v)
    outputs.dir(outDir)
    doLast {
        val file = outDir.get().file("app/wordfeudwordfinder/extension/core/BuildInfo.java").asFile
        file.parentFile.mkdirs()
        val literal = v.replace("\\", "\\\\").replace("\"", "\\\"")
        file.writeText(
            """
            |package app.wordfeudwordfinder.extension.core;
            |
            |/** Generated by the generateBuildInfo task; do not edit. */
            |public final class BuildInfo {
            |    public static final String PATCH_VERSION = "$literal";
            |
            |    private BuildInfo() {}
            |}
            |""".trimMargin()
        )
    }
}

apply(from = rootProject.file("gradle/wordlist-manifest.gradle.kts"))

android {
    namespace = "app.wordfeudwordfinder.extension"
    sourceSets {
        getByName("main") {
            java.srcDir(buildInfoDir.get().asFile)
            java.srcDir(layout.buildDirectory.dir("generated/source/wordlists").get().asFile)
        }
    }
}

tasks.named("preBuild") {
    dependsOn(generateBuildInfo)
    dependsOn("generateWordListManifest")
}

