#!/usr/bin/env bash
# Compile-checks ALL extension sources (including ui/ and other android.* users) with javac
# against android.jar (platform 34) on the classpath (java.* APIs are checked against JDK 17).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
CACHE="$HERE/.cache"
JAR="$CACHE/android.jar"
URL="https://dl.google.com/android/repository/platform-34-ext7_r02.zip"
SRC="$HERE/../../extensions/extension/src/main/java"
OUT="$HERE/build/android-compile-check"

if [ ! -f "$JAR" ]; then
  mkdir -p "$CACHE/dl"
  curl -fsSL "$URL" -o "$CACHE/platform.zip"
  unzip -q -o "$CACHE/platform.zip" -d "$CACHE/dl"
  cp "$CACHE"/dl/*/android.jar "$JAR"
  rm -rf "$CACHE/dl" "$CACHE/platform.zip"
fi

rm -rf "$OUT"; mkdir -p "$OUT"
mapfile -t FILES < <(find "$SRC" -name '*.java')
# BuildInfo is generated by the real build (generateBuildInfo); compile against the "dev" stand-in.
FILES+=("$HERE/src/buildinfo/java/app/wordfeudwordfinder/extension/core/BuildInfo.java")
# WordListManifest is generated from wordlists/manifest.json (gradle/wordlist-manifest.gradle.kts); generate it
# with the JVM test build when it is missing.
MANIFEST="$HERE/build/generated/source/wordlists/app/wordfeudwordfinder/extension/words/WordListManifest.java"
[ -f "$MANIFEST" ] || gradle -q -p "$HERE" generateWordListManifest
FILES+=("$MANIFEST")
if [ "${#FILES[@]}" -eq 0 ]; then
  echo "android-compile-check: no Java sources yet, nothing to compile"
  exit 0
fi
javac --release 17 -Xlint:-options -classpath "$JAR" -d "$OUT" "${FILES[@]}"
echo "android-compile-check: OK (${#FILES[@]} files)"

# Unit tests too: on Android org.json's JSONException is a checked exception (on the JVM test jar it is not), so
# tests that compile in the JVM build can still fail in CI. Needs JUnit from the Gradle cache (run the JVM tests once).
JUNIT=$(find "$HOME/.gradle" -name 'junit-4.13.2.jar' 2>/dev/null | head -1)
HAMCREST=$(find "$HOME/.gradle" -name 'hamcrest-core-1.3.jar' 2>/dev/null | head -1)
TESTSRC="$HERE/../../extensions/extension/src/test/java"
if [ -n "$JUNIT" ] && [ -n "$HAMCREST" ] && [ -d "$TESTSRC" ]; then
  mapfile -t TESTS < <(find "$TESTSRC" -name '*.java')
  javac --release 17 -nowarn -classpath "$JAR:$OUT:$JUNIT:$HAMCREST" -d "$OUT" "${TESTS[@]}"
  echo "android-compile-check: tests OK (${#TESTS[@]} files)"
else
  echo "android-compile-check: tests skipped (run gradle -p tools/jvm-tests test once for JUnit)"
fi
