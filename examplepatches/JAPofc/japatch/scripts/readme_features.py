#!/usr/bin/env python3
"""Rewrite the feature table in README.md from patches-list.json.

    python3 scripts/readme_features.py          # update README.md in place
    python3 scripts/readme_features.py --check  # fail if README.md is out of date

The table used to be typed by hand, so every release could ship without its new features listed. The
list is generated by the build, so it is always current; this script keeps the README honest without
anyone having to remember. Sections follow the app's own Settings groups, in the same order.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
LIST = ROOT / "patches-list.json"

START = "<!-- features:start -->"
END = "<!-- features:end -->"
# The Settings groups, in the order Discord shows them. Every patch is a plugin in the "Features" section,
# and its own name says where it lives, so the group is read from the name prefixes below.
GROUPS = [
    ("Messages", ["Keep deleted", "Bulk delete", "Hide blocked", "Message highlights", "Translate", "Double-tap",
                  "Load full-quality", "Skip delete", "Skip pin", "Download voice", "Keep media", "Banners in",
                  "Jump to first", "Favourite", "Delete without", "Edit without", "Edit messages", "Export chats",
                  "Replace text", "View raw"]),
    ("Sending", ["Send Nitro", "Bring back Tenor", "Fix link previews", "Send audio", "Send long", "Hide typing",
                 "Show file sizes", "Anonymous file names", "Tap mentions", "Expand the message bar", "Compress big",
                 "Reply without pinging", "Always trust links"]),
    ("People", ["Pastel", "Show device", "Show owner", "Alert when", "Fix unknown", "Copy profile", "Leave group", "Show names your way",
                "Show timeout", "User and server reviews", "User activity", "Account switcher", "Listen along",
                "HypeSquad", "Custom idle", "Mutual group", "Platform spoof"]),
    ("Servers", ["Read all", "Show hidden", "Server info", "Edit servers", "Clone emojis", "Clean channel",
                 "Preview servers", "Pause invites", "Fast delete"]),
    ("Appearance", ["Use your phone's font", "Use your phone's emojis", "Remove anything", "JaPatch button",
                    "Unlock app icons", "Unlock Nitro themes", "Full-screen chat", "Material You", "Custom themes",
                    "Icon packs"]),
    ("Quests and advanced", ["Complete Quests", "Complete badges", "Unlock Discord experiments",
                             "Keep Bluetooth", "Voice channel options", "Fake deafen"]),
]


def _icon_keys():
    """The keys in FEATURE_ICONS, which is what the app counts."""
    source = (ROOT / "patches/src/main/resources/japatch/bootstrap.js").read_text(encoding="utf-8")
    start = source.index("const FEATURE_ICONS = {")
    depth = 0
    for i in range(start, len(source)):
        if source[i] == "{":
            depth += 1
        elif source[i] == "}":
            depth -= 1
            if depth == 0:
                block = source[start:i + 1]
                break
    return re.findall(r"([A-Za-z0-9_]+)\s*:\s*\[\s*\d+\s*,\s*\"", block)


def _compiled_features():
    """Every feature the Kotlin side compiles in: the listOf(...) entries plus the XSelected flags."""
    kotlin = (ROOT / "patches/src/main/kotlin/app/japatch/patches/DiscordPatches.kt").read_text(encoding="utf-8")
    start = kotlin.index('listOf("noTyping"')
    depth, end = 0, start
    for i in range(kotlin.index("(", start), len(kotlin)):
        if kotlin[i] == "(":
            depth += 1
        elif kotlin[i] == ")":
            depth -= 1
            if depth == 0:
                end = i
                break
    from_list = re.findall(r'"([A-Za-z0-9_]+)"', kotlin[start:end])
    flags = [m[0].lower() + m[1:] for m in re.findall(r"\b([A-Za-z0-9_]+)Selected\b", kotlin)]
    return set(from_list) | set(flags)


def patches():
    data = json.loads(LIST.read_text(encoding="utf-8"))
    return [p for p in data["patches"] if p.get("category") == "Features"]


LIMIT = 150


def sentence(text):
    """Morphe's descriptions run several sentences and credit other patches. A table cell needs one short line:
    keep the first sentence, and only then trim, so the wording stays the author's."""
    text = re.sub(r"\s+", " ", (text or "").strip())
    if len(text) > LIMIT:
        first = re.split(r"(?<=[.!?])\s+(?=[A-Z])", text)[0]
        if len(first) <= LIMIT + 40:
            text = first
    if len(text) > LIMIT + 40:
        text = text[:LIMIT + 40].rsplit(" ", 1)[0] + "…"
    return text.rstrip(".")


def table():
    found = patches()
    by_name = {p["name"]: sentence(p.get("description")) for p in found}
    used = set()
    lines = [START, ""]
    left = []
    for title, prefixes in GROUPS:
        rows = []
        for name, description in by_name.items():
            if name in used:
                continue
            if any(name.startswith(prefix) for prefix in prefixes):
                used.add(name)
                rows.append((name, description))
        if not rows:
            continue
        rows.sort()
        lines.append(f"### {title}")
        lines.append("")
        lines.append("| Feature | What it does |")
        lines.append("| --- | --- |")
        for name, description in rows:
            lines.append(f"| {name} | {description} |")
        lines.append("")
    left = [name for name in by_name if name not in used]
    if left:
        lines.append("### Setup")
        lines.append("")
        lines.append("| Feature | What it does |")
        lines.append("| --- | --- |")
        for name in sorted(left):
            lines.append(f"| {name} | {by_name[name]} |")
        lines.append("")
    # The number the app itself shows (featureSummary(): FEATURE_ICONS keys that are actually compiled in),
    # not the manifest's row count. They were 77, 79 and 84 in three files at once, and every reader had to
    # guess which one was true. The manifest counts rows; the app counts what a person can switch on.
    shown = sum(1 for key in _compiled_features() if key in _icon_keys())
    lines.append(f"**{shown} features**, all off until you turn them on in "
                 f"**Discord Settings → JaPatch → Features**.")
    lines.append("")
    lines.append(END)
    return "\n".join(lines)


def build(readme):
    if START not in readme or END not in readme:
        raise SystemExit(f"README.md is missing {START} / {END}")
    before, rest = readme.split(START, 1)
    _, after = rest.split(END, 1)
    return before + table() + after


if __name__ == "__main__":
    current = README.read_text(encoding="utf-8")
    wanted = build(current)
    if "--check" in sys.argv:
        if wanted != current:
            raise SystemExit("README.md feature table is out of date: run python3 scripts/readme_features.py")
        print("README.md feature table matches patches-list.json")
    else:
        README.write_text(wanted, encoding="utf-8")
        print("README.md feature table rewritten from patches-list.json")
