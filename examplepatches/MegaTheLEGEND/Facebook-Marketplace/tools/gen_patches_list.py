"""Generates patches-list.json (same shape as Morphe's) from the Kotlin sources.
Usage: python tools/gen_patches_list.py <version> [out=patches-list.json]"""
import json, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "patches/src/main/kotlin/app/morphe/patches/facebook/marketplace"
VERSION = sys.argv[1] if len(sys.argv) > 1 else "dev"
OUT = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "patches-list.json"

STR = r'"((?:[^"\\]|\\.)*)"'

def lit(expr):
    """Joins 'a' + 'b' Kotlin literals (resolves $NAME via consts) into one string."""
    parts = re.findall(STR, expr)
    out = "".join(parts).replace('\\"', '"').replace("\\\\", "\\")
    return out

def consts(text):
    return dict(re.findall(r'(?:private\s+)?const val (\w+)\s*=\s*"([^"]*)"', text))

def sub(s, c):
    return re.sub(r"\$(\w+)", lambda m: c.get(m.group(1), m.group(0)), s)

def field(block, name):
    m = re.search(name + r"\s*=\s*((?:\"(?:[^\"\\]|\\.)*\"\s*\+?\s*)+)", block)
    return lit(m.group(1)) if m else None

def options(text, c):
    res = []
    for m in re.finditer(r"(boolean|string)Option\(\s*(.*?)\n\s*\)", text, re.S):
        kind, body = m.group(1), m.group(2)
        key = field(body, "key")
        if not key:
            continue
        dm = re.search(r"default\s*=\s*([^\n,]+)", body)
        dv = dm.group(1).strip() if dm else None
        if kind == "boolean":
            dv = dv == "true"
        else:
            dv = sub(lit(dv), c) if dv and dv.startswith('"') else c.get((dv or "").strip(), dv)
        res.append({
            "key": key,
            "title": sub(field(body, "title") or key, c),
            "description": sub(field(body, "description") or "", c),
            "required": False,
            "type": "kotlin.Boolean" if kind == "boolean" else "kotlin.String",
            "default": dv,
            "values": None,
        })
    return res

def patch(file, valname, c):
    t = (SRC / file).read_text(encoding="utf-8")
    c = {**c, **consts(t)}
    m = re.search(valname + r"\s*=\s*\w+Patch\(\s*name\s*=\s*\"([^\"]+)\",\s*description\s*=\s*((?:\"(?:[^\"\\]|\\.)*\"\s*\+?\s*)+),\s*(?://[^\n]*\n\s*)*default\s*=\s*(true|false)", t, re.S)
    name, desc, default = m.group(1), sub(lit(m.group(2)), c), m.group(3) == "true"
    return name, desc, default, options(t, c)

compat = [{
    "packageName": "com.facebook.katana", "name": "Facebook", "description": None,
    "apkFileType": "APK_REQUIRED", "appIconColor": "#1877F2",
    "signatures": ["e3f9e1e0cf99d0e56a055ba65e241b3399f7cea524326b0cdd6ec1327ed0fdc1"],
    "targets": [{"version": "582.0.0.50.54", "versionCodes": None, "isExperimental": False,
                 "minSdk": 30, "description": None}],
}]
patches = []
for f, v in (("MarketplaceOnlyPatch.kt", "val marketplaceOnlyPatch"), ("MarketplaceRenamePatch.kt", "val marketplaceRenamePatch")):
    n, d, df, o = patch(f, v, {})
    patches.append({"name": n, "description": d, "default": df, "category": None,
                    "compatiblePackages": compat, "options": o})

json.dump({"NOTE": "Generated by tools/gen_patches_list.py. Do not edit by hand.",
           "version": VERSION, "patches": patches}, open(OUT, "w", encoding="utf-8"), indent=2, ensure_ascii=False)
print("wrote", OUT, [(p["name"], len(p["options"])) for p in patches])
