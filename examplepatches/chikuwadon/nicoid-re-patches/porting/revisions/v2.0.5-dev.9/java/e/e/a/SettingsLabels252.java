package e.e.a;

import android.content.SharedPreferences;
import android.preference.Preference;
import android.preference.PreferenceActivity;
import android.preference.PreferenceGroup;
import android.preference.PreferenceManager;
import android.os.Handler;
import android.os.Looper;
import java.lang.ref.WeakReference;
import java.util.WeakHashMap;

/** Targeted locale updates without replacing existing preference actions. */
public final class SettingsLabels252 {
 private static final Handler MAIN=new Handler(Looper.getMainLooper());
 private static final WeakHashMap<PreferenceActivity,SharedPreferences.OnSharedPreferenceChangeListener> WATCHERS=new WeakHashMap<>();
 private static final String DESCRIPTION="動画画面の長押し中だけ再生速度を変更します。指を離すと元に戻ります（左端で無効）";
 private SettingsLabels252(){}

 public static void install(PreferenceActivity activity){
  if(activity==null||activity.isFinishing()||activity.isDestroyed())return;
  refresh(activity);
  SharedPreferences prefs=PreferenceManager.getDefaultSharedPreferences(activity);
  SharedPreferences.OnSharedPreferenceChangeListener old=WATCHERS.remove(activity);
  if(old!=null)prefs.unregisterOnSharedPreferenceChangeListener(old);
  WeakReference<PreferenceActivity> weak=new WeakReference<>(activity);
  SharedPreferences.OnSharedPreferenceChangeListener listener=(p,key)->{
   if(!"mp4_tree_uri".equals(key) && !"app_lang".equals(key) && !isLongPressKey(weak.get(),key))return;
   MAIN.post(()->{
    PreferenceActivity a=weak.get();
    if(a!=null&&!a.isFinishing()&&!a.isDestroyed())refresh(a);
   });
  };
  prefs.registerOnSharedPreferenceChangeListener(listener);
  WATCHERS.put(activity,listener);
 }
 private static boolean isLongPressKey(PreferenceActivity a,String key){
  if(a==null||key==null||a.isFinishing()||a.isDestroyed())return false;
  Preference p=findLongPress(a.getPreferenceScreen());
  return p!=null&&key.equals(p.getKey());
 }
 public static void refresh(PreferenceActivity a){
  if(a==null||a.isFinishing()||a.isDestroyed())return;
  UiStrings.selectLanguage(PreferenceManager.getDefaultSharedPreferences(a).getString("app_lang","0"));
  SettingsCategories241.updateLanguage(a);
  // Never change the storage URI or the existing storage picker callback.
  Preference location=a.findPreference("mp4_tree_uri");
  if(location!=null){
   location.setTitle(UiStrings.translate("動画・音声の保存先フォルダ"));
   CharSequence summary=location.getSummary();
   String first=summary==null?"":summary.toString().split("\\n",2)[0];
   String description=UiStrings.translate("保存したMP4・MP3は本アプリでは再生できません。外部の再生アプリをご利用ください");
   location.setSummary(first.isEmpty()?description:first+"\n"+description);
  }

  Preference speed=findLongPress(a.getPreferenceScreen());
  if(speed!=null&&speed.getSummary()!=null){
   String summary=speed.getSummary().toString();
   int pos=summary.indexOf('：');
   if(pos<0)pos=summary.indexOf(':');
   String selected=pos>=0?summary.substring(0,pos).trim():summary.trim();
   // The prefix is generated by the existing speed preference; never
   // replace it with a fixed or guessed selection.
   if(!selected.isEmpty()&&selected.length()<24){
    String separator=PanelUi.tr(a,"：",": ","：");
    speed.setSummary(selected+separator+UiStrings.translate(DESCRIPTION));
   }
  }
  Preference lang=a.findPreference("app_lang");
  if(lang!=null)lang.setTitle(UiStrings.translate("アプリ全体の言語"));
  PreferenceGroup root=a.getPreferenceScreen();
  if(root!=null)translateLanguageHeader(root);
 }
 private static Preference findLongPress(Preference p){
  if(p==null)return null;
  if(p.getTitle()!=null){
   String title=p.getTitle().toString();
   if(title.equals("長押し中の再生速度")||title.equals("Long-press playback speed")
       ||title.equals("長按播放速度")||title.equals(UiStrings.translate("長押し中の再生速度")))return p;
  }
  if(p instanceof PreferenceGroup){
   PreferenceGroup group=(PreferenceGroup)p;
   for(int i=0;i<group.getPreferenceCount();i++){
    Preference match=findLongPress(group.getPreference(i));
    if(match!=null)return match;
   }
  }
  return null;
 }
 private static void translateLanguageHeader(PreferenceGroup group){
  for(int i=0;i<group.getPreferenceCount();i++){
   Preference p=group.getPreference(i);
   if(p instanceof PreferenceGroup){
    if(p.getTitle()!=null&&("言語".equals(p.getTitle().toString())
        ||"Language".equals(p.getTitle().toString())
        ||"語言".equals(p.getTitle().toString())))
     p.setTitle(UiStrings.translate("言語"));
    translateLanguageHeader((PreferenceGroup)p);
   }
  }
 }
}
