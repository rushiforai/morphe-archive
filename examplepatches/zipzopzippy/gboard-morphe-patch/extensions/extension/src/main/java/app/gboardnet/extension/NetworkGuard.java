/**
 * Decides which network requests Gboard may make.
 *
 * Called from wrappers generated by the patch around every URL / Cronet / DNS / socket call site.
 * Must never itself use the network, and must be cheap: it is on hot paths.
 */
@SuppressWarnings("unused")
public final class NetworkGuard {
    private static final String TAG = "GboardNetworkGuard";

    static final String CONFIG_FILE = "gboardnet_network_guard.properties";
    static final String LOG_FILE = "gboardnet_network_guard.log";
    static final String KEY_ENABLED = "enabled";
    static final String KEY_LOGGING = "logging";
    static final String KEY_RULES = "rules";
    static final String KEY_BLOCK_GMS = "blockGms";
    static final String KEY_GMS_RULES = "gmsRules";
    static final String KEY_PREFER_OFFLINE_VOICE = "preferOfflineVoice";
    /** Patch defaults the saved config already knows about, so newly added defaults can be merged in. */
    static final String KEY_KNOWN_DEFAULT_RULES = "knownDefaultRules";
    static final String KEY_KNOWN_DEFAULT_GMS_RULES = "knownDefaultGmsRules";

    static final String GMS_PACKAGE = "com.google.android.gms";

    /** Cronet requests that are blocked are pointed here, so they fail via onFailed(). */
    static final String BLOCKED_URL = "http://127.0.0.1:9/blocked-by-gboard-network-guard";

    private static final long RELOAD_INTERVAL_MS = 1000;
    private static final long MAX_LOG_BYTES = 256 * 1024;

    private static volatile Context appContext;
    private static volatile Config config;
    private static volatile long lastReloadCheck;
    private static long loadedMtime = Long.MIN_VALUE;

    private static final Object LOG_LOCK = new Object();
    private static String lastLogKey;
    private static long lastLogTime;
    private static ExecutorService logWriter;

    private NetworkGuard() {
    }

    // region Patch time defaults (method bodies are replaced by the patch)

    public static String patchDefaultRules() {
        return "*.gstatic.com\ntenor.googleapis.com\ntranslation.googleapis.com\ndl.google.com/android/voice/gboard/";
    }

    public static boolean patchDefaultEnabled() {
        return true;
    }

    public static boolean patchDefaultBlockGms() {
        return true;
    }

    public static boolean patchDefaultPreferOfflineVoice() {
        return true;
    }

    public static String patchDefaultGmsRules() {
        return "com.google.android.gms.chimera.container.moduleinstall.ModuleInstallService.START\n"
                + "com.google.android.chimera.BoundService.START";
    }

    // endregion

    // region Hooks called from patched code

    /** URL.openConnection / openStream and Network.openConnection. */
    public static void checkUrl(URL url) throws IOException {
        if (url == null) return;
        String protocol = url.getProtocol();
        if (!isNetworkScheme(protocol)) return;
        if (!decideUrl("url", url.getHost(), url.getPath())) {
            throw new IOException("Blocked by Gboard network guard: " + url.getHost());
        }
    }

    /** Cronet newUrlRequestBuilder / newBidirectionalStreamBuilder. Never throws. */
    public static String filterCronetUrl(String url) {
        try {
            if (url == null) return null;
            Uri uri = Uri.parse(url);
            String scheme = uri.getScheme();
            if (scheme != null && !isNetworkScheme(scheme)) return url;
            if (decideUrl("cronet", uri.getHost(), uri.getPath())) return url;
            return BLOCKED_URL;
        } catch (Throwable t) {
            Log.w(TAG, "filterCronetUrl failed, blocking", t);
            return BLOCKED_URL;
        }
    }

    /** InetAddress.getByName / getAllByName, Network.getByName, SocketFactory.createSocket(String,..). */
    public static void checkHost(String host) throws UnknownHostException {
        if (host == null || host.isEmpty() || isIpLiteral(host)) return; // no DNS lookup happens
        if (!decideHost("dns", host)) {
            throw new UnknownHostException("Blocked by Gboard network guard: " + host);
        }
    }

    /** Socket.connect / SocketChannel.connect. */
    public static void checkSocketAddress(SocketAddress address) throws IOException {
        if (!(address instanceof InetSocketAddress)) return;
        InetSocketAddress inet = (InetSocketAddress) address;
        InetAddress resolved = inet.getAddress();
        if (resolved != null && (resolved.isLoopbackAddress() || resolved.isAnyLocalAddress())) return;
        // getHostString() never does a reverse lookup.
        String host = inet.getHostString();
        if (host == null && resolved != null) host = resolved.getHostAddress();
        if (!decideHost("socket", host)) {
            throw new IOException("Blocked by Gboard network guard: " + host);
        }
    }

    /** SocketFactory.createSocket(InetAddress, ..). */
    public static void checkInetAddress(InetAddress address) throws IOException {
        if (address == null || address.isLoopbackAddress() || address.isAnyLocalAddress()) return;
        // toString() is "hostname/1.2.3.4" (hostname may be empty) and never does a lookup.
        String text = address.toString();
        int slash = text.indexOf('/');
        String host = slash > 0 ? text.substring(0, slash) : address.getHostAddress();
        if (!decideHost("socket", host)) {
            throw new IOException("Blocked by Gboard network guard: " + host);
        }
    }

    /**
     * Context.bindService and friends. Returns false to refuse binding to Play services, in which
     * case the caller sees the same result as when the service is unavailable.
     */
    public static boolean allowServiceBind(Intent intent, Object connection) {
        try {
            if (intent == null) return true;
            String pkg = intent.getPackage();
            ComponentName component = intent.getComponent();
            if (pkg == null && component != null) pkg = component.getPackageName();
            if (!GMS_PACKAGE.equals(pkg)) return true;

            Config c = current();
            if (!c.enabled || !c.blockGms) return true;

            String action = intent.getAction();
            String target = action != null ? action
                    : component != null ? component.getClassName() : "(no action)";
            boolean allowed = c.allowsGms(target);
            record(c, allowed, "gms", target);
            if (!allowed && connection != null) {
                synchronized (refusedConnections) {
                    refusedConnections.put(connection, Boolean.TRUE);
                }
            }
            return allowed;
        } catch (Throwable t) {
            Log.w(TAG, "allowServiceBind failed, allowing", t);
            return true;
        }
    }

    /** Context.unbindService: skip connections whose bind was refused (unbinding them would throw). */
    public static boolean allowUnbind(Object connection) {
        if (connection == null) return true;
        synchronized (refusedConnections) {
            return refusedConnections.remove(connection) == null;
        }
    }

    private static final Map<Object, Boolean> refusedConnections = new WeakHashMap<>();

    /**
     * Called by the offline voice patch with Gboard's online (S3) recognizer, before Gboard decides
     * to use it. Returning null makes Gboard fall through to its on-device recognizers.
     */
    public static Object filterOnlineRecognizer(Object recognizer, Object sessionParams) {
        try {
            // Only English sessions: Gboard's on-device model is English, other languages keep
            // the stock (online) behaviour.
            if (recognizer != null && current().preferOfflineVoice && isEnglishSession(sessionParams)) {
                return null;
            }
        } catch (Throwable t) {
            Log.w(TAG, "filterOnlineRecognizer failed", t);
        }
        return recognizer;
    }

    /**
     * Replaces Gboard's "language equals en-US" check in the offline recognizer: any variant of the
     * same language (en-AU, en-GB, ...) counts. Gboard's language objects print as tags like "en-AU".
     */
    public static boolean sameLanguageFamily(Object language, Object other) {
        String a = languagePrefix(language == null ? null : language.toString());
        return a != null && a.equals(languagePrefix(other == null ? null : other.toString()));
    }

    /** Session params print like "oaa[audioInputStream=null, primaryLanguageTag=en-AU, ...]". */
    static boolean isEnglishSession(Object sessionParams) {
        if (sessionParams == null) return false;
        String s = sessionParams.toString();
        int i = s.indexOf("primaryLanguageTag=");
        if (i < 0) return false;
        int start = i + "primaryLanguageTag=".length();
        int end = start;
        while (end < s.length() && s.charAt(end) != ',' && s.charAt(end) != ']' && s.charAt(end) != ' ') end++;
        return "en".equals(languagePrefix(s.substring(start, end)));
    }

    static String languagePrefix(String tag) {
        if (tag == null) return null;
        String t = tag.trim().toLowerCase(Locale.ROOT);
        int cut = t.length();
        int dash = t.indexOf('-');
        int underscore = t.indexOf('_');
        if (dash >= 0) cut = Math.min(cut, dash);
        if (underscore >= 0) cut = Math.min(cut, underscore);
        return cut == 0 ? null : t.substring(0, cut);
    }

    /** Used by the offline voice patch: make sure the speech pack list always includes [extra]. */
    @SuppressWarnings({"rawtypes", "unchecked"})
    public static List withExtraLanguage(List tags, Object extra) {
        if (extra == null) return tags;
        if (tags != null && tags.contains(extra)) return tags;
        List result = tags == null ? new ArrayList() : new ArrayList(tags);
        result.add(extra);
        return result;
    }

    // endregion

    // region Decisions

    private static boolean decideUrl(String layer, String host, String path) {
        Config c = current();
        if (!c.enabled || isLocalHost(host)) return true;
        boolean allowed = c.allowsUrl(host, path);
        record(c, allowed, layer, host + (path == null ? "" : path));
        return allowed;
    }

    private static boolean decideHost(String layer, String host) {
        Config c = current();
        if (!c.enabled || isLocalHost(host)) return true;
        boolean allowed = c.allowsHost(host);
        record(c, allowed, layer, host);
        return allowed;
    }

    private static boolean isNetworkScheme(String scheme) {
        if (scheme == null) return false;
        String s = scheme.toLowerCase(Locale.ROOT);
        return s.equals("http") || s.equals("https") || s.equals("ftp")
                || s.equals("ws") || s.equals("wss");
    }

    private static boolean isLocalHost(String host) {
        if (host == null) return false;
        String h = normalizeHost(host);
        return h.equals("localhost") || h.equals("::1") || h.startsWith("127.") || h.equals("0.0.0.0");
    }

    static boolean isIpLiteral(String host) {
        if (host.indexOf(':') >= 0) return true; // IPv6
        for (int i = 0; i < host.length(); i++) {
            char c = host.charAt(i);
            if (c != '.' && (c < '0' || c > '9')) return false;
        }
        return true;
    }

    static String normalizeHost(String host) {
        String h = host.trim().toLowerCase(Locale.ROOT);
        if (h.startsWith("[") && h.endsWith("]")) h = h.substring(1, h.length() - 1);
        if (h.endsWith(".")) h = h.substring(0, h.length() - 1);
        return h;
    }

    // endregion

    // region Config

    static final class Rule {
        final String host;      // normalised, without "*."
        final boolean wildcard; // matches subdomains too
        final String pathPrefix; // "" = any path

        Rule(String host, boolean wildcard, String pathPrefix) {
            this.host = host;
            this.wildcard = wildcard;
            this.pathPrefix = pathPrefix;
        }

        boolean matchesHost(String h) {
            return h.equals(host) || (wildcard && h.endsWith("." + host));
        }

        /** Parses "host", "*.host", "host/path/prefix", optionally with a scheme and port. */
        static Rule parse(String line) {
            String s = line.trim();
            int hash = s.indexOf('#');
            if (hash >= 0) s = s.substring(0, hash).trim();
            if (s.isEmpty()) return null;
            int scheme = s.indexOf("://");
            if (scheme >= 0) s = s.substring(scheme + 3);
            String path = "";
            int slash = s.indexOf('/');
            if (slash >= 0) {
                path = s.substring(slash);
                s = s.substring(0, slash);
            }
            if (!s.startsWith("[")) {
                int colon = s.lastIndexOf(':');
                if (colon >= 0 && s.indexOf(':') == colon) s = s.substring(0, colon); // strip port
            }
            boolean wildcard = false;
            if (s.startsWith("*.")) {
                wildcard = true;
                s = s.substring(2);
            } else if (s.startsWith(".")) {
                wildcard = true;
                s = s.substring(1);
            }
            s = normalizeHost(s);
            if (s.isEmpty()) return null;
            if (path.equals("/")) path = "";
            return new Rule(s, wildcard, path);
        }
    }

    static final class Config {
        final boolean enabled;
        final boolean logging;
        final String rulesText;
        final List<Rule> rules;
        final boolean blockGms;
        final String gmsRulesText;
        final List<String> gmsRules;
        final boolean preferOfflineVoice;

        Config(boolean enabled, boolean logging, String rulesText, boolean blockGms, String gmsRulesText,
               boolean preferOfflineVoice) {
            this.enabled = enabled;
            this.preferOfflineVoice = preferOfflineVoice;
            this.logging = logging;
            this.blockGms = blockGms;
            this.gmsRulesText = gmsRulesText == null ? "" : gmsRulesText;
            List<String> gms = new ArrayList<>();
            for (String line : this.gmsRulesText.split("\n")) {
                String s = line.trim();
                int hash = s.indexOf('#');
                if (hash >= 0) s = s.substring(0, hash).trim();
                if (!s.isEmpty()) gms.add(s);
            }
            this.gmsRules = Collections.unmodifiableList(gms);
            this.rulesText = rulesText == null ? "" : rulesText;
            List<Rule> parsed = new ArrayList<>();
            for (String line : this.rulesText.split("\n")) {
                Rule r = Rule.parse(line);
                if (r != null) parsed.add(r);
            }
            this.rules = Collections.unmodifiableList(parsed);
        }

        /** Host level check (DNS / sockets): any rule for this host, regardless of its path. */
        boolean allowsHost(String host) {
            if (host == null) return false;
            String h = normalizeHost(host);
            for (Rule r : rules) if (r.matchesHost(h)) return true;
            return false;
        }

        /** Exact action / class name, or a prefix ending in '*'. */
        boolean allowsGms(String target) {
            for (String r : gmsRules) {
                if (r.endsWith("*") ? target.startsWith(r.substring(0, r.length() - 1)) : target.equals(r)) {
                    return true;
                }
            }
            return false;
        }

        boolean allowsUrl(String host, String path) {
            if (host == null) return false;
            String h = normalizeHost(host);
            String p = path == null || path.isEmpty() ? "/" : path;
            for (Rule r : rules) {
                if (r.matchesHost(h) && (r.pathPrefix.isEmpty() || p.startsWith(r.pathPrefix))) return true;
            }
            return false;
        }
    }

    static Config defaults() {
        return new Config(patchDefaultEnabled(), true, patchDefaultRules(), patchDefaultBlockGms(),
                patchDefaultGmsRules(), patchDefaultPreferOfflineVoice());
    }

    public static void init(Context context) {
        if (context == null) return;
        Context app = context.getApplicationContext();
        appContext = app != null ? app : context;
        lastReloadCheck = 0;
    }

    private static Context context() {
        Context c = appContext;
        if (c != null) return c;
        try {
            Object app = Class.forName("android.app.ActivityThread")
                    .getMethod("currentApplication").invoke(null);
            if (app instanceof Context) {
                appContext = (Context) app;
                return appContext;
            }
        } catch (Throwable ignored) {
        }
        return null;
    }

    /** Device protected storage, so the config is readable before the first unlock too. */
    static File storageDir(Context context) {
        Context storage = context;
        if (Build.VERSION.SDK_INT >= 24) {
            Context dp = context.createDeviceProtectedStorageContext();
            if (dp != null) storage = dp;
        }
        return storage.getFilesDir();
    }

    static Config current() {
        long now = System.currentTimeMillis();
        Config c = config;
        if (c != null && now - lastReloadCheck < RELOAD_INTERVAL_MS) return c;
        synchronized (NetworkGuard.class) {
            lastReloadCheck = now;
            c = config;
            Context ctx = context();
            if (ctx == null) {
                if (c == null) config = c = defaults();
                return c;
            }
            try {
                File file = new File(storageDir(ctx), CONFIG_FILE);
                long mtime = file.exists() ? file.lastModified() : 0;
                if (c == null || mtime != loadedMtime) {
                    c = mtime == 0 ? defaults() : load(file);
                    config = c;
                    loadedMtime = mtime;
                }
            } catch (Throwable t) {
                Log.w(TAG, "Could not load config", t);
                if (c == null) config = c = defaults();
            }
            return c;
        }
    }

    private static Config load(File file) throws IOException {
        Properties p = new Properties();
        InputStream in = new FileInputStream(file);
        try {
            p.load(in);
        } finally {
            in.close();
        }
        Config d = defaults();
        return new Config(
                Boolean.parseBoolean(p.getProperty(KEY_ENABLED, String.valueOf(d.enabled))),
                Boolean.parseBoolean(p.getProperty(KEY_LOGGING, String.valueOf(d.logging))),
                mergeNewDefaults(p.getProperty(KEY_RULES, d.rulesText),
                        p.getProperty(KEY_KNOWN_DEFAULT_RULES, ""), d.rulesText),
                Boolean.parseBoolean(p.getProperty(KEY_BLOCK_GMS, String.valueOf(d.blockGms))),
                mergeNewDefaults(p.getProperty(KEY_GMS_RULES, d.gmsRulesText),
                        p.getProperty(KEY_KNOWN_DEFAULT_GMS_RULES, ""), d.gmsRulesText),
                Boolean.parseBoolean(p.getProperty(KEY_PREFER_OFFLINE_VOICE,
                        String.valueOf(d.preferOfflineVoice))));
    }

    /**
     * Appends patch default lines that the saved list has never seen (added by a newer patch
     * version). Defaults the user already saw and removed stay removed.
     */
    static String mergeNewDefaults(String saved, String knownDefaults, String currentDefaults) {
        java.util.Set<String> savedLines = lineSet(saved);
        java.util.Set<String> known = lineSet(knownDefaults);
        StringBuilder out = new StringBuilder(saved == null ? "" : saved.trim());
        for (String line : currentDefaults.split("\n")) {
            String l = line.trim();
            if (l.isEmpty() || known.contains(l) || savedLines.contains(l)) continue;
            if (out.length() > 0) out.append('\n');
            out.append(l);
        }
        return out.toString();
    }

    private static java.util.Set<String> lineSet(String text) {
        java.util.Set<String> set = new java.util.HashSet<>();
        if (text == null) return set;
        for (String line : text.split("\n")) {
            String l = line.trim();
            if (!l.isEmpty()) set.add(l);
        }
        return set;
    }

    /** Called by the settings screen. */
    static void save(Context context, boolean enabled, boolean logging, String rules,
                     boolean blockGms, String gmsRules, boolean preferOfflineVoice) throws IOException {
        Properties p = new Properties();
        p.setProperty(KEY_ENABLED, String.valueOf(enabled));
        p.setProperty(KEY_LOGGING, String.valueOf(logging));
        p.setProperty(KEY_RULES, rules);
        p.setProperty(KEY_BLOCK_GMS, String.valueOf(blockGms));
        p.setProperty(KEY_GMS_RULES, gmsRules);
        p.setProperty(KEY_PREFER_OFFLINE_VOICE, String.valueOf(preferOfflineVoice));
        p.setProperty(KEY_KNOWN_DEFAULT_RULES, patchDefaultRules());
        p.setProperty(KEY_KNOWN_DEFAULT_GMS_RULES, patchDefaultGmsRules());
        File dir = storageDir(context);
        File tmp = new File(dir, CONFIG_FILE + ".tmp");
        OutputStream out = new FileOutputStream(tmp);
        try {
            p.store(out, "Gboard network guard");
        } finally {
            out.close();
        }
        File target = new File(dir, CONFIG_FILE);
        if (!tmp.renameTo(target)) throw new IOException("Could not write " + target);
        synchronized (NetworkGuard.class) {
            lastReloadCheck = 0;
        }
    }

    // endregion

    // region Log

    private static void record(Config c, boolean allowed, String layer, String target) {
        if (!c.logging) return;
        String key = (allowed ? "ALLOW " : "BLOCK ") + layer + " " + target;
        long now = System.currentTimeMillis();
        final String line;
        synchronized (LOG_LOCK) {
            // The same request usually shows up at several layers in a row; skip exact repeats.
            if (key.equals(lastLogKey) && now - lastLogTime < 5000) return;
            lastLogKey = key;
            lastLogTime = now;
            line = new SimpleDateFormat("MM-dd HH:mm:ss", Locale.US).format(new Date(now)) + " " + key;
            if (logWriter == null) logWriter = Executors.newSingleThreadExecutor(r -> {
                Thread t = new Thread(r, "GboardNetworkGuardLog");
                t.setDaemon(true);
                return t;
            });
        }
        final Context ctx = context();
        if (ctx == null) return;
        logWriter.execute(() -> appendLog(ctx, line));
    }

    private static void appendLog(Context ctx, String line) {
        try {
            File file = new File(storageDir(ctx), LOG_FILE);
            if (file.length() > MAX_LOG_BYTES) {
                // Keep the newest half.
                List<String> lines = readLog(ctx);
                Writer w = new FileWriter(file, false);
                try {
                    for (int i = lines.size() / 2; i < lines.size(); i++) w.write(lines.get(i) + "\n");
                } finally {
                    w.close();
                }
            }
            Writer w = new FileWriter(file, true);
            try {
                w.write(line + "\n");
            } finally {
                w.close();
            }
        } catch (Throwable t) {
            Log.w(TAG, "Could not write log", t);
        }
    }

    static List<String> readLog(Context ctx) {
        List<String> lines = new ArrayList<>();
        File file = new File(storageDir(ctx), LOG_FILE);
        if (!file.exists()) return lines;
        try {
            java.io.BufferedReader r = new java.io.BufferedReader(new java.io.FileReader(file));
            try {
                String l;
                while ((l = r.readLine()) != null) lines.add(l);
            } finally {
                r.close();
            }
        } catch (IOException e) {
            Log.w(TAG, "Could not read log", e);
        }
        return lines;
    }

    static void clearLog(Context ctx) {
        synchronized (LOG_LOCK) {
            lastLogKey = null;
        }
        //noinspection ResultOfMethodCallIgnored
        new File(storageDir(ctx), LOG_FILE).delete();
    }

    // endregion
}
