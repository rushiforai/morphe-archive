"""Generate NativeQuadFarLayouts.kt from the verified 5001712 patch plan.

  python -B -I tools/gen_kotlin.py <plan dir> <helper .so> <out .kt>

Only the standalone far-plane base (2.0.20/5001712) is emitted. Original bytes are pinned by
SHA-256 per site (the scene library is also modified by other patches, so only the owned regions are
pinned, plus the stock file size). Patched bytes are embedded in full.
"""
import hashlib
import json
import os
import sys

VERSIONS = {5001712: '2.0.20'}
BUILD_ID = 'GXR-NATIVE-QUAD-1.3-FARPLANE-ABI1'


def chunks(h, n=96):
    return [h[i:i + n] for i in range(0, len(h), n)]


def main():
    plan_dir, helper, out = sys.argv[1:4]
    hbytes = open(helper, 'rb').read()
    assert BUILD_ID.encode() in hbytes
    lines = [
        '// GENERATED by extensions/native-quad-far-plane/tools/gen_kotlin.py - do not edit by hand.',
        '// Source: build_patch_tables.py plan verified against the exact decoded 5001712 base.',
        'package app.template.patches.steamlink.binary',
        '',
        'internal const val NATIVE_QUAD_FAR_BUILD_ID = "%s"' % BUILD_ID,
        'internal const val NATIVE_QUAD_FAR_HELPER_SHA256 = "%s"' % hashlib.sha256(hbytes).hexdigest(),
        '',
        '/** One owned scene-library region: stock bytes pinned by SHA-256, replacement bytes in full. */',
        'internal class NativeQuadFarSite(val name: String, val offset: Int, val length: Int, '
        'val stockSha256: String, val patched: String)',
        '',
        '/** Exact-base layout. [size] is the stock scene library size; sites are file offsets (== virtual addresses). */',
        'internal class NativeQuadFarLayout(val versionName: String, val versionCode: String, val size: Int, '
        'val sites: List<NativeQuadFarSite>)',
        '',
        'internal val NATIVE_QUAD_FAR_LAYOUTS: Map<String, NativeQuadFarLayout> = listOf(',
    ]
    for code in sorted(VERSIONS):
        plan = json.load(open(os.path.join(plan_dir, '%d.json' % code)))
        d = plan['derived']
        lines.append('    NativeQuadFarLayout("%s", "%d", %d, listOf(' % (VERSIONS[code], code, d['size']))
        for p in plan['patches']:
            orig = bytes.fromhex(p['original'])
            lines.append('        NativeQuadFarSite("%s", 0x%x, %d, "%s",' % (
                p['name'], p['address'], p['length'], hashlib.sha256(orig).hexdigest()))
            cs = chunks(p['patched'])
            for i, c in enumerate(cs):
                lines.append('            "%s"%s' % (c, ' +' if i + 1 < len(cs) else ''))
            lines.append('        ),')
        lines.append('    )),')
    lines.append(').associateBy { it.versionCode }')
    with open(out, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


main()
