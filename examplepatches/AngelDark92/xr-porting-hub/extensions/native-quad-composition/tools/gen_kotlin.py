"""Generate NativeQuadLayouts.kt from the verified patch plans.

  python -B -I tools/gen_kotlin.py <plan dir> <helper .so> <out .kt>

Original bytes are pinned by SHA-256 per site (the scene library is also modified by other patches, so
only the owned regions are pinned, plus the stock file size). Patched bytes are embedded in full.
"""
import hashlib
import json
import os
import sys

VERSIONS = {5001712: '2.0.20', 5001812: '2.0.20', 5001968: '2.0.21', 5002244: '2.0.22', 5002363: '2.0.23',
            5002395: '2.0.24'}
BUILD_ID = 'GXR-NATIVE-QUAD-1.2-ABI1'


def chunks(h, n=96):
    return [h[i:i + n] for i in range(0, len(h), n)]


def main():
    plan_dir, helper, out = sys.argv[1:4]
    hbytes = open(helper, 'rb').read()
    assert BUILD_ID.encode() in hbytes
    lines = [
        '// GENERATED by extensions/native-quad-composition/tools/gen_kotlin.py - do not edit by hand.',
        '// Source: build_patch_tables.py plans verified against each exact decoded base.',
        'package app.template.patches.steamlink.binary',
        '',
        'internal const val NATIVE_QUAD_BUILD_ID = "%s"' % BUILD_ID,
        'internal const val NATIVE_QUAD_HELPER_SHA256 = "%s"' % hashlib.sha256(hbytes).hexdigest(),
        '',
        '/** One owned scene-library region: stock bytes pinned by SHA-256, replacement bytes in full. */',
        'internal class NativeQuadSite(val name: String, val offset: Int, val length: Int, val stockSha256: String, val patched: String)',
        '',
        '/** Exact-base layout. [size] is the stock scene library size; sites are file offsets (== virtual addresses). */',
        'internal class NativeQuadLayout(val versionName: String, val versionCode: String, val size: Int, val sites: List<NativeQuadSite>)',
        '',
        'internal val NATIVE_QUAD_LAYOUTS: Map<String, NativeQuadLayout> = listOf(',
    ]
    for code in sorted(VERSIONS):
        plan = json.load(open(os.path.join(plan_dir, '%d.json' % code)))
        d = plan['derived']
        lines.append('    NativeQuadLayout("%s", "%d", %d, listOf(' % (VERSIONS[code], code, d['size']))
        for p in plan['patches']:
            orig = bytes.fromhex(p['original'])
            lines.append('        NativeQuadSite("%s", 0x%x, %d, "%s",' % (
                p['name'], p['address'], p['length'], hashlib.sha256(orig).hexdigest()))
            cs = chunks(p['patched'])
            for i, c in enumerate(cs):
                lines.append('            "%s"%s' % (c, ' +' if i + 1 < len(cs) else ''))
            lines.append('        ),')
        lines.append('    )),')
    lines.append(').associateBy { it.versionCode }')
    with open(out, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


main()
