#!/usr/bin/env node
// Generates CountryData.java from an X-Posed checkout:
//   node tools/generate-country-data.mjs <x-account-location-device checkout>
// The tables are MIT licensed by Alexander Hagenah; see NOTICE.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const checkout = process.argv[2];
if (!checkout) {
    console.error('usage: generate-country-data.mjs <x-account-location-device checkout>');
    process.exit(2);
}
const root = resolve(checkout);
const shared = join(root, 'extension/src/shared');
const { COUNTRY_FLAGS, COUNTRY_ALIASES, REGION_DATA, LANGUAGE_DATA } = await import(pathToFileURL(join(shared, 'constants.js')));
const { REGION_GEOGRAPHY_GROUPS, REGION_GEOGRAPHY_NOTES } = await import(pathToFileURL(join(shared, 'region-geography.js')));
const { version } = JSON.parse(readFileSync(join(root, 'extension/package.json'), 'utf8'));
const commit = execFileSync('git', ['-C', root, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();

/** Java string literal with every non-ASCII UTF-16 unit escaped, so the source stays ASCII. */
function literal(text) {
    let out = '"';
    for (let i = 0; i < text.length; i++) {
        const c = text[i];
        const unit = text.charCodeAt(i);
        if (c === '"' || c === '\\') out += '\\' + c;
        else if (c === '\t') out += '\\t';
        else if (c === '\n') out += '\\n';
        else if (unit < 0x20 || unit > 0x7e) out += '\\u' + unit.toString(16).padStart(4, '0');
        else out += c;
    }
    return out + '"';
}

function block(name, doc, rows) {
    for (const row of rows) {
        for (const cell of row) {
            if (/[\t\n]/.test(cell)) throw new Error(`Separator inside ${name} cell: ${cell}`);
        }
    }
    const lines = rows.map(row => `            + ${literal(row.join('\t') + '\n')}`);
    return `    /** ${doc} */\n    static final String ${name} = ""\n${lines.join('\n')};\n`;
}

const flags = Object.entries(COUNTRY_FLAGS).sort(([a], [b]) => a.localeCompare(b));
const aliases = Object.entries(COUNTRY_ALIASES).sort(([a], [b]) => a.localeCompare(b));
const regions = REGION_DATA.map(region => {
    const members = REGION_GEOGRAPHY_GROUPS[region.key];
    const note = REGION_GEOGRAPHY_NOTES[region.key];
    if (!members || !note) throw new Error(`No geography for region ${region.key}`);
    for (const member of members) {
        if (!Object.hasOwn(COUNTRY_FLAGS, member)) throw new Error(`Region member without a flag: ${member}`);
        if (member.includes('|')) throw new Error(`Separator inside region member: ${member}`);
    }
    return [region.name, region.key, region.flag, note, members.join('|')];
});
const languages = LANGUAGE_DATA.map(language => [language.code]).sort(([a], [b]) => a.localeCompare(b));

const java = `package app.xposed.extension;

/**
 * Country and region tables of X-Posed ${version} (commit ${commit}, MIT, Alexander Hagenah):
 * COUNTRY_FLAGS, COUNTRY_ALIASES, REGION_DATA, the UN M49 based region memberships of
 * region-geography.js and the post languages of LANGUAGE_DATA. Generated by
 * tools/generate-country-data.mjs; do not edit.
 */
final class CountryData {
    static final String SOURCE = ${literal(`X-Posed ${version} (${commit})`)};

${block('FLAGS', 'Lowercase country name, tab, flag emoji; one per line.', flags)}
${block('ALIASES', 'Lowercase alternative name, tab, lowercase canonical name; one per line.', aliases)}
${block('REGIONS', 'Name, key, globe emoji, description and member names joined by |; tab separated, one per line.', regions)}
${block('LANGUAGES', 'Primary language subtags X-Posed offers as post language filters; one per line.', languages)}
    private CountryData() {
    }
}
`;

const target = new URL('../extensions/extension/src/main/java/app/xposed/extension/CountryData.java', import.meta.url);
writeFileSync(target, java);
console.log(`Wrote ${flags.length} flags, ${aliases.length} aliases, ${regions.length} regions and ${languages.length} languages from X-Posed ${version} (${commit}).`);
