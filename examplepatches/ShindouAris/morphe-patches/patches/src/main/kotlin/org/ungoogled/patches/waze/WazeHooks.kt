/** One insert of the Mod's own lines into a method of Waze, as generated by tools/waze_hooks_gen.py. */
internal class WazeInsert(
    /** Index of the stock instruction the lines go in front of. */
    val index: Int,
    /** The opcode that must be at [index]; a different one means this is not the Waze build the hook was made for. */
    val opcode: String,
    /** The previous line was a label: jumps to it must run the new lines too. */
    val atLabel: Boolean,
    /** How many instructions the lines assemble to. */
    val count: Int,
    /** Labels of the stock method the lines jump to: name to stock instruction index. */
    val externals: List<Pair<String, Int>>,
    /** try ranges as instruction offsets inside the lines: exception type (null = any), start, end, handler. */
    val catches: List<WazeCatch>,
    val smali: String,
)

internal class WazeCatch(val type: String?, val start: Int, val end: Int, val handler: Int)

internal class WazeMethodHooks(val cls: String, val signature: String, val inserts: List<WazeInsert>)

private fun normalized(opcode: String) = opcode.lowercase().filter { it.isLetterOrDigit() }

/** Reads waze/hooks.txt (generated) and waze/hooks_manual.txt (hand-written), the data files next to this patch. */
internal fun loadWazeHooks(): List<WazeMethodHooks> = readWazeHooks("hooks.txt") + readWazeHooks("hooks_manual.txt")

private fun readWazeHooks(file: String): List<WazeMethodHooks> {
    val stream = WazeHooksResource::class.java.getResourceAsStream("/waze/$file")
        ?: throw PatchException("waze/$file is missing from the patches file")
    val result = mutableListOf<WazeMethodHooks>()
    var cls = ""
    var signature = ""
    var inserts = mutableListOf<WazeInsert>()

    fun flush() {
        if (cls.isNotEmpty()) result += WazeMethodHooks(cls, signature, inserts)
        inserts = mutableListOf()
    }

    var index = 0
    var opcode = ""
    var atLabel = false
    var count = 0
    var externals = mutableListOf<Pair<String, Int>>()
    var catches = mutableListOf<WazeCatch>()
    val lines = StringBuilder()
    var open = false

    stream.bufferedReader(Charsets.UTF_8).useLines { all ->
        for (line in all) {
            when {
                open && line == "@end" -> {
                    inserts += WazeInsert(index, opcode, atLabel, count, externals, catches, lines.toString())
                    open = false
                }
                open && line.startsWith("@external ") -> {
                    val (name, target) = line.removePrefix("@external ").split(" ")
                    externals += name to target.toInt()
                }
                open && line.startsWith("@catch ") -> {
                    val (type, start, end, handler) = line.removePrefix("@catch ").split(" ")
                    catches += WazeCatch(type.takeIf { it != "-" }, start.toInt(), end.toInt(), handler.toInt())
                }
                open -> lines.appendLine(line)
                line.startsWith("@method ") -> {
                    flush()
                    val rest = line.removePrefix("@method ")
                    cls = rest.substringBefore(' ')
                    signature = rest.substringAfter(' ')
                }
                line.startsWith("@insert ") -> {
                    val p = line.removePrefix("@insert ").split(" ")
                    index = p[0].toInt(); opcode = p[1]; atLabel = p[2] == "1"; count = p[3].toInt()
                    externals = mutableListOf(); catches = mutableListOf(); lines.setLength(0)
                    open = true
                }
                line.isBlank() || line.startsWith("#") -> Unit
                else -> throw PatchException("waze/hooks.txt: cannot read line: $line")
            }
        }
    }
    flush()
    return result
}

/** Anchor for getResourceAsStream: the patches file's class loader finds waze/hooks.txt through any of its classes. */
private object WazeHooksResource

internal fun BytecodePatchContext.findWazeMethod(cls: String, signature: String): MutableMethod =
    mutableClassDefBy("L$cls;").methods.singleOrNull {
        it.name + "(" + it.parameterTypes.joinToString("") + ")" + it.returnType == signature
    } ?: throw PatchException("$cls->$signature not found: this is not the Waze build the hooks were made for")

/** Puts the lines of one insert into [method]; [applied] are the (stock index, size) of the inserts already made. */
private fun MutableMethod.applyInsert(hook: WazeInsert, applied: MutableList<Pair<Int, Int>>) {
    val at = getInstruction(hook.index)
    if (normalized(at.opcode.name) != normalized(hook.opcode)) {
        throw PatchException("$definingClass->$name: instruction ${hook.index} is ${at.opcode.name}, expected " +
            "${hook.opcode}: this is not the Waze build the hooks were made for")
    }
    // Waze's alignment nop in front of a switch payload comes and goes with the size of the code, it is not counted.
    fun size() = implementation!!.instructions.count { it.opcode != Opcode.NOP }
    val before = size()
    // A label at the very end of the lines marks the stock instruction after them, which is outside the lines: it is
    // an external label for the patcher.
    val lines = hook.smali.lines().filter { it.isNotBlank() }
    val trailing = mutableListOf<String>()
    val body = mutableListOf<String>()
    for ((i, line) in lines.withIndex()) {
        if (line.startsWith(":") && lines.drop(i).all { it.startsWith(":") || it.startsWith(".") }) {
            trailing += line.removePrefix(":")
        } else {
            body += line
        }
    }
    val smali = body.joinToString("\n")
    when {
        hook.externals.isNotEmpty() || trailing.isNotEmpty() || body.any { it.startsWith(":") } -> {
            if (hook.atLabel) throw PatchException("$definingClass->$name: labelled lines at a label")
            // A target already pushed down by the (later, higher) inserts made before this one.
            fun shifted(target: Int) = target + applied.filter { it.first <= target }.sumOf { it.second }
            val labels = hook.externals.map { (label, target) -> ExternalLabel(label.removePrefix(":"), shifted(target)) } +
                trailing.map { ExternalLabel(it, shifted(hook.index)) }
            addInstructionsWithLabels(hook.index, smali, *labels.toTypedArray())
        }
        hook.atLabel -> addInstructionsAtLabel(hook.index, hook.smali)
        else -> addInstructions(hook.index, hook.smali)
    }
    val added = size() - before
    if (added != hook.count) {
        throw PatchException("$definingClass->$name at ${hook.index}: ${hook.count} instructions expected, $added added")
    }
    for (c in hook.catches) {
        val impl = implementation!!
        val type = c.type?.let { ImmutableTypeReference(it) }
        impl.addCatch(type, impl.newLabelForIndex(hook.index + c.start), impl.newLabelForIndex(hook.index + c.end),
            impl.newLabelForIndex(hook.index + c.handler))
    }
    applied += hook.index to added
}

/** Adds a method without parameters that returns nothing to [cls], with [registers] registers (parameters included). */
internal fun BytecodePatchContext.addWazeMethod(cls: String, access: Int, name: String, registers: Int, smali: String) {
    val target = mutableClassDefBy("L$cls;")
    if (target.methods.any { it.name == name && it.parameterTypes.isEmpty() }) {
        throw PatchException("$cls->$name()V exists: this is not the Waze build the hooks were made for")
    }
    val method = MutableMethod(
        ImmutableMethod("L$cls;", name, emptyList<ImmutableMethodParameter>(), "V", access, null, null,
            MutableMethodImplementation(registers)),
    )
    method.addInstructions(0, smali)
    target.methods.add(method)
}

/** Adds a field without an initial value to [cls]. */
internal fun BytecodePatchContext.addWazeField(cls: String, access: Int, name: String, type: String) {
    val target = mutableClassDefBy("L$cls;")
    if (target.fields.any { it.name == name }) throw PatchException("$cls.$name exists")
    target.fields.add(ImmutableField("L$cls;", name, type, access, null, null, null).toMutable())
}

/** Applies every insert of [hooks], the highest index of a method first so the lower ones stay where they are. */
internal fun BytecodePatchContext.applyWazeHooks(hooks: List<WazeMethodHooks>) {
    for (entry in hooks) {
        val method = findWazeMethod(entry.cls, entry.signature)
        val applied = mutableListOf<Pair<Int, Int>>()
        for (insert in entry.inserts.sortedByDescending { it.index }) method.applyInsert(insert, applied)
    }
}
