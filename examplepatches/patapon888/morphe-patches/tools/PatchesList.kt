// Writes patches-list.json for a .mpp file, in the same format as the official Morphe patches repos.
// Usage: java -cp morphe-cli.jar:tools/out PatchesListKt <bundle.mpp> <version> <output.json>

import app.morphe.patcher.patch.PatchLoader
import java.io.File

private fun q(s: String?): String = if (s == null) "null" else buildString {
    append('"')
    for (c in s) when {
        c == '"' -> append("\\\"")
        c == '\\' -> append("\\\\")
        c == '\n' -> append("\\n")
        c == '\r' -> append("\\r")
        c == '\t' -> append("\\t")
        c < ' ' -> append("\\u%04x".format(c.code))
        else -> append(c)
    }
    append('"')
}

private fun value(v: Any?): String = when (v) {
    null -> "null"
    is String -> q(v)
    is Number, is Boolean -> v.toString()
    is Iterable<*> -> v.joinToString(", ", "[", "]") { value(it) }
    is Array<*> -> v.joinToString(", ", "[", "]") { value(it) }
    is Map<*, *> -> v.entries.joinToString(", ", "{", "}") { "${q(it.key.toString())}: ${value(it.value)}" }
    else -> q(v.toString())
}

private fun obj(indent: String, vararg fields: Pair<String, String>): String =
    fields.joinToString(",\n", "{\n", "\n$indent}") { (k, v) -> "$indent  ${q(k)}: $v" }

private fun list(indent: String, items: List<String>): String =
    if (items.isEmpty()) "[]" else items.joinToString(",\n", "[\n", "\n$indent]") { "$indent  $it" }

fun main(args: Array<String>) {
    val (mpp, version, out) = args
    val patches = PatchLoader.Jar(setOf(File(mpp))).filter { it.name != null }.sortedBy { it.name }
    val i = "    "
    val entries = patches.map { p ->
        val packages = p.compatibility?.map { c ->
            val targets = c.targets.map { t ->
                obj("$i      ",
                    "version" to q(t.version),
                    "versionCodes" to value(t.versionCodes?.mapKeys { it.key.name }),
                    "isExperimental" to t.isExperimental.toString(),
                    "minSdk" to value(t.minSdk),
                    "description" to q(t.description))
            }
            obj("$i    ",
                "packageName" to q(c.packageName),
                "name" to q(c.name),
                "description" to q(c.description),
                "apkFileType" to value(c.apkFileType?.name),
                "appIconColor" to value(c.appIconColor?.let { "#%06X".format(it and 0xFFFFFF) }),
                "signatures" to value(c.signatures),
                "targets" to list("$i      ", targets))
        }
        val options = p.options.values.map { o ->
            obj("$i    ",
                "key" to q(o.key),
                "title" to q(o.title),
                "description" to q(o.description),
                "required" to o.required.toString(),
                "type" to q(o.type.toString()),
                "default" to value(o.default),
                "values" to value(o.values))
        }
        obj(i,
            "name" to q(p.name),
            "description" to q(p.description),
            "default" to p.default.toString(),
            "category" to q(p.category),
            "compatiblePackages" to if (packages == null) "null" else list("$i  ", packages),
            "options" to list("$i  ", options))
    }
    val note = "Do NOT manually edit this file. It is generated by build.sh from the .mpp bundle."
    File(out).writeText("{\n  \"NOTE\": ${q(note)},\n  \"version\": ${q(version)},\n  \"patches\": ${list("  ", entries)}\n}\n")
    println("${patches.size} patches written to $out")
}
