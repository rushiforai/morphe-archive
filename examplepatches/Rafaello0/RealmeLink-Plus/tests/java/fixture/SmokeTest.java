package fixture;
import app.hxreborn.extension.realmelink.ModeKeeper;
import android.os.Handler;
import com.realme.iot.common.devices.Device;
import com.realme.iot.headset.activity.device.HeadsetDeviceActivity;
import com.realme.iot.headset.manager.HeadsetManager;
import com.realme.iot.headset.manager.HeadsetManagerProxy;
public class SmokeTest {
 private enum Status { CONNECTED, DISCONNECTED, CONNECTING, HEADSET_CONNECTED, HEADSET_DISCONNECTED, CONNECT_FAIL, DATA_SYNCING, A2DP_CONNECTED }
 private static void check(boolean v,String text){if(!v)throw new IllegalStateException(text);}
 public static void main(String[] args){
  HeadsetDeviceActivity a=new HeadsetDeviceActivity();
  ModeKeeper.initialize(a);ModeKeeper.enableNoiseControl();ModeKeeper.enableGameMode();
  Device bud=new Device("00:11:22:33:44:55");
  HeadsetManagerProxy m=HeadsetManager.getInstance();
  // Simulated UI writes learn settings; real headphones must still be tested.
  a.select(bud,12,2,0,1);
  a.select(bud,11,6,0,1);
  check(m.writes==0,"capture should not itself send commands");
  m.actual.put("001122334455:2:0",0);
  m.actual.put("001122334455:6:0",0);
  ModeKeeper.onDeviceReady(bud);Handler.drain();
  check(m.writes==2,"both saved modes must be restored exactly once");
  check(m.actual.get("001122334455:2:0")==1,"ANC mismatch");
  check(m.actual.get("001122334455:6:0")==1,"Game Mode mismatch");
  ModeKeeper.onDeviceReady(bud);Handler.drain();
  check(m.writes==2,"repeated connect must not flood commands");
  Device different=new Device("AA:BB:CC:DD:EE:FF");
  a.select(different,999,4,0,1);ModeKeeper.onDeviceReady(different);Handler.drain();
  check(m.writes==2,"unknown UI row must be ignored");
  check(ModeKeeper.setMaintained(bud,"anc",false),"disable ANC maintenance");
  ModeKeeper.onConnection(bud,false);
  m.actual.put("001122334455:2:0",0);
  m.actual.put("001122334455:6:0",0);
  ModeKeeper.onConnection(bud,true);Handler.drain();
  check(m.writes==3,"only enabled game restored");
  check(m.actual.get("001122334455:2:0")==0,"disabled ANC left unchanged");
  a.select(different,12,2,0,2);
  m.actual.put("AABBCCDDEEFF:2:0",0);
  ModeKeeper.onConnection(different,true);Handler.drain();
  check(m.actual.get("AABBCCDDEEFF:2:0")==2,"other pair independent");
  check(!ModeKeeper.isMaintained(bud,"anc") && ModeKeeper.isMaintained(different,"anc"),"independent preferences");
  ModeKeeper.onConnection(different,false);
  m.actual.remove("AABBCCDDEEFF:2:0");
  int before=m.writes;
  ModeKeeper.onConnection(different,true);Handler.drain();
  check(m.writes==before,"unknown read never writes");
  ModeKeeper.onConnection(bud,false);
  m.actual.put("001122334455:6:0",0);
  before=m.writes;
  ModeKeeper.onConnection(bud,true);
  ModeKeeper.onConnection(bud,false);
  Handler.drain();
  check(m.writes==before,"disconnect cancels pending check");
  ModeKeeper.onConnection(bud,true);
  Handler.advance(1700);
  m.actual.put("001122334455:6:0",0);
  Handler.drain();
  check(m.actual.get("001122334455:6:0")==1,"late reset restored");
  ModeKeeper.onConnection(bud,false);
  m.actual.put("001122334455:6:0",0);
  ModeKeeper.onConnection(bud,true);
  a.select(bud,11,6,0,0);
  before=m.writes;
  Handler.drain();
  check(m.writes==before,"new manual selection cancels old work");
  check(ModeKeeper.savedProfiles().length==2,"persisted profiles independent");
  check(ModeKeeper.setMaintainedFor("00:11:22:33:44:55","anc",true),"offline profile control");
  Handler.drain();
  m.actual.put("001122334455:2:0",0);
  ModeKeeper.onBluetoothEvent("00:11:22:33:44:55",true);
  ModeKeeper.onBluetoothEvent("00:11:22:33:44:55",true);
  Handler.drain();
  check(m.actual.get("001122334455:2:0")==1,"ACL reconnect restores known profile");
  before=m.writes;
  ModeKeeper.onBluetoothEvent("AA:00:00:00:00:01",true);
  ModeKeeper.onBluetoothEvent("00:11:22:33:44:55",false);
  Handler.drain();
  check(m.writes==before,"unknown ACL and disconnect do not write");
  check(!ModeKeeper.setMaintainedFor("00:11:22:33:44:5Z","anc",true),"invalid address rejected");
  check(ModeKeeper.activeProfile("00:11:22:33:44:55"),"active profile");
  check(!ModeKeeper.activeProfile("00:11:22:33:44:56"),"unknown profile");
  ModeKeeper.onVendorStatus(bud, Status.DISCONNECTED);
  Handler.drain();
  m.actual.put("001122334455:2:0",0);
  ModeKeeper.onVendorStatus(bud, Status.CONNECTED);
  Handler.drain();
  check(m.actual.get("001122334455:2:0")==1,"global status restores without presenter");
  before=m.writes;
  ModeKeeper.onVendorStatus(bud, Status.CONNECTING);
  Handler.drain();
  check(m.writes==before,"intermediate status ignored");
  ModeKeeper.onVendorStatus(bud, Status.CONNECT_FAIL);Handler.drain();
  m.actual.put("001122334455:2:0",0);
  m.rejectedReads=2;
  m.replyDelay=500;
  ModeKeeper.onVendorStatus(bud, Status.HEADSET_CONNECTED);
  Handler.drain();
  check(m.actual.get("001122334455:2:0")==1,"headset state and transient rejected read recovered");
  check(!ModeKeeper.hasPendingChecks("00:11:22:33:44:55"),"finished checks released");
  ModeKeeper.onVendorStatus(bud, Status.HEADSET_DISCONNECTED);Handler.drain();
  m.actual.put("001122334455:2:0",0);
  m.replyDelay=3000;
  before=m.writes;
  ModeKeeper.onDeviceReady(bud);Handler.drain();
  check(m.writes==before,"late reply after timeout ignored");
  m.replyDelay=500;
  ModeKeeper.onConnection(bud,false);
  m.conflictingReplies=true;
  ModeKeeper.onDeviceReady(bud);Handler.drain();
  check(m.writes==before,"conflicting replies never write");
  m.conflictingReplies=false;
  ModeKeeper.onConnection(bud,false);
  ModeKeeper.onDeviceReady(bud);
  Handler.advance(1700);
  check(ModeKeeper.hasPendingChecks("001122334455"),"in-flight request tracked");
  ModeKeeper.cancelPendingChecks("001122334455");
  Handler.drain();
  check(m.writes==before,"cancel invalidates delayed reply");
  check(!ModeKeeper.hasPendingChecks("001122334455"),"cancel releases session");
  m.replyDelay=0;
  ModeKeeper.onVendorStatus(bud,Status.A2DP_CONNECTED);Handler.drain();
  check(m.writes==before,"transport-only event not treated as ready");
  ModeKeeper.onVendorStatus(bud,Status.DATA_SYNCING);Handler.drain();
  check(m.actual.get("001122334455:2:0")==1,"data-syncing readiness with verified query");
  check("realme Buds Air7".equals(ModeKeeper.savedProfileName("00:11:22:33:44:55")), "vendor name persisted by profile");
  ProfileNameTest.run();
  System.out.println("SMOKE PASS: saved modes, read-before-write, verify, cooldown, unknown rows");
 }
}
