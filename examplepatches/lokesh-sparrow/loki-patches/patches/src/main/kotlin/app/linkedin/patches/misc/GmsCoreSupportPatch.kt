private const val LINKEDIN_PACKAGE = "com.linkedin.android"

/** SHA-1 of LinkedIn's signing certificate, which GmsCore presents to Google in place of the patched app's. */
private const val LINKEDIN_SIGNATURE = "443cb997718d0ac5162888bae5e4724582862676"

/** Vendor prefix that GmsCore (microG RE) uses in place of "com.google". */
private const val GMS_CORE_VENDOR = "app.revanced"

/** Points the app at GmsCore and declares the package and signature GmsCore spoofs for it. */
private val gmsCoreSupportResourcePatch = resourcePatch {
    execute {
        val manifest = get("AndroidManifest.xml")
        manifest.writeText(manifest.readText().replace("com.google.android.c2dm", "$GMS_CORE_VENDOR.android.c2dm"))

        document("AndroidManifest.xml").use { document ->
            val root = document.documentElement
            val application = document.getElementsByTagName("application").item(0) as Element
            fun Element.add(tag: String, vararg attributes: Pair<String, String>) {
                appendChild(document.createElement(tag).also { child ->
                    attributes.forEach { (name, value) -> child.setAttribute(name, value) }
                })
            }
            application.add(
                "meta-data",
                "android:name" to "$GMS_CORE_VENDOR.android.gms.SPOOFED_PACKAGE_NAME",
                "android:value" to LINKEDIN_PACKAGE,
            )
            application.add(
                "meta-data",
                "android:name" to "$GMS_CORE_VENDOR.android.gms.SPOOFED_PACKAGE_SIGNATURE",
                "android:value" to LINKEDIN_SIGNATURE,
            )
            application.add(
                "meta-data",
                "android:name" to "app.revanced.MICROG_PACKAGE_NAME",
                "android:value" to "$GMS_CORE_VENDOR.android.gms",
            )
            // Android 11+ hides packages the app doesn't declare.
            val queries = document.getElementsByTagName("queries").item(0) as? Element
                ?: document.createElement("queries").also { root.insertBefore(it, application) }
            queries.add("package", "android:name" to "$GMS_CORE_VENDOR.android.gms")
        }
    }
}

/**
 * Play services version from which Credential Manager uses the Identity Credentials API, which GmsCore doesn't
 * implement (androidx.credentials' PRE_U_MIN_GMS_APK_VERSION).
 */
private const val GMS_CORE_MAX_APK_VERSION = 252400000

/** Google Play services availability checks, which verify the signature of the Play services package. */
private const val PLAY_SERVICES_UTIL = "Lcom/google/android/gms/common/GooglePlayServicesUtilLight;"

/** Picks the Credential Manager provider: the system one on Android 14+, Play services' own below. */
private const val CREDENTIAL_PROVIDER_FACTORY = "Landroidx/credentials/CredentialProviderFactory;"

@Suppress("unused")
val gmsCoreSupportPatch = bytecodePatch(
    name = "GmsCore support",
    description = "Makes \"Continue with Google\" work in patched LinkedIn by signing in through microG RE " +
        "(GmsCore) instead of Google Play services. Needs microG RE installed and signed in to a Google account.",
    default = false
) {
    compatibleWith(COMPATIBILITY_LINKEDIN)
    dependsOn(settingsPatch, gmsCoreSupportResourcePatch)

    execute {
        val replacements = buildMap {
            put("com.google", GMS_CORE_VENDOR)
            put("com.google.android.gms", "$GMS_CORE_VENDOR.android.gms")
            (PERMISSIONS + ACTIONS + AUTHORITIES).forEach { put(it, it.replace("com.google", GMS_CORE_VENDOR)) }
        }
        fun replacement(string: String): String? = replacements[string]
            ?: AUTHORITIES.firstOrNull { string.startsWith("content://$it") }?.let {
                string.replace("content://$it", "content://${it.replace("com.google", GMS_CORE_VENDOR)}")
            }

        if (replaceStrings(::replacement) == 0) throw PatchException("No Google Play services strings found")

        // GmsCore is signed with its own key, so the signature checks of the availability calls would fail. It
        // reports as too old for the APIs that need Play services 25.24 or newer (Credential Manager's Identity
        // Credentials API, which GmsCore lacks), so the Google sign-in falls back to the one GmsCore implements.
        mutableClass(PLAY_SERVICES_UTIL).methods.forEach { method ->
            when (method.name) {
                "isGooglePlayServicesAvailable" -> method.addInstructions(
                    0,
                    """
                        const v0, $GMS_CORE_MAX_APK_VERSION
                        if-ge p1, v0, :too_old
                        const/4 v0, 0x0
                        return v0
                        :too_old
                        const/4 v0, 0x2
                        return v0
                    """
                )
                "ensurePlayServicesAvailable" -> method.addInstructions(0, "return-void")
            }
        }

        // The system Credential Manager asks the real Play services, which reject the patched app's signature.
        // Play services' own provider in the app goes through GmsCore instead.
        mutableClass(CREDENTIAL_PROVIDER_FACTORY).methods.first { it.name == "getBestAvailableProvider\$default" }
            .addInstructions(
                0,
                """
                    invoke-virtual { p0 }, $CREDENTIAL_PROVIDER_FACTORY->tryCreateClosedSourceProviderFromManifest()Landroidx/credentials/CredentialProvider;
                    move-result-object v0
                    return-object v0
                """
            )

        markIncluded("isGmsCoreSupportIncluded")
    }
}

/** The class with type [type]. */
private fun BytecodePatchContext.mutableClass(type: String): MutableClass {
    var found: MutableClass? = null
    classDefForEach { if (it.type == type) found = mutableClassDefBy(it) }
    return found ?: throw PatchException("$type not found")
}

/**
 * Replaces every string constant for which [replacement] returns a value. Returns how many were replaced.
 */
private fun BytecodePatchContext.replaceStrings(replacement: (String) -> String?): Int {
    val classes = mutableListOf<ClassDef>()
    classDefForEach { classDef ->
        if (classDef.methods.any { method ->
                method.implementation?.instructions?.any { it.stringConstant()?.let(replacement) != null } == true
            }) classes += classDef
    }
    var replaced = 0
    classes.forEach { classDef ->
        mutableClassDefBy(classDef).methods.forEach { method ->
            val instructions = method.implementation?.instructions?.toList() ?: return@forEach
            instructions.withIndex().forEach { (index, instruction) ->
                val to = instruction.stringConstant()?.let(replacement) ?: return@forEach
                val register = (instruction as OneRegisterInstruction).registerA
                val opcode = if (instruction.opcode == Opcode.CONST_STRING_JUMBO) "const-string/jumbo" else "const-string"
                method.replaceInstruction(index, "$opcode v$register, \"$to\"")
                replaced++
            }
        }
    }
    return replaced
}

private fun Instruction.stringConstant(): String? =
    if (opcode == Opcode.CONST_STRING || opcode == Opcode.CONST_STRING_JUMBO) {
        ((this as ReferenceInstruction).reference as StringReference).string
    } else null

