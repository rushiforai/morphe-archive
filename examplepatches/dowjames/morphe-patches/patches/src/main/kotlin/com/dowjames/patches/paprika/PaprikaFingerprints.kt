package com.dowjames.patches.paprika

import app.morphe.patcher.Fingerprint
import app.morphe.patcher.methodCall

// Paprika is a .NET-for-Android (Mono AOT) app: the premium gate lives in
// Paprika.Android.dll (PurchaseManager), which is AOT-compiled and cannot be
// IL-patched reliably. The billing bridge classes below are the Java-side
// Xamarin callable wrappers that hand Google Play Billing results into the
// managed code, so injecting a synthetic owned purchase here unlocks Premium
// before the managed PurchaseManager ever sees the real billing state.
//
// The crc64f0146600faa7a777 package is generated by the Xamarin.Android.Google
// BillingClient binding; it is stable for the pinned app version.

private const val PURCHASES_UPDATED_LISTENER_CLASS =
    "Lcrc64f0146600faa7a777/InternalPurchasesUpdatedListener;"

private const val PURCHASES_RESPONSE_LISTENER_CLASS =
    "Lcrc64f0146600faa7a777/InternalPurchasesResponseListener;"

/**
 * Fires when a purchase completes or billing state changes.
 * Forwards (BillingResult, List&lt;Purchase&gt;) to the managed listener.
 */
object PurchasesUpdatedListenerFingerprint : Fingerprint(
    definingClass = PURCHASES_UPDATED_LISTENER_CLASS,
    name = "onPurchasesUpdated",
    returnType = "V",
    parameters = listOf(
        "Lcom/android/billingclient/api/BillingResult;",
        "Ljava/util/List;",
    ),
    filters = listOf(
        methodCall(
            definingClass = PURCHASES_UPDATED_LISTENER_CLASS,
            name = "n_onPurchasesUpdated",
        )
    )
)

/**
 * Answers queryPurchasesAsync() with the list of owned purchases.
 * Forwards (BillingResult, List&lt;Purchase&gt;) to the managed listener.
 */
object PurchasesResponseListenerFingerprint : Fingerprint(
    definingClass = PURCHASES_RESPONSE_LISTENER_CLASS,
    name = "onQueryPurchasesResponse",
    returnType = "V",
    parameters = listOf(
        "Lcom/android/billingclient/api/BillingResult;",
        "Ljava/util/List;",
    ),
    filters = listOf(
        methodCall(
            definingClass = PURCHASES_RESPONSE_LISTENER_CLASS,
            name = "n_onQueryPurchasesResponse",
        )
    )
)
