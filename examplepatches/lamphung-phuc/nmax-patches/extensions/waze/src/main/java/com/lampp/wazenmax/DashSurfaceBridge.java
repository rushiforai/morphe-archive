package com.lampp.wazenmax;

import android.app.Activity;
import android.app.Application;
import android.content.Context;
import android.content.ContextWrapper;
import android.content.pm.ActivityInfo;
import android.content.res.Resources;
import android.graphics.Rect;
import android.os.Bundle;
import android.os.Handler;
import android.os.Looper;
import android.util.Log;
import android.view.Surface;
import android.view.SurfaceHolder;
import android.view.View;
import android.view.ViewGroup;

import com.lampp.nmaxconnect.dashui.DashCastUi;

import java.lang.ref.WeakReference;
import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.WeakHashMap;

/**
 * PoC: Data API calls 5/6 hand Waze's map renderer a Surface owned by a client app (the NMAX dash stream) in place of
 * the phone's SurfaceView, the same way Android Auto hands it the car screen. Detach gives the phone surface back.
 *
 * Hooks (smali): y.<init> → {@link #register}; y.addListener → {@link #listenerAdded}; x.surfaceCreated →
 * {@link #phoneSurface}; x.surfaceDestroyed → {@link #phoneSurfaceGone}; x.surfaceChanged → {@link #isActive};
 * {@link WazeDashService} calls 5-7 → {@link #attachDash} / {@link #detachDash} / {@link #isDashShown}; v.pause /
 * v.resume (map view Activity pause/resume) → {@link #mapPause} / {@link #mapResume}; Marker.setScale →
 * {@link #markerScale}. y is the phone map's surface
 * fan-out (com.waze.bl.k), j a renderer's surface callbacks. Waze's names are obfuscated and change per build, so they
 * are called by reflection with the names resolve.py found ({@link DashNames}, generated by patch.py).
 * Everything below runs on the main thread, where the SurfaceHolder callbacks already run.
 *
 * While a client offers a surface, a round cast button over the phone map moves the map between the dash and the
 * phone, the phone shows "Map is on the dash" (touch-proof) while the dash has it, and Waze stays portrait; the client
 * asks where it is with call 7 ({@link #isDashShown}) and shows a card on the dash while it is on the phone.
 */
public final class DashSurfaceBridge {
    private static final String TAG = "WazeNmaxDash";
    private static final long WATCHDOG_MS = 2_000L;
    private static final float PIN_SHRINK = 0.5f;
    private static final Handler MAIN = new Handler(Looper.getMainLooper());

    /** Every phone fan-out and its live phone holder (null while the phone has no surface). */
    private static final Map<Object, SurfaceHolder> FANS = new WeakHashMap<>();
    /** Every map view the Activity lifecycle drives, and whether it is paused (render thread wanted off). */
    private static final Map<Object, Boolean> PAUSED = new WeakHashMap<>();
    /** The client's surface; kept while the rider has the map on the phone ({@link #onPhone}). */
    private static volatile Surface dash;
    private static volatile boolean onPhone;
    private static int width;
    private static int height;
    private static volatile int dpi;
    private static boolean watching;
    private static WeakReference<Activity> resumed = new WeakReference<>(null);
    private static WeakReference<Activity> mapActivity = new WeakReference<>(null);
    private static WeakReference<Activity> locked = new WeakReference<>(null);
    private static int unlockedOrientation;

    private DashSurfaceBridge() {
    }

    public static void register(Object fan) {
        synchronized (FANS) {
            if (FANS.containsKey(fan)) return;
            FANS.put(fan, null);
        }
        watchActivities();
        // Resolve every reflected name now, so a mismatch shows in logcat (the update check greps it), not mid-ride.
        try {
            Log.i(TAG, "names OK (" + W.Z_RUNNER + ", " + W.Z + ")");
        } catch (Throwable e) {
            Log.e(TAG, "names BROKEN", e);
        }
    }

    /** Records the phone holder (null = destroyed); true while the dash owns the map, so the caller skips its work. */
    public static boolean phoneSurface(Object fan, SurfaceHolder holder) {
        synchronized (FANS) {
            FANS.put(fan, holder);
        }
        return owns();
    }

    /**
     * x.surfaceDestroyed. Screen off or Waze in the background: the view stays, and so does the dash. A closed view
     * (the route preview's map, when navigation starts) still holds the dash surface, so the map that stays could
     * never draw into it and the dash froze on the preview: once the view has left its window, its renderers let go
     * and the dash surface is handed out again.
     */
    public static boolean phoneSurfaceGone(Object fan, View view) {
        boolean owned = phoneSurface(fan, null);
        if (owned) MAIN.post(() -> dropIfClosed(fan, view)); // after the detach, when isAttachedToWindow says
        return owned;
    }

    private static void dropIfClosed(Object fan, View view) {
        if (!owns() || view.isAttachedToWindow()) return;
        for (Object l : listeners(fan)) call(W.J_GONE, l);
        synchronized (FANS) {
            FANS.remove(fan);
        }
        handTo(dash, width, height, dpi, true);
        Log.i(TAG, "map view closed, dash surface handed to " + fans().size() + " map(s)");
    }

    /**
     * v.pause (Activity paused, e.g. screen off): true = skip it, the dash still needs frames; {@link #giveBack}
     * replays it.
     */
    public static boolean mapPause(Object map) {
        PAUSED.put(map, Boolean.TRUE);
        return owns();
    }

    public static void mapResume(Object map) {
        PAUSED.put(map, Boolean.FALSE);
        MAIN.post(DashSurfaceBridge::updateToggle); // the map's Activity is back: its cast button and note
    }

    /**
     * Marker.setScale (map pins): their bitmaps are drawn at the phone's density, so on the dash's lower dpi they come
     * out too big; shrink them by the ratio, then by {@link #PIN_SHRINK} (the ratio alone left them twice the share of
     * the frame they take of the phone screen). Any thread; pins built before attach keep their size until Waze
     * rebuilds the map content.
     */
    public static float markerScale(float scale) {
        int d = dpi;
        if (!owns() || d <= 0) return scale;
        return scale * PIN_SHRINK * d / Resources.getSystem().getDisplayMetrics().densityDpi;
    }

    public static boolean isActive(Object fan) {
        return owns();
    }

    /** The dash has the map: a client surface is attached and the rider has not taken the map to the phone. */
    private static boolean owns() {
        return dash != null && !onPhone;
    }

    public static void listenerAdded(Object fan, Object listener) {
        if (!owns()) return;
        surfaceReady(listener, dash, width, height, dpi);
    }

    /** Binder thread; {@link WazeDashService} already checked the caller. */
    static void attachDash(Surface s, int w, int h, int d) {
        MAIN.post(() -> attach(s, w, h, d));
    }

    static void detachDash() {
        MAIN.post(DashSurfaceBridge::detach);
    }

    static boolean isDashShown() {
        return owns();
    }

    private static List<Object> fans() {
        synchronized (FANS) {
            return new ArrayList<>(FANS.keySet());
        }
    }

    private static List<Object> listeners(Object fan) {
        return new ArrayList<Object>((List<?>) call(W.Y_LISTENERS, fan));
    }

    private static void surfaceReady(Object listener, Surface s, int w, int h, int d) {
        call(W.J_READY, listener, s, w, h, d);
        call(W.J_RESIZED, listener, w, h, d);
    }

    private static void attach(Surface s, int w, int h, int d) {
        if (s == null || !s.isValid() || w <= 0 || h <= 0) {
            Log.w(TAG, "attach ignored: invalid surface " + w + "x" + h);
            return;
        }
        boolean owned = owns();
        Surface old = dash;
        dash = s;
        width = w;
        height = h;
        dpi = d;
        if (!onPhone) handTo(s, w, h, d, owned);
        if (old != null && old != s) old.release();
        Log.i(TAG, "dash surface attached " + w + "x" + h + "@" + d + " to " + fans().size() + " map(s)"
                + (onPhone ? ", map stays on the phone" : ""));
        MAIN.removeCallbacks(WATCHDOG);
        MAIN.postDelayed(WATCHDOG, WATCHDOG_MS);
        updateToggle();
    }

    /** Takes the map off the phone (or off an older dash surface, {@code owned}) and gives it to {@code s}. */
    private static void handTo(Surface s, int w, int h, int d, boolean owned) {
        for (Object fan : fans()) {
            boolean hadSurface = owned || phoneHolder(fan) != null;
            if (hadSurface) for (Object l : listeners(fan)) call(W.J_GONE, l);
            call(W.Y_HOLDER, fan, (Object) null); // late listeners must not get the phone surface (addListener hands it out)
        }
        for (Object fan : fans()) {
            for (Object l : listeners(fan)) surfaceReady(l, s, w, h, d);
        }
        // Waze already in the background: its render thread was stopped by the pause, start it for the dash.
        for (Object map : pausedMaps()) {
            if (W.running(map)) continue;
            call(W.V_RESUME, map);
            PAUSED.put(map, Boolean.TRUE);
        }
    }

    private static void detach() {
        if (dash == null) return;
        if (owns()) giveBack();
        dash.release();
        dash = null;
        MAIN.removeCallbacks(WATCHDOG);
        updateToggle();
        Log.i(TAG, "dash surface detached");
    }

    /** The rider's tap: the map to the phone, or back to the dash. */
    private static void flip() {
        Surface s = dash;
        if (s == null) return;
        if (onPhone) {
            onPhone = false;
            handTo(s, width, height, dpi, false);
        } else {
            giveBack();
            onPhone = true;
        }
        Log.i(TAG, "map on the " + (onPhone ? "phone" : "dash"));
        updateToggle();
    }

    /** The dash's renderers go back to the phone holders; the pauses skipped meanwhile are replayed. */
    private static void giveBack() {
        for (Object fan : fans()) for (Object l : listeners(fan)) call(W.J_GONE, l);
        int phoneDpi = Resources.getSystem().getDisplayMetrics().densityDpi;
        for (Object fan : fans()) {
            SurfaceHolder holder = phoneHolder(fan);
            if (holder == null || !holder.getSurface().isValid()) continue;
            Rect r = holder.getSurfaceFrame();
            call(W.Y_HOLDER, fan, holder);
            call(W.Y_WIDTH, fan, r.width());
            call(W.Y_HEIGHT, fan, r.height());
            call(W.Y_DPI, fan, phoneDpi);
            for (Object l : listeners(fan)) surfaceReady(l, holder.getSurface(), r.width(), r.height(), phoneDpi);
        }
        for (Object map : pausedMaps()) call(W.V_PAUSE, map); // the pauses skipped while the dash owned the map
    }

    /** Tracks the resumed Activity, so the button goes on the one that shows the map. */
    private static void watchActivities() {
        if (watching) return;
        watching = true;
        Application app;
        try {
            app = (Application) Class.forName("android.app.ActivityThread").getMethod("currentApplication").invoke(null);
        } catch (ReflectiveOperationException e) {
            Log.w(TAG, "no Application, no dash button", e);
            return;
        }
        app.registerActivityLifecycleCallbacks(new Application.ActivityLifecycleCallbacks() {
            @Override
            public void onActivityResumed(Activity a) {
                resumed = new WeakReference<>(a);
                updateToggle();
            }

            @Override
            public void onActivityPaused(Activity a) {
                if (resumed.get() == a) resumed = new WeakReference<>(null);
            }

            @Override
            public void onActivityCreated(Activity a, Bundle b) {
            }

            @Override
            public void onActivityStarted(Activity a) {
            }

            @Override
            public void onActivityStopped(Activity a) {
            }

            @Override
            public void onActivitySaveInstanceState(Activity a, Bundle b) {
            }

            @Override
            public void onActivityDestroyed(Activity a) {
            }
        });
    }

    /**
     * The cast button and "Map is on the dash" note (shared DashCastUi; the map view swallows touches meanwhile, so a
     * pan can't move the dash map unseen), and portrait while a client offers a surface (a
     * rotation re-lays Waze out and moves its map, and the dash map with it). On the last resumed Activity showing the
     * map, so a detach in the background still clears it.
     */
    private static void updateToggle() {
        Activity r = resumed.get();
        // Waze can resume its Activity before the map registers the lifecycle callbacks (cold start): then the
        // running map view, which the pause/resume hooks already track, gives it.
        if (r == null) {
            for (Map.Entry<Object, Boolean> e : PAUSED.entrySet()) {
                if (e.getKey() instanceof View && !e.getValue() && ((View) e.getKey()).isAttachedToWindow()) {
                    r = activityOf((View) e.getKey());
                    if (r != null) break;
                }
            }
        }
        if (r != null && dash != null) {
            ViewGroup content = r.findViewById(android.R.id.content);
            if (content != null && findMap(content) != null) mapActivity = new WeakReference<>(r);
        }
        Activity a = mapActivity.get();
        if (a == null) return;
        ViewGroup content = a.findViewById(android.R.id.content);
        View map = content == null ? null : findMap(content);
        lockOrientation(a, dash != null);
        DashCastUi.update(a, map, dash != null && map != null, owns(), DashSurfaceBridge::flip, true);
    }

    private static void lockOrientation(Activity a, boolean lock) {
        Activity was = locked.get();
        if (lock && was != a) {
            unlockedOrientation = a.getRequestedOrientation();
            a.setRequestedOrientation(ActivityInfo.SCREEN_ORIENTATION_PORTRAIT);
            locked = new WeakReference<>(a);
        } else if (!lock && was == a) {
            a.setRequestedOrientation(unlockedOrientation);
            locked = new WeakReference<>(null);
        }
    }

    private static Activity activityOf(View v) {
        Context c = v.getContext();
        while (c instanceof ContextWrapper && !(c instanceof Activity)) c = ((ContextWrapper) c).getBaseContext();
        return c instanceof Activity ? (Activity) c : null;
    }

    /** Waze's map SurfaceView in the tree, null if this screen has none (the button stays off Waze's other screens). */
    private static View findMap(View v) {
        if (W.Z.isInstance(v)) return v;
        if (!(v instanceof ViewGroup)) return null;
        ViewGroup g = (ViewGroup) v;
        for (int i = 0; i < g.getChildCount(); i++) {
            View m = findMap(g.getChildAt(i));
            if (m != null) return m;
        }
        return null;
    }

    private static List<Object> pausedMaps() {
        List<Object> out = new ArrayList<>();
        for (Map.Entry<Object, Boolean> e : PAUSED.entrySet()) if (e.getValue()) out.add(e.getKey());
        return out;
    }

    private static SurfaceHolder phoneHolder(Object fan) {
        synchronized (FANS) {
            return FANS.get(fan);
        }
    }

    private static Object call(Method m, Object target, Object... args) {
        try {
            return m.invoke(target, args);
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException(m.toString(), e);
        }
    }

    /** The client died or dropped its ImageReader: give the map back to the phone. */
    private static final Runnable WATCHDOG = new Runnable() {
        @Override
        public void run() {
            if (dash == null) return;
            if (!dash.isValid()) {
                Log.i(TAG, "dash surface gone");
                detach();
            } else {
                MAIN.postDelayed(this, WATCHDOG_MS);
            }
        }
    };

    /** Waze's methods, looked up once by the names resolve.py found in this build. */
    private static final class W {
        static final Method J_READY = find(DashNames.J, DashNames.J_SURFACE_READY, Surface.class, int.class, int.class,
                int.class);
        static final Method J_RESIZED = find(DashNames.J, DashNames.J_RESIZED, int.class, int.class, int.class);
        static final Method J_GONE = find(DashNames.J, DashNames.J_GONE);
        static final Method Y_LISTENERS = find(DashNames.Y, DashNames.Y_LISTENERS);
        static final Method Y_HOLDER = find(DashNames.Y, DashNames.Y_SET_HOLDER, SurfaceHolder.class);
        static final Method Y_WIDTH = find(DashNames.Y, DashNames.Y_SET_WIDTH, Integer.class);
        static final Method Y_HEIGHT = find(DashNames.Y, DashNames.Y_SET_HEIGHT, Integer.class);
        static final Method Y_DPI = find(DashNames.Y, DashNames.Y_SET_DPI, Integer.class);
        static final Method V_PAUSE = find(DashNames.V, DashNames.V_PAUSE);
        static final Method V_RESUME = find(DashNames.V, DashNames.V_RESUME);
        static final Field Z_RUNNER = field(DashNames.Z, DashNames.Z_RUNNER);
        /** The phone map's SurfaceView. */
        static final Class<?> Z = load(DashNames.Z);

        /** The map's render thread runs while z's runner field is set (5.27 has no getter left for it). */
        static boolean running(Object map) {
            try {
                return Z_RUNNER.get(map) != null;
            } catch (IllegalAccessException e) {
                throw new IllegalStateException(Z_RUNNER.toString(), e);
            }
        }

        private static Field field(String cls, String name) {
            try {
                Field f = load(cls).getDeclaredField(name);
                f.setAccessible(true);
                return f;
            } catch (NoSuchFieldException e) {
                throw new IllegalStateException("Waze build does not match DashNames", e);
            }
        }

        private static Class<?> load(String cls) {
            try {
                return Class.forName(cls, false, DashSurfaceBridge.class.getClassLoader());
            } catch (ClassNotFoundException e) {
                throw new IllegalStateException("Waze build does not match DashNames", e);
            }
        }

        /** Declared method on the class or a superclass (z.running lives on v's parent), made callable. */
        private static Method find(String cls, String name, Class<?>... params) {
            try {
                for (Class<?> c = Class.forName(cls, false, DashSurfaceBridge.class.getClassLoader()); c != null;
                     c = c.getSuperclass()) {
                    try {
                        Method m = c.getDeclaredMethod(name, params);
                        m.setAccessible(true);
                        return m;
                    } catch (NoSuchMethodException ignored) {
                        // try the superclass
                    }
                }
                throw new NoSuchMethodException(cls + "." + name);
            } catch (ReflectiveOperationException e) {
                throw new IllegalStateException("Waze build does not match DashNames", e);
            }
        }
    }
}
