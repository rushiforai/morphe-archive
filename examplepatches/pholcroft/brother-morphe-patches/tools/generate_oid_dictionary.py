#!/usr/bin/env python3
"""Validate the contributor-edited OID dictionary and generate the Android lookup."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/oid-dictionary.json"
TARGET = ROOT / "extensions/extension/src/main/java/app/template/extension/extension/OidDictionary.java"

def generate():
    entries = json.loads(SOURCE.read_text(encoding="utf-8"))
    seen = set()
    for e in entries:
        required = {"oid", "symbol", "name", "description", "source"}
        if not required <= set(e) or set(e) - required - {"values", "values_source"}:
            raise ValueError("Each entry needs oid, symbol, name, description and source")
        if not all(isinstance(e[k], str) and e[k].strip() for k in required):
            raise ValueError("Every required field must be a non-empty string")
        if ("values" in e) != ("values_source" in e):
            raise ValueError("Value meanings require a values_source")
        if "values" in e:
            if not isinstance(e["values_source"], str) or not e["values_source"].startswith("https://"):
                raise ValueError("Value meanings require an HTTPS source")
            if not isinstance(e["values"], dict) or not e["values"]:
                raise ValueError("values must be a non-empty object of integer strings")
            for key, meaning in e["values"].items():
                if not re.fullmatch(r"-?(?:0|[1-9][0-9]*)", key) or not isinstance(meaning, str) or not meaning.strip():
                    raise ValueError("Invalid integer value or meaning: " + str(key))
        if not re.fullmatch(r"(?:0|[1-9][0-9]*)(?:\.(?:0|[1-9][0-9]*))+", e["oid"]):
            raise ValueError("Invalid numeric OID: " + e["oid"])
        if e["oid"] in seen or not e["source"].startswith("https://"):
            raise ValueError("Duplicate OID or invalid source: " + e["oid"])
        seen.add(e["oid"])
    def q(s): return json.dumps(s, ensure_ascii=True)
    lines = ["package app.template.extension.extension;", "", "// Generated by tools/generate_oid_dictionary.py; edit data/oid-dictionary.json.", "public final class OidDictionary {", "    public static final class Entry {", "        public final String oid, symbol, name, description, source, valuesSource; private final String[][] values;", "        Entry(String oid,String symbol,String name,String description,String source,String valuesSource,String[][] values){this.oid=oid;this.symbol=symbol;this.name=name;this.description=description;this.source=source;this.valuesSource=valuesSource;this.values=values;}", "        public String valueMeaning(String encoded){if(encoded==null||!encoded.startsWith(\"integer:\"))return null;String number=encoded.substring(8);for(String[] value:values)if(value[0].equals(number))return value[1];return null;}", "    }", "    private static final Entry[] ENTRIES={"]
    for e in sorted(entries, key=lambda x: (-len(x["oid"]), x["oid"])):
        pairs = ",".join("{" + q(k) + "," + q(v) + "}" for k, v in sorted(e.get("values", {}).items(), key=lambda pair: int(pair[0])))
        lines.append("        new Entry(" + ",".join(q(e[k]) for k in ("oid", "symbol", "name", "description", "source")) + "," + q(e.get("values_source", "")) + ",new String[][]{" + pairs + "}),")
    lines += ["    };", "    public static Entry lookup(String oid){if(oid==null)return null;for(Entry e:ENTRIES)if(oid.equals(e.oid)||oid.startsWith(e.oid+\".\"))return e;return null;}", "    private OidDictionary(){}", "}", ""]
    return "\n".join(lines)

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    result = parser.parse_args()
    generated = generate()
    if result.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") != generated:
            raise SystemExit("Generated dictionary is stale; run python tools/generate_oid_dictionary.py")
        print("Dictionary is up to date")
    else:
        TARGET.write_text(generated, encoding="utf-8", newline="\n")
