def source(root, cls):
    matches = list(root.glob('smali*/'+cls+'.smali')) + list(root.glob('smali/smali*/'+cls+'.smali'))
    assert len(matches) == 1, cls
    return matches[0].read_text()


def code(root, cls, sig, skip=0):
    return [x.replace('const-string/jumbo ', 'const-string ') for x in canonical_method(root, cls, sig, skip)]


def digest(lines):
    return hashlib.sha256('\n'.join(lines).encode()).hexdigest()


def emitted(root, cls, sig, args):
    """Execute emitted helpers against boundary values; expectations stay literal."""
    instructions = code(root, cls, sig)
    regs = {'p'+str(i): v for i,v in enumerate(args)}
    result, pc = None, 0
    for _ in range(10000):
        line = instructions[pc]; pc += 1
        if line.startswith('const-string '):
            dest,literal=line.split(' ',1)[1].split(', ',1);regs[dest]=smali_string(literal)
        elif line.startswith(('const/4 ','const/16 ')):
            dest,v=line.split(' ',1)[1].split(', ');regs[dest]=int(v,16)
        elif line.startswith('move-result'):regs[line.split()[1]]=result
        elif line.startswith(('move-object ','move ')):
            dest,src=line.split(' ',1)[1].split(', ');regs[dest]=regs[src]
        elif line.startswith('sget-object '):regs[line.split()[1].strip(',')]='Locale.US'
        elif line.startswith('new-instance '):
            dest,typ=line.split(' ',1)[1].split(', ');regs[dest]=[] if typ=='Ljava/util/ArrayList;' else {'type':typ}
        elif line.startswith('new-array '):
            dest,count,typ=line.split(' ',1)[1].split(', ');assert typ=='[B';regs[dest]=bytes(regs[count])
        elif line.startswith('check-cast '):pass
        elif line.startswith('invoke-'):
            ns=line.split('{',1)[1].split('}',1)[0]
            if ' .. ' in ns:
                start,end=ns.split(' .. ');names=[start[0]+str(i) for i in range(int(start[1:]),int(end[1:])+1)]
            else:names=ns.split(', ') if ns else []
            values=[regs[n] for n in names]
            ref=line.split('}, ',1)[1]
            owner,target=ref.split('->')
            if target.startswith('morphe'):result=emitted(root,owner[1:-1],target,values)
            elif 'Uri;->parse' in ref:
                try:result=urlsplit(values[0])
                except ValueError:result=None
            elif 'Uri;->getHost' in ref:result=(urlsplit(values[0]) if isinstance(values[0],str) else values[0]).hostname if values[0] else None
            elif 'Uri;->getScheme' in ref:result=(urlsplit(values[0]) if isinstance(values[0],str) else values[0]).scheme if values[0] else None
            elif 'Uri;->getEncodedPath' in ref:result=(urlsplit(values[0]) if isinstance(values[0],str) else values[0]).path if values[0] else None
            elif 'Uri;->toString' in ref:result=values[0]
            elif 'WebResourceRequest;->getUrl' in ref:result=values[0]['url']
            elif 'WebResourceRequest;->getMethod' in ref:result=values[0].get('method','GET')
            elif 'WebResourceRequest;->isForMainFrame' in ref:result=values[0].get('main',False)
            elif 'String;->toLowerCase' in ref:result=values[0].lower()
            elif 'String;->equals' in ref:result=values[0]==values[1]
            elif 'String;->matches' in ref:result=re.fullmatch(values[1],values[0]) is not None
            elif 'List;->isEmpty' in ref:result=not values[0]
            elif 'List;->iterator' in ref or 'Iterable;->iterator' in ref:result={'values':iter(values[0]),'next':None}
            elif 'Iterator;->hasNext' in ref:
                try:values[0]['next']=next(values[0]['values']);result=True
                except StopIteration:result=False
            elif 'Iterator;->next' in ref:result=values[0]['next']
            elif 'NRCReaderPage;->getPage' in ref:result=values[0]['page']
            elif 'Page;->getFrames' in ref:result=values[0]['frames']
            elif 'PageFrame;->isAdvertisement' in ref:result=values[0]['ad']
            elif 'List;->add' in ref or 'ArrayList;->add' in ref:values[0].append(values[1]);result=True
            elif 'ArrayList;-><init>' in ref:pass
            elif 'ByteArrayInputStream;-><init>' in ref:values[0]['bytes']=values[1]
            elif 'WebResourceResponse;-><init>' in ref:
                if len(values)==4:values[0].update(status=200,mime=values[1],stream=values[3])
                else:values[0].update(status=values[3],mime=values[1],stream=values[6])
            elif 'Collections;->emptyMap' in ref:result={}
            elif 'Collections;->emptyList' in ref:result=[]
            elif 'AdvertisingIdClient$Info;-><init>' in ref:values[0].update(id=values[1],limited=values[2])
            else:raise AssertionError('Unsupported emitted operation: '+line)
        elif line.startswith(('if-eqz ','if-nez ')):
            op,reg,target=line.replace(',','').split()
            if bool(regs[reg])==(op=='if-nez'):pc=int(target[1:])
        elif line.startswith('goto'):pc=int(line.split()[1][1:])
        elif line=='return-void':return None
        elif line.startswith(('return-object ','return ')):return regs[line.split()[1]]
        else:raise AssertionError('Unsupported emitted instruction: '+line)
    raise AssertionError('Emitted loop did not terminate')


