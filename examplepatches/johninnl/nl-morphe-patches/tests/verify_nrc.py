def verify_call_kinds(root):
    import os
    sdk,archive=sdk_classes()
    sdk_root=Path(os.environ.get('ANDROID_HOME',str(Path.home()/'Library/Android/sdk')))
    api=ET.parse(sdk_root/'platforms/android-36/data/api-versions.xml')
    api_types={e.get('name'):e for e in api.iter('class')}
    try:
        for cls in [WEB,READER]:
            for sig,body in re.findall(r'^\.method[^\n]* (\S+)\n(.*?)^\.end method',source(root,cls),re.M|re.S):
                if not sig.startswith('morphe'):continue
                for kind,typ,target in re.findall(r'invoke-(static|virtual|interface|direct)(?:/range)?\s+\{[^}]*\},\s+(L[^;]+;)->(\S+)',body):
                    if typ.startswith(('Lpinch/','Lnl/pinch/')):
                        text=source(root,typ[1:-1]);matches=re.findall(r'^\.method ([^\n]*?) '+re.escape(target)+r'$',text,re.M)
                        assert len(matches)==1,(typ,target)
                        assert (kind=='interface')==bool(re.search(r'^\.class .*\binterface\b',text,re.M)),(kind,typ,target)
                        assert (kind=='static')==('static' in matches[0].split()),(kind,typ,target)
                    else:
                        original_type=typ
                        contract=sdk(typ);assert contract,typ
                        if kind in {'virtual','interface'}:assert (kind=='interface')==contract[0],(typ,target)
                        while target not in contract[2] and contract[1]:contract=sdk(contract[1]);assert contract
                        assert target in contract[2],(typ,target)
                        # Actual Android API history, independently from current
                        # android.jar: NRC supports Android23.
                        pending=[(original_type[1:-1],1)];seen={};available=[]
                        while pending:
                            name,earliest=pending.pop()
                            if name in seen and seen[name]<=earliest:continue
                            seen[name]=earliest;api_type=api_types.get(name)
                            if api_type is None:continue
                            earliest=max(earliest,int(api_type.get('since','1')))
                            method=next((m for m in api_type.findall('method') if m.get('name')==target),None)
                            if method is not None:available.append(max(earliest,int(method.get('since',api_type.get('since','1')))))
                            if not target.startswith('<init>('):
                                pending.extend((node.get('name'),max(earliest,int(node.get('since','1')))) for node in api_type if node.tag in {'extends','implements'})
                        assert available and min(available)<=23,(original_type,target,'API23',available)
                        assert (kind=='static')==bool(contract[2][target]&8),(typ,target)
                        if kind=='direct':assert target.startswith('<init>(')
    finally:archive.close()


