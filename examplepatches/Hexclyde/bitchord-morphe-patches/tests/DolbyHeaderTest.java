    static byte[] bytes(String name) {
        String hex = HEADS.get(name);
        byte[] out = new byte[hex.length() / 2];
        for (int i = 0; i < out.length; i++)
            out[i] = (byte) Integer.parseInt(hex.substring(2 * i, 2 * i + 2), 16);
        return out;
    }

    static JSONObject read(String name) {
        byte[] head = bytes(name);
        return AudioHeader.parse(head, head.length);
    }

    static String label(String name) {
        return AudioHeader.label(read(name));
    }

    public static void main(String[] args) throws Exception {
        check(label("st.ac3").equals("DD 2.0"), "Dolby Digital stereo: " + label("st.ac3"));
        check(label("s51.ac3").equals("DD 5.1"), "Dolby Digital 5.1");
        check(label("s51.ec3").equals("DD+ 5.1"), "Dolby Digital Plus 5.1");
        check(label("atmos.ec3").equals("Dolby Atmos"), "Atmos in a plain .ec3");
        check(read("atmos.ec3").getInt("rate") == 44100, "Sample rate");
        check(label("s51.m4a").equals("DD+ 5.1"), "In an .m4a: " + label("s51.m4a"));
        check(label("atmos.mp4").equals("Dolby Atmos"), "Atmos in an .mp4 without dec3's flag");
        check(label("s51_end.mp4").equals("DD+ 5.1"), "Description at the end: from the frames");
        check(label("st_ac3.m4a").equals("DD 2.0"), "Dolby Digital in an .m4a");
        check(label("s51.mka").equals("DD+ 5.1"), "In an .mka");
        check(label("atmos.mka").equals("Dolby Atmos"), "Atmos in an .mka");
        check(label("t.mka").equals("TrueHD 5.1"), "TrueHD: " + label("t.mka"));
        check(
                label("atmos-truehd.mka").equals("TrueHD Atmos"),
                "Four substreams with the top bit of the substream info: "
                        + label("atmos-truehd.mka"));
        check(label("a24.m4a").equals("ALAC 24bit"), "ALAC's bit depth: " + label("a24.m4a"));
        check(read("aac_end.m4a") == null, "AAC is left to its bitrate");

        // dec3 for 7.1 with Atmos: one independent 5.1 substream, a dependent one adding the rear
        // pair (Lrs/Rrs), and the extension byte with the Atmos flag.
        byte[] dec3 = {
            0, 0, 0, 16, 'd', 'e', 'c', '3', 0x30, 0x00, 0x20, 0x0f, 0x02, (byte) 0x80, 0x01, 0x10
        };
        // data_rate 0x600, 1 substream | fscod 0, bsid 16, asvc 0, bsmod 0, acmod 7, lfe 1,
        // reserved 3 bits, num_dep_sub 1, chan_loc 0b010000000 | reserved 7, flag 1 | complexity
        JSONObject header = DolbyHeader.dec3(dec3, 0);
        check(header.optBoolean("atmos"), "dec3 Atmos flag: " + header);
        check(
                header.getInt("channels") == 8 && header.getInt("rate") == 48000,
                "7.1 from the dependent substream: " + header);
        header.remove("atmos");
        check(DolbyHeader.label(header).equals("DD+ 7.1"), DolbyHeader.label(header));

        // Not Dolby, or not a whole header.
        check(DolbyHeader.parse(new byte[100], 100, 0) == null, "Zeros");
        check(DolbyHeader.parse(bytes("atmos.ec3"), 6, 0) == null, "Cut short");

        // What BitChord is told.
        JSONObject row =
                new JSONObject()
                        .put("format", "m4a")
                        .put("size", 17_280_000)
                        .put("duration", 180)
                        .put("mime", "audio/mp4");
        check(
                InternalAddon.quality(row).equals("LOSSLESS"),
                "768 kbps in an .m4a looks like ALAC from its bitrate alone");
        check(
                InternalAddon.quality(row, read("s51.m4a")).equals("HIGH"),
                "but its header says Dolby Digital Plus");
        check(InternalAddon.quality(row, read("t.mka")).equals("LOSSLESS"), "TrueHD is lossless");
        check(
                InternalAddon.format(new JSONObject().put("format", "ec3")).equals("eac3"),
                "BitChord takes .ec3 in a type for Atmos");
        check(
                LegendMatch.row(new JSONObject().put("format", "ac3"), null).startsWith("DD"),
                "Legend before the header is read");
        System.out.println("PASS: " + checks + " Dolby format, channel, Atmos and quality checks.");
    }
