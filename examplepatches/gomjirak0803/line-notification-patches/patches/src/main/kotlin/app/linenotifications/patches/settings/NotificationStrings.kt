internal fun ResourcePatchContext.applyNotificationStrings() {
    for ((qualifier, entries) in NOTIFICATION_STRINGS) {
        document("res/$qualifier/strings.xml").use { document ->
            val resources = document.getElementsByTagName("resources").item(0) as Element
            for ((key, value) in entries) {
                resources.appendChild(document.createElement("string").apply {
                    setAttribute("name", key)
                    textContent = value
                })
            }
        }
    }
}
