    /** Used while the village's own land distribution isn't known: most layouts put the fields here. */
    static final int FALLBACK_DISTRIBUTION = 3;

    /** 1..13 from the game's landDistribution value (a number, or text holding one); 0 if not usable. */
    static int distribution(String raw) {
        if (raw == null) {
            return 0;
        }
        String digits = raw.replaceAll("[^0-9]", "");
        if (digits.isEmpty() || digits.length() > 3) {
            return 0;
        }
        int n = Integer.parseInt(digits);
        return n >= 1 && n <= FIELDS.length ? n : 0;
    }

    /** {x, y} of this slot in the game's screens, or null for a slot this table doesn't have. */
    static double[] position(int slotId, int distribution) {
        if (slotId >= 1 && slotId <= 18) {
            int d = distribution >= 1 && distribution <= FIELDS.length ? distribution : FALLBACK_DISTRIBUTION;
            return FIELDS[d - 1][slotId - 1];
        }
        if (slotId >= 19 && slotId <= 40) {
            return CENTER[slotId - 19];
        }
        if (slotId >= 41 && slotId <= 44) {
            return EXTRA[slotId - 41];
        }
        return null;
    }
