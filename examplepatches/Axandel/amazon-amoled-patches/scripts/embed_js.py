#!/usr/bin/env python3
"""Regenerates WebAssets.java from extensions/extension/src/main/js/amoled-dark.js.

Run from the repository root:  python3 scripts/embed_js.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "extensions/extension/src/main/js/amoled-dark.js"
OUT = ROOT / "extensions/extension/src/main/java/app/amazonamoled/extension/WebAssets.java"


def strip_comments(js: str) -> str:
    # Drop the leading block comment and whole-line // comments. Strings in this file never
    # contain "//" at the start of a line, so this simple pass is safe.
    js = re.sub(r"\A\s*/\*.*?\*/\s*", "", js, flags=re.S)
    lines = [l for l in js.splitlines() if not l.strip().startswith("//")]
    return "\n".join(l.rstrip() for l in lines if l.strip()).strip().rstrip(";")


def main() -> None:
    js = strip_comments(SRC.read_text(encoding="utf-8"))
    if len(js.encode("utf-8")) > 60000:
        raise SystemExit("Script too large for one Java string constant")
    parts = " +\n".join("        " + json.dumps(line + "\n", ensure_ascii=True) for line in js.splitlines())
    OUT.write_text(
        "package app.amazonamoled.extension;\n\n"
        "// GENERATED by scripts/embed_js.py from src/main/js/amoled-dark.js. Do not edit by hand.\n"
        "final class WebAssets {\n"
        "    private WebAssets() {}\n\n"
        "    /** A JavaScript function expression taking the settings object. */\n"
        "    static final String DARK_JS =\n" + parts + ";\n"
        "}\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(js)} chars)")


if __name__ == "__main__":
    main()
