    check(dex.classes.size == 20)
    var restored = 0
    for (extracted in dex.classes) {
        val source = extracted.methods.single()
        check(source.parameterTypes.first() == extracted.type.substringBefore("\$c202006") + ";")
        val owner = mutableClassDefBy(source.parameterTypes.first().toString())
        val original = owner.methods.single {
            it.name == source.name && it.parameterTypes == source.parameterTypes.drop(1) &&
                it.returnType == source.returnType
        }
        check(checkNotNull(original.implementation).instructions.any {
            (it as? com.android.tools.smali.dexlib2.iface.instruction.ReferenceInstruction)
                ?.reference?.toString() == "Ljava/lang/reflect/Method;->invoke(Ljava/lang/Object;[Ljava/lang/Object;)Ljava/lang/Object;"
        })
        check(owner.methods.remove(original))
        check(owner.methods.add(MutableMethod(ImmutableMethod(
            owner.type, original.name, original.parameters, original.returnType, original.accessFlags,
            original.annotations, original.hiddenApiRestrictions, source.implementation,
        ))))
        restored++
    }
    check(restored == 20)
}

