// Callback implementations carried forward from 9.0.26.3 with 9.0.27.3 references.
// Includes media-button dispatch, Cast, shortcuts and SDK broadcast receivers.
internal fun restoreStartupCallbacks() {
    val dex = DexBackedDexFile(Opcodes.getDefault(), ByteBuffer.wrap(Base64.getDecoder().decode(STARTUP_CALLBACKS)))
    var restored = 0
    for (sourceClass in dex.classes) {
        val owner = mutableClassDefBy(sourceClass.type)
        for (source in sourceClass.methods) {
            val original = owner.methods.single {
                it.name == source.name && it.parameterTypes == source.parameterTypes && it.returnType == source.returnType
            }
            check(checkNotNull(original.implementation).instructions.any {
                (it as? ReferenceInstruction)?.reference?.toString() ==
                    "Lcom/pairip/VMRunner;->invoke(Ljava/lang/String;[Ljava/lang/Object;)Ljava/lang/Object;"
            })
            check(owner.methods.remove(original))
            check(owner.methods.add(MutableMethod(ImmutableMethod(
                owner.type, original.name, original.parameters, original.returnType, original.accessFlags,
                original.annotations, original.hiddenApiRestrictions, source.implementation,
            ))))
            restored++
        }
    }
    check(restored == 20)
}

