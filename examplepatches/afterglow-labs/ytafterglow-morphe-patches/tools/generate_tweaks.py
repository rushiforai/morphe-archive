#!/usr/bin/env python3
"""Generates settings/TweakCatalog.java from tools/tweaks.json and tools/parity.json.

TweakCatalog maps each Morphe tweak (one named patch) to its iOS keys, lists the
base keys of the always-installed settings page, and lists SHOWN_KEYS: the keys
whose parity status is "done" or whose note starts with "partial". The settings
page shows a row only if its tweak is installed and its key is shown (base rows
always show), so the page never offers a switch that does nothing yet.

usage: tools/generate_tweaks.py [--check]   (--check: fail if the file is stale)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TWEAKS = os.path.join(ROOT, "tools", "tweaks.json")
PARITY = os.path.join(ROOT, "tools", "parity.json")
OUT = os.path.join(ROOT, "extensions", "extension", "src", "main", "java",
                   "app", "afterglow", "extension", "settings", "TweakCatalog.java")


def java_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def java_array(values, indent):
    if not values:
        return "new String[] {}"
    pad = " " * indent
    body = (",\n" + pad).join(java_string(v) for v in values)
    return "new String[] {\n" + pad + body + ",\n" + " " * (indent - 4) + "}"


def shown_keys(parity):
    shown = []
    for key, entry in parity.items():
        note = (entry.get("note") or "").strip().lower()
        if entry.get("status") == "done" or note.startswith("partial"):
            shown.append(key)
    return sorted(shown)


def render():
    with open(TWEAKS) as fh:
        tweaks = json.load(fh)
    with open(PARITY) as fh:
        parity = json.load(fh)

    lines = [
        "// Generated by tools/generate_tweaks.py from tools/tweaks.json and tools/parity.json. Do not edit.",
        "package app.afterglow.extension.settings;",
        "",
        "import java.util.Collections;",
        "import java.util.HashMap;",
        "import java.util.HashSet;",
        "import java.util.Map;",
        "import java.util.Set;",
        "",
        "/**",
        " * The Morphe tweak list: each tweak is one named patch that owns some iOS",
        " * settings keys. Base keys belong to the always-installed settings page.",
        " * SHOWN_KEYS are the keys whose Android behavior works (fully or in part).",
        " */",
        "public final class TweakCatalog {",
        "",
        "    /** One tweak: its id (InstalledTweaks), its name in Morphe and the keys it owns. */",
        "    public static final class Tweak {",
        "        public final String id;",
        "        public final String name;",
        "        public final String[] keys;",
        "",
        "        Tweak(String id, String name, String[] keys) {",
        "            this.id = id;",
        "            this.name = name;",
        "            this.keys = keys;",
        "        }",
        "    }",
        "",
        "    public static final Tweak[] ALL = {",
    ]
    for tweak in tweaks["tweaks"]:
        lines.append(f"            new Tweak({java_string(tweak['id'])}, {java_string(tweak['name'])}, "
                     f"{java_array(tweak['keys'], 20)}),")
    lines += [
        "    };",
        "",
        f"    private static final String[] BASE = {java_array(tweaks['base'], 12)};",
        "",
        f"    private static final String[] SHOWN = {java_array(sorted(set(shown_keys(parity)) | set(tweaks.get('implementedInternalKeys', {}))), 12)};",
        "",
        "    /** Keys of the always-installed settings page. */",
        "    public static final Set<String> BASE_KEYS;",
        "    /** Keys whose behavior works on Android, fully or in part. */",
        "    public static final Set<String> SHOWN_KEYS;",
        "    private static final Map<String, Tweak> BY_ID = new HashMap<>();",
        "    private static final Map<String, Tweak> BY_KEY = new HashMap<>();",
        "",
        "    static {",
        "        Set<String> base = new HashSet<>();",
        "        Collections.addAll(base, BASE);",
        "        BASE_KEYS = Collections.unmodifiableSet(base);",
        "        Set<String> shown = new HashSet<>();",
        "        Collections.addAll(shown, SHOWN);",
        "        SHOWN_KEYS = Collections.unmodifiableSet(shown);",
        "        for (Tweak tweak : ALL) {",
        "            BY_ID.put(tweak.id, tweak);",
        "            for (String key : tweak.keys) BY_KEY.put(key, tweak);",
        "        }",
        "    }",
        "",
        "    private TweakCatalog() {}",
        "",
        "    /** The tweak that owns this key, or null for base and unknown keys. */",
        "    public static Tweak tweakForKey(String key) {",
        "        return key == null ? null : BY_KEY.get(key);",
        "    }",
        "",
        "    /** The tweak with this id, or null. */",
        "    public static Tweak tweak(String id) {",
        "        return id == null ? null : BY_ID.get(id);",
        "    }",
        "",
        "    public static boolean isBaseKey(String key) {",
        "        return key != null && BASE_KEYS.contains(key);",
        "    }",
        "",
        "    public static boolean isShown(String key) {",
        "        return key != null && SHOWN_KEYS.contains(key);",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            print(f"stale: {os.path.relpath(OUT, ROOT)}; run tools/generate_tweaks.py")
            return 1
        print("TweakCatalog.java is up to date")
        return 0
    with open(OUT, "w") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
