#!/usr/bin/env python3
"""Expose pinned Morphe implementations without changing their dependency graph.

The imported patches are unnamed dependencies. Each public wrapper preserves the
original option objects and adds the Afterglow settings entry. Morphe's settings
continue to own the imported features; no iOS parity claim is implied.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "tools/morphe-catalog.json"
OUTPUT = ROOT / "patches/src/main/kotlin/app/afterglow/patches/morphe/MorpheCatalogPatches.kt"
TWEAKS = ROOT / "tools/tweaks.json"


def literal(value):
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def render(entries):
    lines = [
        "// Generated by tools/generate_morphe_catalog.py. Do not edit.",
        "// Feature implementations remain in vendor/morphe with their original notices.",
        "package app.afterglow.patches.morphe", "",
        "import app.afterglow.patches.shared.Constants.COMPATIBILITY_YOUTUBE",
        "import app.afterglow.patches.shared.markTweakInstalled",
        "import app.morphe.patcher.patch.bytecodePatch", "",
        "import app.morphe.patcher.patch.PatchAvailability", "",
    ]
    for index, entry in enumerate(entries):
        symbol = entry["original_property"]
        description = entry['description'].replace("Morphe settings", "Afterglow settings")
        description = description.replace("YT Afterglow", "Afterglow").replace("YTAfterglow", "Afterglow")
        lines += [
            '@Suppress("unused")',
            f"val morpheCatalog{index}Patch = bytecodePatch(",
            f"    name = {literal(entry['export_name'])},",
            f"    description = {literal(description + ' Configure in Afterglow settings → Additional features.')},",
            f"    default = {str(entry['default']).lower()},",
            ") {",
            "    compatibleWith(COMPATIBILITY_YOUTUBE)",
            "    availability { installer, architecture ->",
            f"        when (val state = {symbol}.availability?.resolve(installer, architecture)) {{",
            "            PatchAvailability.UNAVAILABLE, PatchAvailability.REQUIRED -> state",
            f"            else -> PatchAvailability.{'ENABLED' if entry['default'] else 'DISABLED'}",
            "        }",
            "    }",
            f"    dependsOn({symbol}, morpheSettingsBridgePatch)",
            f"    {symbol}.options.values.forEach {{ it() }}",
            f"    execute {{ markTweakInstalled({literal(entry['id'])}) }}",
            "}", "",
        ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = json.loads(CATALOG.read_text())
    entries = [entry for entry in catalog["patches"] if entry["decision"] == "expose"]
    for field in ("id", "export_name", "original_property"):
        values = [entry[field] for entry in entries]
        assert len(values) == len(set(values)), f"Duplicate exported {field}"
    tweaks = json.loads(TWEAKS.read_text())
    # Imported controls belong to the original upstream preference screen, not
    # to fabricated iOS keys. Empty key lists still record installed ownership.
    retained = [entry for entry in tweaks["tweaks"] if not entry["id"].startswith("morphe-")]
    assert not ({entry["name"] for entry in retained} & {entry["export_name"] for entry in entries})
    tweaks["tweaks"] = retained + [
        {"id": entry["id"], "name": entry["export_name"], "keys": []} for entry in entries
    ]
    contents = render(entries)
    tweak_contents = json.dumps(tweaks, indent=2, ensure_ascii=False) + "\n"
    if args.check:
        assert OUTPUT.exists() and OUTPUT.read_text() == contents, "Stale Morphe wrappers"
        assert json.loads(TWEAKS.read_text()) == tweaks, "Stale Morphe tweak ownership"
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(contents)
        TWEAKS.write_text(tweak_contents)
    print(f"{len(entries)} Morphe feature wrappers; {sum(entry['default'] for entry in entries)} selected by default")


if __name__ == "__main__":
    main()
