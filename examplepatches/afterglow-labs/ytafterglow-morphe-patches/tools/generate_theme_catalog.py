#!/usr/bin/env python3
"""Generate the Android preset catalog from the pinned iOS palette data.

Normal: python3 -I tools/generate_theme_catalog.py [--check]
Refresh: python3 -I tools/generate_theme_catalog.py --ios-source /path/to/ios
Verify against iOS without writing: add --check to the refresh command.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tools/ios-theme-catalog.json"
OUT = ROOT / "extensions/extension/src/main/java/app/afterglow/extension/settings/ThemeCatalog.java"
IOS_PATH = "Utils/YTAGThemeCatalog.m"
ORDER = ["OVERLAY_CONTROL", "TAB_ICON", "SEEK_PLAYED", "BACKGROUND", "PRIMARY_TEXT",
         "SECONDARY_TEXT", "NAVIGATION_SURFACE", "ACCENT", "GRADIENT_START", "GRADIENT_END"]
STR = r'@"((?:[^"\\]|\\.)*)"'


def extract(repo):
    source = (repo / IOS_PATH).read_text(encoding="utf-8")
    block = source.split("static NSArray<YTAGTheme *> *YTAGThemeCatalogBuildPresets(void)", 1)[1].split("\n}", 1)[0]
    pattern = re.compile(r"YTAGThemeCatalog(GradientPreset|Preset)\(" + STR + r",\s*" + STR
                         + r",\s*" + STR + r",\s*(YES|NO),\s*(YES|NO),\s*(.*)\),?$")
    presets = []
    for line in block.splitlines():
        if "YTAGThemeCatalog" not in line:
            continue
        match = pattern.fullmatch(line.strip())
        if not match:
            raise ValueError("Unrecognized iOS preset line: " + line)
        kind, identifier, name, summary, light, glow, color_text = match.groups()
        colors = [[float(c.strip()) for c in rgb.split(",")]
                  for rgb in re.findall(r"RGB\(([^)]+)\)", color_text)]
        if len(colors) != (10 if kind == "GradientPreset" else 8):
            raise ValueError("Unexpected color count for " + identifier)
        if re.sub(r"RGB\([^)]+\)|[\s,]", "", color_text):
            raise ValueError("Unexpected color expression for " + identifier)
        if any(len(rgb) != 3 or any(not math.isfinite(c) or not 0 <= c <= 1 for c in rgb) for rgb in colors):
            raise ValueError("Invalid RGB values for " + identifier)
        presets.append(dict(identifier=json.loads('"' + identifier + '"'), name=json.loads('"' + name + '"'),
                            summary=json.loads('"' + summary + '"'), lightFoundation=light == "YES",
                            glowEnabled=glow == "YES", colors=dict(zip(ORDER, colors))))
    if not presets or len({p["identifier"] for p in presets}) != len(presets):
        raise ValueError("Missing or duplicate iOS presets")
    return {"source": IOS_PATH, "sha256": hashlib.sha256(source.encode()).hexdigest(), "presets": presets}


def render(data):
    lines = ["// Generated by tools/generate_theme_catalog.py. Do not edit.",
             "// iOS " + data["source"] + " SHA-256: " + data["sha256"],
             "package app.afterglow.extension.settings;", "",
             "import java.util.Arrays;", "import java.util.Collections;", "import java.util.EnumMap;",
             "import java.util.List;", "import java.util.Map;", "import java.util.Objects;", "",
             "/** iOS master presets, in source order. Channels are rounded to eight-bit ARGB once. */",
             "public final class ThemeCatalog {",
             "    public static final List<ThemePalette> PRESETS = Collections.unmodifiableList(Arrays.asList("]
    for i, preset in enumerate(data["presets"]):
        colors = []
        for role in ORDER:
            if role not in preset["colors"]:
                continue
            rgb = preset["colors"][role]
            channels = [int(math.floor(c * 255 + 0.5)) for c in rgb]
            colors.append("0xFF" + "".join(f"{c:02X}" for c in channels))
        texts = ", ".join(json.dumps(preset[k], ensure_ascii=True) for k in ("identifier", "name", "summary"))
        flags = ", ".join(str(preset[k]).lower() for k in ("lightFoundation", "glowEnabled"))
        lines.append(f"            preset({texts}, {flags}, new int[] {{{', '.join(colors)}}})"
                     + ("," if i + 1 < len(data["presets"]) else ""))
    lines += ["    ));", "", "    private ThemeCatalog() {}", "",
              "    private static ThemePalette preset(String id, String name, String summary, boolean light,",
              "                                       boolean glow, int[] colors) {",
              "        ThemeRole[] order = {" + ", ".join("ThemeRole." + r for r in ORDER) + "};",
              "        EnumMap<ThemeRole, Integer> palette = new EnumMap<>(ThemeRole.class);",
              "        for (int i = 0; i < colors.length; i++) palette.put(order[i], colors[i]);",
              "        for (ThemeRole role : new ThemeRole[] {ThemeRole.SEEK_LIVE, ThemeRole.SEEK_SCRUBBER, ThemeRole.SEEK_SCRUBBER_LIVE})",
              "            palette.put(role, palette.get(ThemeRole.SEEK_PLAYED));",
              "        return new ThemePalette(id, name, summary, true, light, glow, palette);",
              "    }", "",
              "    public static ThemePalette find(String identifier) {",
              "        for (ThemePalette preset : PRESETS) if (preset.identifier.equals(identifier)) return preset;",
              "        return null;", "    }", "",
              "    // iOS hasSameLegacyPaletteAsTheme ignores the independent glow override.",
              "    static ThemePalette match(Map<ThemeRole, Integer> colors) {",
              "        for (ThemePalette preset : PRESETS) {", "            boolean matches = true;",
              "            for (ThemeRole role : ThemeRole.values()) {",
              "                if (role.legacyKey == null || role == ThemeRole.GLOW) continue;",
              "                if (!Objects.equals(colors.get(role), preset.explicit(role))) {",
              "                    matches = false;", "                    break;", "                }", "            }",
              "            if (matches) return preset;", "        }", "        return null;", "    }", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ios-source", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = extract(args.ios_source) if args.ios_source else json.loads(DATA.read_text())
    rendered = render(data)
    if args.check:
        if json.loads(DATA.read_text()) != data:
            raise SystemExit("iOS theme catalog snapshot differs from the supplied iOS source")
        if OUT.read_text() != rendered:
            raise SystemExit("ThemeCatalog.java is stale; run tools/generate_theme_catalog.py")
        print(f"theme catalog: {len(data['presets'])} iOS presets; generated Java is current")
    else:
        DATA.write_text(json.dumps(data, indent=2) + "\n")
        OUT.write_text(rendered)
        print(f"generated {len(data['presets'])} iOS presets")


if __name__ == "__main__":
    main()
