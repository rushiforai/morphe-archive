#!/usr/bin/env python3
"""Generate the Android settings screen spec from the iOS transcription.

Reads  tools/ios-settings-ui.json   (pages, rows and search index of iOS Settings.x)
       gradle.properties            (the Android version shown in About's summary)
Writes extensions/.../ui/SettingsSpec.java  (GENERATED; do not edit by hand)

Every row is classified from the JSON's structured fields (kind, key, detail,
picker, target, action, custom, textInput). Behaviour iOS computes in one-off
blocks is selected through ROW_DETAILS. Anything the generator cannot classify
raises, so a changed JSON fails here instead of rendering wrongly.

Run: python3 tools/generate_settings_ui.py
Check: python3 tools/check_settings_ui.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_from_ios import java_literal  # noqa: E402  (shared Java string escaping)

SPEC_JSON = ROOT / "tools/ios-settings-ui.json"
GRADLE_PROPERTIES = ROOT / "gradle.properties"
OUT = ROOT / "extensions/extension/src/main/java/app/afterglow/extension/ui/SettingsSpec.java"
HEADER = "// GENERATED by tools/generate_settings_ui.py from tools/ios-settings-ui.json. Do not edit.\n"

# Row-specific detail behaviour (the iOS one-off summary/detail blocks).
ROW_DETAILS = {
    "root.themes": "THEME_APPEARANCE",
    "themes.typography": "THEME_TYPOGRAPHY",
    "themes.seekBar": "THEME_SEEK_BAR",
    "player.sponsorBlock": "SPONSOR_BLOCK",
    "interface.tabbar": "TABS_COUNT",
    "tabbar.customizeTabs": "SHOWN_COUNT",
    "themes.themeStudio": "THEME_STUDIO",
    "root.about": "VERSION",
}

# Search entries whose English title is a LOC() string not carried by a row
# (Settings.x:2178-2181). Everything else reuses the text of the row it names.
SEARCH_TITLE_KEYS = {"Theme Presets": "Presets", "Custom Colors": "CustomColors", "Gradient Background": "Gradient"}
SEARCH_DESCRIPTION_KEYS = {"Automatically skips community-identified segments using YTAfterglow's built-in client and the official SponsorBlock API.": "SponsorBlockDesc"}
PATH_KEYS = {"Main": "Main"}  # path elements that name no row (iOS LiteMode entry uses path [LOC(Main)])

TAB_EDITOR_FOOTER_FORMAT = "Drag to reorder. Move a tab to Hidden Tabs to remove it from the bar. Keep 2 to %d tabs shown."


class SpecError(Exception):
    pass


# ---------------------------------------------------------------- text helpers

def jt(text) -> str:
    """Java expression for a JSON text object {key, en, origin}."""
    if text is None:
        return "null"
    if isinstance(text, str):
        return f"lit({java_literal(text)})"
    if text.get("origin") == "computed":
        raise SpecError(f"computed text needs explicit handling: {text}")
    key = text.get("key")
    if key is None:
        return f"lit({java_literal(text['en'])})"
    return f"t({java_literal(key)}, {java_literal(text['en'])})"


def jstrs(values) -> str:
    return ", ".join(java_literal(v) for v in values)


# ---------------------------------------------------------------- model indexes

class Spec:
    def __init__(self, data: dict):
        self.data = data
        self.pages = {p["id"]: p for p in data["pages"]}
        self.order = data["pageOrder"]
        self.row_page = {}
        self.rows = {}
        self.parent = {self.order[0]: None}
        for p in data["pages"]:
            for r in p["rows"]:
                if r["id"] in self.rows:
                    raise SpecError(f"duplicate row id {r['id']}")
                self.rows[r["id"]] = r
                self.row_page[r["id"]] = p["id"]
                tgt = r.get("target") or {}
                if tgt.get("type") == "page":
                    self.parent[tgt["pageId"]] = (p["id"], r["id"])
        missing = [pid for pid in self.order if pid not in self.parent]
        if missing:
            raise SpecError(f"pages without an opening row: {missing}")

    def chain(self, pid: str) -> list[str]:
        out = []
        while pid is not None:
            out.append(pid)
            link = self.parent[pid]
            pid = link[0] if link else None
        return list(reversed(out))

    def opener_visibility(self, pid: str) -> list:
        """visibleWhen of every row on the way to `pid`."""
        out = []
        while self.parent[pid] is not None:
            parent, rid = self.parent[pid]
            out.append(self.rows[rid].get("visibleWhen"))
            pid = parent
        return out


# ---------------------------------------------------------------- row classification

def visibility_code(row: dict) -> str:
    vw = row.get("visibleWhen")
    if not vw:
        return ""
    if vw.get("advancedMode"):
        return ".visible(Visibility.ADVANCED, null)"
    if "standardPlayerControlAvailable" in vw:
        return f".visible(Visibility.STANDARD_CONTROL, {java_literal(vw['standardPlayerControlAvailable'])})"
    if "storedValuePresent" in vw:
        return f".visible(Visibility.STORED_VALUE, {java_literal(vw['storedValuePresent'])})"
    raise SpecError(f"unknown visibleWhen on {row['id']}: {vw}")


def detail_code(row: dict) -> str:
    rid = row["id"]
    det = row.get("detail")
    if rid in ROW_DETAILS:
        kind = ROW_DETAILS[rid]
        code = f".detail(Detail.{kind})"
        if kind == "THEME_SEEK_BAR":
            code += f".detailKeys({jstrs(det['keys'])})"
        if kind == "SPONSOR_BLOCK":
            code += f".detailText({jt(det['offText'])})"
        return code
    if det is None:
        return ""
    if "keys" in det and det.get("formula", "").startswith("enabledSummaryForKeys"):
        # Fix (fresh-install summaries): SettingsBehavior counts only BOOLEAN keys; the
        # full iOS key list is kept here so the source of truth stays visible.
        return f".detail(Detail.ENABLED_SUMMARY).detailKeys({jstrs(det['keys'])})"
    if "text" in det and det.get("formula") == "constant":
        return f".detail(Detail.CONSTANT).detailText({jt(det['text'])})"
    raise SpecError(f"unclassified detail on {rid}: {det.get('formula')}")


def option_code(opt: dict) -> str:
    return f"opt({jt(opt['label'])}, {int(opt['value'])})"


def switch_code(row: dict) -> list[str]:
    parts = [f".key({java_literal(row['key'])})", f".title({jt(row['title'])})"]
    desc = row["description"]
    parts.append(f".desc({jt({'key': desc['key'], 'en': desc['en']})})")
    if desc.get("composition", "").startswith("plain"):
        parts.append(".plainDescription()")
    elif row.get("restartNote") and "Restart YouTube" in desc["en"]:
        # Fix (duplicated restart sentence): iOS appends "Restart YouTube to apply." even when
        # the description already says to restart (disableFloatingTabBar shows both sentences).
        parts.append(".suppressRestartNote()")
    return parts


def picker_code(row: dict, spec: Spec) -> list[str]:
    pk = row["picker"]
    key = row["key"]
    parts = [f".key({java_literal(key)})", f".title({jt(row['title'])})"]
    if row.get("description") is not None:
        parts.append(f".desc({jt(row['description'])})")
    nav = pk["navTitle"]
    if nav.get("origin") == "locMissingEchoesKey":
        # Fix (quality picker title): iOS uses LOC(@"SelectQuality"), which no .lproj defines,
        # so the raw key shows. Use the row's own localized title, like every other picker.
        nav = row["title"]
    if "optionsComputed" in pk:
        if key == "startupTab":
            parts.append(f".picker(Picker.STARTUP_TAB, {jt(nav)}).detail(Detail.STARTUP_TAB)")
        elif key in ("anchorLeftTab", "anchorRightTab"):
            left = key == "anchorLeftTab"
            other = "anchorRightTab" if left else "anchorLeftTab"
            choice = "YTAGControlCenter" if left else "FElibrary"
            other_choice = "FElibrary" if left else "YTAGControlCenter"
            parts.append(f".picker(Picker.ANCHOR, {jt(nav)}).detail(Detail.ANCHOR)"
                         f".anchor({java_literal(other)}, {java_literal(choice)}, {java_literal(other_choice)})")
        else:
            raise SpecError(f"unknown computed picker {row['id']}")
    else:
        opts = ", ".join(option_code(o) for o in pk["options"])
        if row["id"] == "effects.glowStrength":
            dlg = pk["customGlowStrengthDialog"]
            parts.append(f".picker(Picker.GLOW_STRENGTH, {jt(nav)}, {opts}).detail(Detail.GLOW_STRENGTH)"
                         f".number({dlg['min']}, {dlg['max']}, {dlg['fallback']}, {java_literal(dlg['suffix'])})"
                         f".dialog({jt(dlg['alertTitle'])}, lit({java_literal('Enter an exact glow strength value.')}))")
        elif "explicit" in pk["storedValue"]:
            if not pk.get("afterSelect", "").startswith("pops"):
                raise SpecError(f"explicit-value picker that does not pop: {row['id']}")
            parts.append(f".picker(Picker.VALUE, {jt(nav)}, {opts}).detail(Detail.SCRUBBER_SIZE).pops()")
        else:
            parts.append(f".picker(Picker.INDEX, {jt(nav)}, {opts}).detail(Detail.OPTION_LABEL)")
    if pk.get("trailingRows"):
        trailing = ", ".join(row_code(r, spec, factory="tr") for r in pk["trailingRows"])
        parts.append(f".trailing({trailing})")
    return parts


def action_code(row: dict) -> list[str]:
    rid = row["id"]
    reg = row.get("registryKey")
    parts = []
    if row.get("key"):
        parts.append(f".key({java_literal(row['key'])})")
    if ".useDefault." in rid:
        # Title is "Use Default %@" with LOC(<color row title key>) (Settings.x:2075).
        prefix = "Use Default "
        if not row["title"]["en"].startswith(prefix):
            raise SpecError(f"unexpected Use Default title on {rid}")
        color_rows = [r for r in SPEC_ROWS.values() if r.get("kind") == "custom" and r.get("key") == row["key"]]
        if len(color_rows) != 1:
            raise SpecError(f"no unique color row for {rid}")
        parts.append(f".title({jt(color_rows[0]['title'])}).titlePrefix({java_literal(prefix)})")
    else:
        parts.append(f".title({jt(row['title'])})")
    if row.get("description") is not None:
        parts.append(f".desc({jt(row['description'])})")
    if rid.endswith(".reset.action"):
        conditional = set((row.get("resetsKeysWhen") or {}).keys())
        always = [k for k in row["resetsKeys"] if k not in conditional]
        parts.append(f".action(Action.RESET_DEFAULTS, {jstrs(always)})")
        if conditional:
            parts.append(f".advancedKeys({jstrs([k for k in row['resetsKeys'] if k in conditional])})")
    elif reg == "action.resetThemeColors":
        keys = row["action"]["confirmation"]["buttons"][0]["steps"][0]["keys"]
        parts.append(f".action(Action.RESET_ALL_COLORS, {jstrs(keys)}).registry({java_literal(reg)})")
    elif reg == "action.clearCache":
        parts.append(f".action(Action.CLEAR_CACHE).registry({java_literal(reg)}).detail(Detail.CACHE_SIZE)")
    elif reg == "action.exportPreferences":
        parts.append(f".action(Action.EXPORT_PREFERENCES).registry({java_literal(reg)})")
    elif reg == "action.importPreferences":
        parts.append(f".action(Action.IMPORT_PREFERENCES).registry({java_literal(reg)})")
    elif reg == "action.resetSettings":
        parts.append(f".action(Action.RESET_SETTINGS).registry({java_literal(reg)})")
    elif reg == "action.clearDebugLog":
        parts.append(f".action(Action.CLEAR_DEBUG_LOG).registry({java_literal(reg)})")
    elif rid == "about.shareDebugLog":
        parts.append(".action(Action.SHARE_DEBUG_LOG)")
    elif ".useDefault." in rid:
        parts.append(f".action(Action.USE_DEFAULT_COLOR, {java_literal(row['key'])}).detail(Detail.CLEARS_COLOR)")
    elif rid == "seekBar.removeCustomImage":
        parts.append(f".action(Action.REMOVE_IMAGE, {java_literal(row['key'])})")
    else:
        raise SpecError(f"unclassified action row {rid}")
    return parts


def destination_code(row: dict) -> list[str]:
    parts = []
    if row.get("key"):
        parts.append(f".key({java_literal(row['key'])})")
    parts.append(f".title({jt(row['title'])})")
    if row.get("description") is not None:
        parts.append(f".desc({jt(row['description'])})")
    tgt = row["target"]
    if tgt["type"] == "page":
        parts.append(f".page({java_literal(tgt['pageId'])})")
    elif tgt["type"] == "external":
        parts.append(f".external({java_literal(tgt['registryKey'])})")
    else:
        raise SpecError(f"unknown target on {row['id']}")
    return parts


def custom_code(row: dict) -> list[str]:
    parts = [f".key({java_literal(row['key'])})", f".title({jt(row['title'])})"]
    if row.get("description") is not None:
        parts.append(f".desc({jt(row['description'])})")
    ctype = row["custom"]["type"]
    if ctype == "colorPicker":
        parts.append(".custom(Custom.COLOR_PICKER).detail(Detail.COLOR)")
    elif ctype == "imagePicker":
        det = row["detail"]
        parts.append(f".custom(Custom.IMAGE_PICKER).detail(Detail.IMAGE_SET).detailText({jt(det['setText'])}).detailAltText({jt(det['noneText'])})")
    else:
        raise SpecError(f"unknown custom row {row['id']}")
    return parts


def text_code(row: dict) -> list[str]:
    ti = row["textInput"]
    return [f".key({java_literal(row['key'])})", f".title({jt(row['title'])})", f".desc({jt(row['description'])})",
            f".detail(Detail.NUMBER).number({ti['min']}, {ti['max']}, {ti['fallback']}, {java_literal(ti['suffix'])})"]


def info_code(row: dict) -> list[str]:
    role = row["role"]
    parts = [f".role(Role.{ {'spacer': 'SPACER', 'header': 'HEADER', 'caption': 'CAPTION'}[role] })"]
    if row.get("title") is not None:
        parts.append(f".title({jt(row['title'])})")
    if row.get("description") is not None:
        parts.append(f".desc({jt(row['description'])})")
    if role == "header":
        parts.append(".disabled()")
    return parts


def row_code(row: dict, spec: Spec, factory: str = "r", section: int | None = None) -> str:
    kind = row["kind"]
    if kind == "switch":
        parts = switch_code(row)
    elif kind == "picker":
        parts = picker_code(row, spec)
    elif kind == "action":
        parts = action_code(row)
    elif kind == "destination":
        parts = destination_code(row)
    elif kind == "link":
        parts = [f".title({jt(row['title'])})", f".desc({jt(row['description'])})", f".url({java_literal(row['url'])})"]
    elif kind == "custom":
        parts = custom_code(row)
    elif kind == "text":
        parts = text_code(row)
    elif kind == "info":
        parts = info_code(row)
    else:
        raise SpecError(f"unknown kind {kind} on {row['id']}")
    # Pickers, custom and text rows set their own detail; destinations and actions use
    # ROW_DETAILS or the JSON detail (enabled summary / constant).
    if kind in ("destination", "action") and ".detail(" not in "".join(parts):
        parts.append(detail_code(row))
    parts.append(visibility_code(row))
    if section is not None:
        # Visual section of the row on its page (the JSON's derived sections); rows without a
        # key follow their section when installed-tweak filtering hides keyed rows.
        parts.append(f".sec({section})")
    src = row.get("placedAt") or row["source"]
    parts.append(f".src({java_literal(src)})")
    head = f"{factory}({java_literal(row['id'])}, Kind.{kind.upper()})"
    return head + "".join(p for p in parts if p)


# ---------------------------------------------------------------- search resolution

def first_row_titled(page: dict, title: str, skip_info: bool):
    for r in page["rows"]:
        if skip_info and r["kind"] == "info":
            continue
        t = r.get("title")
        if isinstance(t, dict) and t.get("en") == title:
            return r
    return None


def resolve_entry(entry: dict, spec: Spec) -> tuple[list[str], str | None, list]:
    """Return (page chain, row id or None, path texts) for one search entry.

    Fix (search entries that iOS cannot open): iOS walks the English titles and
    stops at the first match, so `[Main]` (Lite Mode), the disabled "Theme Studio"
    header and "Comments header" break 31 entries, and 3 more flash a header row.
    Android resolves each entry to the row that really holds the setting:
      1. a registry key -> the row whose key/registryKey matches;
      2. otherwise walk the path titles skipping info rows; a path that reaches an
         unported destination (Theme Studio: presets, colors, gradient) targets
         that destination's row;
      3. a target title is matched on the final page, skipping info rows.
    """
    root = spec.order[0]
    path_texts = []
    current = root
    stopped_at = None
    for element in entry["path"]:
        row = first_row_titled(spec.pages[current], element, skip_info=True) if stopped_at is None else None
        if row is None:
            if element in PATH_KEYS:
                path_texts.append({"key": PATH_KEYS[element], "en": element})
                continue
            if stopped_at is not None:
                path_texts.append({"key": None, "en": element})
                continue
            raise SpecError(f"search path element {element!r} names no row (entry {entry['order']})")
        path_texts.append(row["title"])
        tgt = row.get("target") or {}
        if tgt.get("type") == "page":
            current = tgt["pageId"]
        elif tgt.get("type") == "external":
            stopped_at = row["id"]
        elif row["kind"] != "picker":
            raise SpecError(f"search path element {element!r} is not a navigation row (entry {entry['order']})")
        else:
            stopped_at = row["id"]

    reg = entry.get("registryKey")
    if reg:
        matches = [rid for rid, r in spec.rows.items() if r.get("key") == reg or r.get("registryKey") == reg]
        matches = [rid for rid in matches if spec.rows[rid]["kind"] != "info"]
        if not matches:
            raise SpecError(f"registry key {reg} has no row (entry {entry['order']})")
        preferred = [rid for rid in matches if spec.row_page[rid] == current]
        rid = (preferred or matches)[0]
        return spec.chain(spec.row_page[rid]), rid, path_texts
    if stopped_at is not None:
        return spec.chain(spec.row_page[stopped_at]), stopped_at, path_texts
    target = entry.get("targetTitle")
    if target:
        row = first_row_titled(spec.pages[current], target, skip_info=True)
        if row is None:
            raise SpecError(f"target {target!r} not found on {current} (entry {entry['order']})")
        return spec.chain(current), row["id"], path_texts
    return spec.chain(current), None, path_texts


def search_code(entry: dict, spec: Spec) -> str:
    chain, rid, path_texts = resolve_entry(entry, spec)
    kind = entry["kind"]
    # Advanced-only rows/pages must only be reachable from advanced-only entries.
    if not entry["advancedOnly"]:
        gates = spec.opener_visibility(chain[-1]) + ([spec.rows[rid].get("visibleWhen")] if rid else [])
        if any(g and g.get("advancedMode") for g in gates):
            raise SpecError(f"entry {entry['order']} reaches an advanced-only row without being advanced-only")
    title_key = entry.get("titleKey")
    reg = entry.get("registryKey")
    if kind == "setting":
        desc_obj = None
        if entry.get("description") is not None:
            desc_obj = {"key": title_key + "Desc", "en": entry["description"]}
        title_obj = {"key": title_key, "en": entry["title"]}
        aliases = [] if reg else list(entry["aliases"])
    elif kind == "literal":
        title_obj = {"key": None, "en": entry["title"]}
        desc_obj = None
        aliases = list(entry["aliases"])
    else:
        if entry["title"] in SEARCH_TITLE_KEYS:
            title_obj = {"key": SEARCH_TITLE_KEYS[entry["title"]], "en": entry["title"]}
        elif kind == "page":
            title_obj = path_texts[-1]
        else:
            title_obj = spec.rows[rid]["title"]
        if title_obj.get("en") != entry["title"]:
            raise SpecError(f"entry {entry['order']} title {entry['title']!r} != row text {title_obj.get('en')!r}")
        d = entry.get("description")
        desc_obj = None if d is None else {"key": SEARCH_DESCRIPTION_KEYS.get(d), "en": d}
        aliases = list(entry["aliases"])
    path = "new Text[] {" + ", ".join(jt(p) for p in path_texts) + "}"
    return (f"e(SearchKind.{kind.upper()}, {jt(title_obj)}, {jt(desc_obj)}, {path}, "
            f"{java_literal(title_key) if title_key else 'null'}, {java_literal(reg) if reg else 'null'}, "
            f"new String[] {{{jstrs(aliases)}}}, {str(entry['advancedOnly']).lower()}, "
            f"new String[] {{{jstrs(chain)}}}, {java_literal(rid) if rid else 'null'}, {java_literal(entry['source'])})")


