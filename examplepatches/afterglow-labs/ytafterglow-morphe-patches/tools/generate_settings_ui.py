SPEC_ROWS: dict = {}


def android_version() -> str:
    try:
        for line in GRADLE_PROPERTIES.read_text(encoding="utf-8").splitlines():
            m = re.match(r"\s*version\s*=\s*(\S+)", line)
            if m:
                return m.group(1)
    except OSError:
        pass
    raise SpecError("gradle.properties has no version")


def render(data: dict) -> str:
    global SPEC_ROWS
    spec = Spec(data)
    SPEC_ROWS = spec.rows
    constants = data["constants"]
    tab_page = spec.pages["page:tabEditor"]
    search_page = spec.pages["page:search"]
    shown = tab_page["sections"][0]
    hidden = tab_page["sections"][1]
    if TAB_EDITOR_FOOTER_FORMAT % 11 != shown["footer"]["en"]:
        raise SpecError("tab editor footer changed in the JSON")

    out = [HEADER, "package app.afterglow.extension.ui;", "",
           "import app.afterglow.extension.ui.SettingsModel.Action;",
           "import app.afterglow.extension.ui.SettingsModel.Custom;",
           "import app.afterglow.extension.ui.SettingsModel.Detail;",
           "import app.afterglow.extension.ui.SettingsModel.Kind;",
           "import app.afterglow.extension.ui.SettingsModel.Option;",
           "import app.afterglow.extension.ui.SettingsModel.Page;",
           "import app.afterglow.extension.ui.SettingsModel.PageType;",
           "import app.afterglow.extension.ui.SettingsModel.Picker;",
           "import app.afterglow.extension.ui.SettingsModel.Role;",
           "import app.afterglow.extension.ui.SettingsModel.Row;",
           "import app.afterglow.extension.ui.SettingsModel.SearchEntry;",
           "import app.afterglow.extension.ui.SettingsModel.SearchKind;",
           "import app.afterglow.extension.ui.SettingsModel.Text;",
           "import app.afterglow.extension.ui.SettingsModel.Visibility;", "",
           "/**",
           " * Every Afterglow settings page, row and search entry, in iOS on-screen order",
           " * (iOS Settings.x via tools/ios-settings-ui.json). Row ids match the JSON.",
           " */",
           "final class SettingsSpec {",
           "    private SettingsSpec() {}", "",
           f"    static final String ROOT = {java_literal(spec.order[0])};",
           f"    static final String SEARCH_PAGE = {java_literal('page:search')};",
           f"    static final String TAB_EDITOR_PAGE = {java_literal('page:tabEditor')};",
           "    /** About summary: the Android package version (gradle.properties), the counterpart of iOS TWEAK_VERSION. */",
           f"    static final String VERSION = {java_literal(android_version())};",
           "    /** Theme Studio detail: iOS shows \"<n> presets\" while no theme is applied. */",
           f"    static final int THEME_PRESET_COUNT = {int(constants['builtInThemePresetCount'])};", ""]

    # tab editor constants
    names = tab_page["tabNames"]
    symbols = tab_page["tabSymbols"]
    tab_ids = tab_page["allTabIds"]
    out.append("    /** Tab ids in iOS ytag_allTabIds order, with their names and SF Symbol names. */")
    out.append(f"    static final String[] TAB_IDS = {{{jstrs(tab_ids)}}};")
    out.append("    static final Text[] TAB_NAMES = {" + ", ".join(jt(names[t]) for t in tab_ids) + "};")
    out.append(f"    static final String[] TAB_SYMBOLS = {{{jstrs(symbols[t] for t in tab_ids)}}};")
    out.append(f"    static final Text TAB_SHOWN_HEADER = {jt(shown['header'])};")
    out.append(f"    static final Text TAB_HIDDEN_HEADER = {jt(hidden['header'])};")
    out.append(f"    static final String TAB_SHOWN_FOOTER_FORMAT = {java_literal(TAB_EDITOR_FOOTER_FORMAT)};")
    out.append(f"    static final Text TAB_HIDDEN_FOOTER = {jt(hidden['footer'])};")
    out.append(f"    static final Text TAB_SHOWN_SUBTITLE = {jt(shown['defaultRows'][0]['subtitle'])};")
    out.append(f"    static final Text TAB_HIDDEN_SUBTITLE = {jt(hidden['defaultRows'][0]['subtitle'])};")
