package gtade.patches

import app.morphe.patcher.patch.PatchException
import java.net.HttpURLConnection
import java.net.URL
import java.net.URLEncoder

/**
 * Builds ProjectPropsDE.dat like the mod repo's mods/projectpropsde/build_props.py, on the device while patching:
 * the Project Props 4 IPLs are downloaded from upstream (pinned commit), so this patches file ships none of them.
 * The game facts come from ProjectPropsDE.stock (model ids, host IPLs with their next free instance index).
 */
internal object ProjectPropsData {
    private const val COMMIT = "0e1f3d50c93275cbd953dd2988da56859cb3d76c"  // user-grinch/Project-Props
    private const val BASE = "https://raw.githubusercontent.com/user-grinch/Project-Props/$COMMIT/" +
        "modloader/Project%20Props%204/Project%20Props%204/"
    private val LOADERS = listOf("Stock Props", "Community Maps")  // the mod's default set, in its loader.txt order
    private val NUM = Regex("""[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?""")
    private const val MAX_INST = 4096  // CFileLoader::LoadScene keeps one IPL's instances in a 4096-entry array
    // Centre-pivot classic models whose DE blueprints lack the downward mesh offset: lower z by the classic min z
    // (new_bushsm, ceasertree01_lvs). Same as build_props.py and the PC build.py.
    private val Z_FIX = mapOf(647 to -1.83, 736 to -11.2)

    fun build(stockTable: String, fetch: (String) -> String = ::download): String {
        val ids = HashSet<Int>()
        val hosts = sortedMapOf<String, Int>()  // host IPL -> next free index
        for (line in stockTable.lines()) {
            val t = line.split(' ')
            when (t[0]) {
                "ids" -> t[1].split(',').forEach { r ->
                    val (a, b) = r.split('-').let { it[0].toInt() to it.last().toInt() }
                    for (i in a..b) ids += i
                }
                "host" -> hosts[t[1]] = t[2].toInt()
            }
        }
        val added = hosts.keys.associateWith { mutableListOf<String>() }

        for (group in LOADERS) {
            val prefix = URLEncoder.encode(group, "UTF-8").replace("+", "%20") + "/"
            for (l in fetch(prefix + "loader.txt").lines()) {
                if (!l.uppercase().startsWith("IPL ")) continue
                val name = l.trim().split(Regex("\\s+"), 2)[1].trim().substringAfterLast('/')
                val insts = instLines(fetch(prefix + "maps/" + URLEncoder.encode(name, "UTF-8").replace("+", "%20")), ids)
                val host = hosts.keys.minBy { hosts[it]!! + added[it]!!.size }  // first of the least filled
                added[host]!! += insts.map { "$it, -1" }
                if (hosts[host]!! + added[host]!!.size > MAX_INST) throw PatchException("$host: more than $MAX_INST instances")
            }
        }

        val out = mutableListOf(
            "; ProjectPropsDE placements, generated by build_props.py from Project Props 4 (github.com/user-grinch/Project-Props).",
            "; 'host <IPL>' starts the lines added to the end of that DE IPL's inst section.",
        )
        for ((rel, lines) in added) if (lines.isNotEmpty()) { out += "host $rel"; out += lines }
        return out.joinToString("\n") + "\n"
    }

    /** The inst entries of a text IPL as 11 columns; LOD is dropped (-1): indices change once merged into a DE IPL. */
    private fun instLines(text: String, ids: Set<Int>): List<String> {
        val out = mutableListOf<String>()
        var sec: String? = null
        for (line in text.lines()) {
            val t = line.substringBefore('#').replace(',', ' ').trim().split(Regex("\\s+")).filter { it.isNotEmpty() }
            if (t.isEmpty()) continue
            when {
                sec == null -> sec = t[0].lowercase()
                t[0].lowercase() == "end" -> sec = null
                sec == "inst" -> {
                    // interior, x y z, qx qy qz qw, lod ("-0.92-1" typos split here)
                    val nums = NUM.findAll(t.drop(2).joinToString(" ")).map { it.value }.toList()
                    val id = if (t[0].all { it in '0'..'9' }) t[0].toInt() else -1
                    if (id !in ids || nums.size < 8) continue
                    val cols = nums.subList(1, 8).toMutableList()
                    Z_FIX[id]?.let { cols[2] = String.format(java.util.Locale.ROOT, "%.4f", cols[2].toDouble() + it) }
                    out += "${t[0]}, ${t[1]}, ${nums[0].toDouble().toInt()}, ${cols.joinToString(", ")}, -1"
                }
            }
        }
        return out
    }

    private fun download(path: String): String {
        val c = URL(BASE + path).openConnection() as HttpURLConnection
        c.connectTimeout = 15000
        c.readTimeout = 30000
        try {
            if (c.responseCode != 200) throw PatchException("Project Props download failed (${c.responseCode}): $path")
            return c.inputStream.use { String(it.readBytes(), Charsets.UTF_8) }
        } catch (e: java.io.IOException) {
            throw PatchException("Project Props needs internet while patching: ${e.message}")
        } finally {
            c.disconnect()
        }
    }
}
