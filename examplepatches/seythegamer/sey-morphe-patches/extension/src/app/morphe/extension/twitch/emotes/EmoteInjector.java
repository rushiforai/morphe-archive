package app.morphe.extension.twitch.emotes;

import android.util.Log;
import android.webkit.WebView;

import java.lang.ref.WeakReference;

/**
 * Injects the third-party emote renderer into the Twitch TV web app.
 *
 * <p>Twitch TV renders chat inside the remote Next.js app, so emotes cannot be
 * patched through native chat models. The extension instead runs a small DOM
 * script in the WebView. The script downloads 7TV, BTTV and FFZ emote sets and
 * replaces matching words in chat messages with CDN images.</p>
 *
 * <p>One shared preference ({@link EmotePrefs}) controls all three providers.
 * The native SEYTTINGS dialog and the script stay in sync through
 * {@link SeyttingsEmoteBridge}.</p>
 */
public final class EmoteInjector {

    private static final String BRIDGE_NAME = "seyttingsEmotes";

    private static final String TAG = SeyttingsEmoteBridge.TAG;

    private static WeakReference<WebView> currentWebView;

    private EmoteInjector() {
    }

    /** Called from the WebView client constructor before the first page load. */
    public static void attach(WebView webView) {
        if (webView == null) {
            return;
        }
        currentWebView = new WeakReference<>(webView);
        EmotePrefs.init(webView.getContext());
        try {
            webView.addJavascriptInterface(new SeyttingsEmoteBridge(), BRIDGE_NAME);
            Log.i(TAG, "bridge attached, enabled=" + EmotePrefs.isEnabled());
        } catch (Throwable ignored) {
            // Never let the injected helper break page loading.
        }
    }

    /** Called from WebViewClient.onPageFinished for every loaded page. */
    public static void inject(WebView webView) {
        if (webView == null) {
            return;
        }
        currentWebView = new WeakReference<>(webView);
        Log.i(TAG, "injecting emote script into " + webView.getUrl());
        evaluate(webView, SCRIPT);
    }

    /** Applies a toggle change immediately without reloading the page. */
    public static void setEnabled(final boolean enabled) {
        evaluateOnCurrent("window.__seyttingsEmotesSetEnabled(" + (enabled ? "true" : "false") + ");");
    }

    /** Re-downloads every provider set and re-renders visible messages. */
    public static void reload() {
        evaluateOnCurrent("window.__seyttingsEmotesReload();");
    }

    private static void evaluateOnCurrent(final String script) {
        WebView webView = currentWebView == null ? null : currentWebView.get();
        if (webView == null) {
            return;
        }
        webView.post(new Runnable() {
            @Override
            public void run() {
                WebView target = currentWebView == null ? null : currentWebView.get();
                if (target != null) {
                    evaluate(target, script);
                }
            }
        });
    }

    private static void evaluate(WebView webView, String script) {
        try {
            webView.evaluateJavascript(script, null);
        } catch (Throwable ignored) {
            // Never let the injected helper break page loading.
        }
    }

    private static final String SCRIPT = String.join("\n",
            "(function () {",
            "  if (window.__seyttingsEmotes) {",
            "    try { window.__seyttingsEmotes.scan(); } catch (e) {}",
            "    return;",
            "  }",
            "",
            "  var TV7_GLOBAL = 'https://7tv.io/v3/emote-sets/global';",
            "  var TV7_USER = 'https://7tv.io/v3/users/twitch/';",
            "  var BTTV_GLOBAL = 'https://api.betterttv.net/3/cached/emotes/global';",
            "  var BTTV_USER = 'https://api.betterttv.net/3/cached/users/twitch/';",
            "  var FFZ_GLOBAL = 'https://api.frankerfacez.com/v1/set/global';",
            "  var FFZ_ROOM = 'https://api.frankerfacez.com/v1/room/';",
            "  var GQL_URL = 'https://gql.twitch.tv/gql';",
            "  var GQL_CLIENT = 'kimne78kx3ncx6brgo4mv6wki5h1ko';",
            "  var GLOBAL_CACHE = 'sey_emotes_global_v1';",
            "  var CHANNEL_CACHE = 'sey_emotes_channel_v1_';",
            "  var ID_CACHE = 'sey_twitch_id_v1_';",
            "  var GLOBAL_TTL = 21600000;",
            "  var CHANNEL_TTL = 1800000;",
            "  var ID_TTL = 604800000;",
            "  var RESERVED = {'settings':1,'directory':1,'search':1,'login':1,'browse':1,",
            "    'friends':1,'inventory':1,'drops':1,'subscriptions':1,'wallet':1,",
            "    'turbo':1,'app-shell':1,'following':1};",
            "",
            "  var state = {",
            "    enabled: true,",
            "    global: {},",
            "    channel: {},",
            "    channelName: null,",
            "    channelToken: 0,",
            "    channelReady: false,",
            "    globalLoading: false,",
            "    globalReady: false,",
            "    lastScan: 0,",
            "    lastCount: -1",
            "  };",
            "",
            "  try {",
            "    if (window.seyttingsEmotes && window.seyttingsEmotes.isEnabled) {",
            "      state.enabled = !!window.seyttingsEmotes.isEnabled();",
            "    }",
            "  } catch (e) {}",
            "",
            "  function log() {",
            "    try {",
            "      console.log.apply(console,",
            "        ['[SEYTTINGS emotes]'].concat(Array.prototype.slice.call(arguments)));",
            "    } catch (e) {}",
            "  }",
            "",
            "  function countKeys(obj) {",
            "    var n = 0;",
            "    for (var k in obj) {",
            "      if (Object.prototype.hasOwnProperty.call(obj, k)) n++;",
            "    }",
            "    return n;",
            "  }",
            "",
            "  function report(message) {",
            "    try {",
            "      if (window.seyttingsEmotes && window.seyttingsEmotes.report) {",
            "        window.seyttingsEmotes.report(String(message));",
            "      }",
            "    } catch (e) {}",
            "  }",
            "",
            "  function getJson(url, options, timeout) {",
            "    return new Promise(function (resolve) {",
            "      var finished = false;",
            "      var controller = window.AbortController ? new AbortController() : null;",
            "      var opts = options || {};",
            "      if (controller) opts.signal = controller.signal;",
            "      var timer = setTimeout(function () {",
            "        if (finished) return;",
            "        finished = true;",
            "        try { if (controller) controller.abort(); } catch (e) {}",
            "        resolve(null);",
            "      }, timeout || 12000);",
            "      try {",
            "        fetch(url, opts).then(function (response) {",
            "          if (!response || !response.ok) return null;",
            "          return response.json();",
            "        }).then(function (json) {",
            "          if (finished) return;",
            "          finished = true;",
            "          clearTimeout(timer);",
            "          resolve(json);",
            "        }).catch(function (error) {",
            "          if (finished) return;",
            "          finished = true;",
            "          clearTimeout(timer);",
            "          log('request failed', url, error && error.message ? error.message : error);",
            "          resolve(null);",
            "        });",
            "      } catch (e) {",
            "        if (!finished) {",
            "          finished = true;",
            "          clearTimeout(timer);",
            "          resolve(null);",
            "        }",
            "      }",
            "    });",
            "  }",
            "",
            "  function readCache(key, ttl) {",
            "    try {",
            "      var raw = window.localStorage.getItem(key);",
            "      if (!raw) return null;",
            "      var parsed = JSON.parse(raw);",
            "      if (!parsed || typeof parsed.t !== 'number') return null;",
            "      if (Date.now() - parsed.t > ttl) return null;",
            "      return parsed.v;",
            "    } catch (e) {",
            "      return null;",
            "    }",
            "  }",
            "",
            "  function writeCache(key, value) {",
            "    try {",
            "      window.localStorage.setItem(key, JSON.stringify({t: Date.now(), v: value}));",
            "    } catch (e) {}",
            "  }",
            "",
            "  function ensureHttps(url) {",
            "    if (!url) return null;",
            "    if (url.indexOf('//') === 0) return 'https:' + url;",
            "    if (url.indexOf('http') === 0) return url;",
            "    return 'https://' + url;",
            "  }",
            "",
            "  function sevenTvFile(host) {",
            "    if (!host || !host.files) return '2x.webp';",
            "    var names = [];",
            "    for (var i = 0; i < host.files.length; i++) {",
            "      var n = host.files[i] && host.files[i].name;",
            "      if (n) names.push(n);",
            "    }",
            "    var order = ['2x.webp', '2x.png', '2x.gif', '1x.webp', '1x.png', '1x.gif'];",
            "    for (var o = 0; o < order.length; o++) {",
            "      if (names.indexOf(order[o]) !== -1) return order[o];",
            "    }",
            "    for (var j = 0; j < names.length; j++) {",
            "      if (names[j].indexOf('.avif') === -1) return names[j];",
            "    }",
            "    return names.length ? names[0] : '2x.webp';",
            "  }",
            "",
            "  function sevenTvUrl(emote) {",
            "    var host = emote && emote.data && emote.data.host;",
            "    var base = host && host.url ? ensureHttps(host.url) : null;",
            "    if (!base && emote && emote.id) base = 'https://cdn.7tv.app/emote/' + emote.id;",
            "    if (!base) return null;",
            "    return base + '/' + sevenTvFile(host);",
            "  }",
            "",
            "  function add7tv(out, emotes) {",
            "    if (!emotes) return;",
            "    for (var i = 0; i < emotes.length; i++) {",
            "      var e = emotes[i];",
            "      if (!e || !e.name) continue;",
            "      var url = sevenTvUrl(e);",
            "      if (url && !out[e.name]) out[e.name] = url;",
            "    }",
            "  }",
            "",
            "  function addBttv(out, emotes) {",
            "    if (!emotes) return;",
            "    for (var i = 0; i < emotes.length; i++) {",
            "      var e = emotes[i];",
            "      if (!e || !e.code || !e.id) continue;",
            "      if (!out[e.code]) {",
            "        out[e.code] = 'https://cdn.betterttv.net/emote/' + e.id + '/3x';",
            "      }",
            "    }",
            "  }",
            "",
            "  function addFfz(out, sets) {",
            "    if (!sets) return;",
            "    for (var key in sets) {",
            "      if (!Object.prototype.hasOwnProperty.call(sets, key)) continue;",
            "      var set = sets[key];",
            "      var emotes = set && set.emoticons;",
            "      if (!emotes) continue;",
            "      for (var i = 0; i < emotes.length; i++) {",
            "        var e = emotes[i];",
            "        if (!e || !e.name || !e.urls) continue;",
            "        var url = ensureHttps(e.urls['4'] || e.urls['2'] || e.urls['1']);",
            "        if (url && !out[e.name]) out[e.name] = url;",
            "      }",
            "    }",
            "  }",
            "",
            "  function loadGlobal(force) {",
            "    if (state.globalLoading) return;",
            "    if (!force) {",
            "      var cached = readCache(GLOBAL_CACHE, GLOBAL_TTL);",
            "      if (cached) {",
            "        state.global = cached;",
            "        state.globalReady = true;",
            "        log('global emotes from cache', countKeys(cached));",
            "        report('global cached ' + countKeys(cached));",
            "        return;",
            "      }",
            "    }",
            "    state.globalLoading = true;",
            "    var out = {};",
            "    getJson(TV7_GLOBAL, null, 15000).then(function (json) {",
            "      if (json && json.emotes) add7tv(out, json.emotes);",
            "      return getJson(BTTV_GLOBAL, null, 15000);",
            "    }).then(function (json) {",
            "      if (json && json.length) addBttv(out, json);",
            "      return getJson(FFZ_GLOBAL, null, 15000);",
            "    }).then(function (json) {",
            "      if (json && json.sets) addFfz(out, json.sets);",
            "      state.global = out;",
            "      state.globalReady = true;",
            "      state.globalLoading = false;",
            "      writeCache(GLOBAL_CACHE, out);",
            "      log('global emotes', countKeys(out));",
            "      report('global loaded ' + countKeys(out));",
            "      scan();",
            "    });",
            "  }",
            "",
            "  function resolveTwitchId(login) {",
            "    var key = ID_CACHE + login;",
            "    var cached = readCache(key, ID_TTL);",
            "    if (cached) return Promise.resolve(cached);",
            "    var body = JSON.stringify([{",
            "      operationName: 'SeyUser',",
            "      variables: {login: login},",
            "      query: 'query SeyUser($login: String!) { user(login: $login) { id } }'",
            "    }]);",
            "    return getJson(GQL_URL, {",
            "      method: 'POST',",
            "      headers: {'Client-ID': GQL_CLIENT, 'Content-Type': 'text/plain'},",
            "      body: body",
            "    }, 10000).then(function (json) {",
            "      var id = json && json[0] && json[0].data && json[0].data.user",
            "        && json[0].data.user.id;",
            "      if (id) writeCache(key, id);",
            "      return id || null;",
            "    });",
            "  }",
            "",
            "  function loadChannel(login, force) {",
            "    if (!login) return;",
            "    if (!force && state.channelName === login && state.channelReady) return;",
            "    state.channelName = login;",
            "    state.channelToken++;",
            "    var token = state.channelToken;",
            "    var cacheKey = CHANNEL_CACHE + login;",
            "    if (!force) {",
            "      var cached = readCache(cacheKey, CHANNEL_TTL);",
            "      if (cached) {",
            "        state.channel = cached;",
            "        state.channelReady = true;",
            "        log('channel emotes from cache', login, countKeys(cached));",
            "        report('channel ' + login + ' cached ' + countKeys(cached));",
            "        return;",
            "      }",
            "    }",
            "    if (force) state.channel = {};",
            "    var idPromise = resolveTwitchId(login);",
            "    var ffzPromise = getJson(FFZ_ROOM + encodeURIComponent(login), null, 12000);",
            "    Promise.all([idPromise, ffzPromise]).then(function (base) {",
            "      var id = base[0];",
            "      var ffz = base[1];",
            "      if (!id && ffz && ffz.room && ffz.room.twitch_id) {",
            "        id = String(ffz.room.twitch_id);",
            "      }",
            "      return Promise.all([",
            "        id ? getJson(TV7_USER + id, null, 20000) : null,",
            "        id ? getJson(BTTV_USER + id, null, 12000) : null,",
            "        ffz",
            "      ]);",
            "    }).then(function (results) {",
            "      if (token !== state.channelToken) return;",
            "      var out = {};",
            "      var seven = results[0];",
            "      if (seven && seven.emote_set && seven.emote_set.emotes) {",
            "        add7tv(out, seven.emote_set.emotes);",
            "      }",
            "      var bttv = results[1];",
            "      if (bttv) {",
            "        addBttv(out, bttv.channelEmotes);",
            "        addBttv(out, bttv.sharedEmotes);",
            "      }",
            "      var ffz = results[2];",
            "      if (ffz && ffz.sets) addFfz(out, ffz.sets);",
            "      if (token !== state.channelToken) return;",
            "      state.channel = out;",
            "      state.channelReady = true;",
            "      writeCache(cacheKey, out);",
            "      log('channel emotes', login, countKeys(out));",
            "      report('channel ' + login + ' loaded ' + countKeys(out));",
            "      scan();",
            "    });",
            "  }",
            "",
            "  function currentChannel() {",
            "    var path = (location.pathname || '/').replace(/^\\/+/, '');",
            "    var name = path.split('/')[0];",
            "    if (!name || RESERVED[name.toLowerCase()]) return null;",
            "    if (!/^[a-zA-Z0-9_]{3,25}$/.test(name)) return null;",
            "    return name.toLowerCase();",
            "  }",
            "",
            "  function chatRoot() {",
            "    var nodes = document.querySelectorAll('aside');",
            "    for (var i = nodes.length - 1; i >= 0; i--) {",
            "      if (nodes[i].querySelector('div[dir=\"auto\"]')) return nodes[i];",
            "    }",
            "    return null;",
            "  }",
            "",
            "  function lookup(code) {",
            "    return state.channel[code] || state.global[code] || null;",
            "  }",
            "",
            "  function userSpan(div) {",
            "    var children = div.children || [];",
            "    for (var i = 0; i < children.length; i++) {",
            "      var c = children[i];",
            "      if (c.tagName === 'SPAN' && /:\\s*$/.test(c.textContent || '')) return c;",
            "    }",
            "    return null;",
            "  }",
            "",
            "  function emotifyText(node) {",
            "    var text = node.nodeValue;",
            "    if (!text || !text.trim()) return;",
            "    var parts = text.split(/(\\s+)/);",
            "    var changed = false;",
            "    var frag = document.createDocumentFragment();",
            "    for (var i = 0; i < parts.length; i++) {",
            "      var part = parts[i];",
            "      if (!part) continue;",
            "      var url = part.trim() ? lookup(part) : null;",
            "      if (url) {",
            "        var img = document.createElement('img');",
            "        img.className = 'seyttings-emote';",
            "        img.src = url;",
            "        img.alt = part;",
            "        img.title = part;",
            "        img.setAttribute('draggable', 'false');",
            "        img.setAttribute('decoding', 'async');",
            "        frag.appendChild(img);",
            "        changed = true;",
            "      } else {",
            "        frag.appendChild(document.createTextNode(part));",
            "      }",
            "    }",
            "    if (changed && node.parentNode) node.parentNode.replaceChild(frag, node);",
            "  }",
            "",
            "  function processDiv(div) {",
            "    if (!div || div.closest('button') || div.closest('[contenteditable=\"true\"]')) return;",
            "    var skip = userSpan(div);",
            "    var walker = document.createTreeWalker(div, NodeFilter.SHOW_TEXT, null, false);",
            "    var nodes = [];",
            "    while (walker.nextNode()) {",
            "      var node = walker.currentNode;",
            "      if (!node.nodeValue || !node.nodeValue.trim()) continue;",
            "      if (skip && skip.contains(node)) continue;",
            "      nodes.push(node);",
            "    }",
            "    for (var i = 0; i < nodes.length; i++) emotifyText(nodes[i]);",
            "  }",
            "",
            "  function scan() {",
            "    if (!state.enabled) return;",
            "    if (!state.globalReady && !state.channelReady) return;",
            "    var root = chatRoot();",
            "    if (!root) return;",
            "    var divs = root.querySelectorAll('div[dir=\"auto\"]');",
            "    for (var i = 0; i < divs.length; i++) processDiv(divs[i]);",
            "    state.lastScan = Date.now();",
            "    var total = document.querySelectorAll('img.seyttings-emote').length;",
            "    if (total !== state.lastCount) {",
            "      state.lastCount = total;",
            "      report('rendered ' + total + ' emote images');",
            "    }",
            "  }",
            "",
            "  function unmotifyAll() {",
            "    var imgs = document.querySelectorAll('img.seyttings-emote');",
            "    for (var i = imgs.length - 1; i >= 0; i--) {",
            "      var img = imgs[i];",
            "      var parent = img.parentNode;",
            "      if (!parent) continue;",
            "      parent.replaceChild(document.createTextNode(img.alt || ''), img);",
            "    }",
            "  }",
            "",
            "  function setEnabled(on) {",
            "    on = !!on;",
            "    state.enabled = on;",
            "    report('toggle ' + on);",
            "    if (!on) {",
            "      unmotifyAll();",
            "      return;",
            "    }",
            "    loadGlobal(false);",
            "    var name = currentChannel();",
            "    if (name) loadChannel(name, false);",
            "    scan();",
            "  }",
            "",
            "  function reload() {",
            "    try {",
            "      var keys = [];",
            "      for (var i = 0; i < localStorage.length; i++) {",
            "        var k = localStorage.key(i);",
            "        if (k && (k === GLOBAL_CACHE",
            "            || k.indexOf(CHANNEL_CACHE) === 0",
            "            || k.indexOf(ID_CACHE) === 0)) {",
            "          keys.push(k);",
            "        }",
            "      }",
            "      for (var j = 0; j < keys.length; j++) localStorage.removeItem(keys[j]);",
            "    } catch (e) {}",
            "    state.global = {};",
            "    state.globalReady = false;",
            "    state.globalLoading = false;",
            "    state.channel = {};",
            "    state.channelReady = false;",
            "    state.channelName = null;",
            "    state.channelToken++;",
            "    unmotifyAll();",
            "    loadGlobal(true);",
            "    var name = currentChannel();",
            "    if (name) loadChannel(name, true);",
            "    scan();",
            "  }",
            "",
            "  function injectStyle() {",
            "    if (document.getElementById('seyttings-emote-style')) return;",
            "    var style = document.createElement('style');",
            "    style.id = 'seyttings-emote-style';",
            "    style.textContent = 'img.seyttings-emote{height:2em;width:auto;max-width:8em;'",
            "      + 'max-height:64px;display:inline-block;vertical-align:middle;margin:0 1px;'",
            "      + 'object-fit:contain}';",
            "    (document.head || document.documentElement).appendChild(style);",
            "  }",
            "",
            "  function tick() {",
            "    if (!state.enabled) return;",
            "    var name = currentChannel();",
            "    if (name !== state.channelName) {",
            "      if (name) {",
            "        loadChannel(name, false);",
            "      } else {",
            "        state.channelName = null;",
            "        state.channel = {};",
            "        state.channelReady = false;",
            "        state.channelToken++;",
            "      }",
            "    }",
            "    scan();",
            "  }",
            "",
            "  window.__seyttingsEmotes = {",
            "    scan: scan,",
            "    setEnabled: setEnabled,",
            "    reload: reload,",
            "    state: state",
            "  };",
            "  window.__seyttingsEmotesSetEnabled = setEnabled;",
            "  window.__seyttingsEmotesReload = reload;",
            "",
            "  injectStyle();",
            "  report('boot enabled=' + state.enabled + ' channel=' + currentChannel());",
            "  if (state.enabled) {",
            "    loadGlobal(false);",
            "    var name = currentChannel();",
            "    if (name) loadChannel(name, false);",
            "    scan();",
            "  }",
            "  window.setInterval(tick, 900);",
            "  window.addEventListener('popstate', tick);",
            "})();");
}
